/*
  答对 / 答错 / 没听清这三摊，是全站说得最勤的话 —— 每一关、每一道题都在说。
  两门课各一份，键完全同构（漏译在两讲的台词表测试里就红了，它们把这三摊
  一起摊进各自的预热单子）。
*/
const 两语 = {
  cn: {
    表扬们: ['答对啦，你真棒！', '太厉害了！', '就是这样，真聪明！', '哇，好棒呀！'],
    鼓励们: ['差一点点，再想一想！', '没关系，再试一次！', '再看仔细一点哦，你可以的！'],
    没听清们: ['我没听清，再说一遍好不好？', '声音再大一点点，我们再来一次！'],
    听好提示: '再想一想，听好提示哦！',
    // 这两句不提「下面的按钮」：亮备选() 对没配 备选 的题是静默 return，承诺一定有钮
    // 就成了骗孩子（票 01）。改叫他再点一次麦克风 —— 有备选的题按钮照样冒出来，没有的题也不落空。
    麦克风没开: '麦克风好像没打开，再点一下麦克风试试吧！',
    耳朵不灵: '我的耳朵今天不太灵，再点一下麦克风，我们再来一次！',
    告诉你: (答们) => `没关系，我告诉你：答案是${答们.join('，或者')}。下次就会啦！`,
    夸并复述: (夸, 词) => `${夸}跟我说：${词}！`,
  },
  en: {
    表扬们: ['That is right, well done!', 'Amazing!', "That's it, so clever!", 'Wow, great job!'],
    鼓励们: ['So close, have another think!', 'Never mind, try again!', 'Look a bit more carefully, you can do it!'],
    没听清们: ['I did not catch that, can you say it again?', 'A little bit louder, and we will try again!'],
    听好提示: 'Have another think, and listen to the hint!',
    麦克风没开: 'The microphone does not seem to be on. Tap the microphone and try again!',
    耳朵不灵: 'My ears are not working well today. Tap the microphone and try again!',
    告诉你: (答们) => `Never mind, I will tell you: the answer is ${答们.join(', or ')}. You will get it next time!`,
    // 「跟我说：X！」这个框子不用冠词 —— 词表里的名词是光杆的（squirrel 不是 a squirrel），
    // 换成 "It is …" 就得为每个词判断该不该加 a/an，而且复述一遍本来就该请孩子跟着念
    夸并复述: (夸, 词) => `${夸} Say it with me: ${词}!`,
  },
};

/**
 * 某一门课的这三摊（外加几句兜底）。缺省当前语言；预热要备**另一门**课时把 `语` 递进来。
 *
 * 只有这一个口子 —— 不另外供一个「当前语言的视图」对象：那种写法看着方便，
 * 却给了 `const { 表扬们 } = 视图` 这种在 import 时就把语言焊死的机会。
 * 每次要说话时现调一次 `问答台词表()`，是这儿唯一正确的用法。
 */
export function 问答台词表(语 = 当前语言()) { return 语 === 'en' ? 两语.en : 两语.cn; }

function 随一句(们) { return 们[Math.floor(Math.random() * 们.length)]; }

let 坞 = null; // {盒, 重听钮, 麦钮, 光环, 备选行}
let 默认挂点 = null; // 借的人可以把坞搬到自己身边（判断关要它排在 ✅❌ 中间），还的时候搬回来

/*
  换主人的那一刻，坞上还挂着上一位装的 onclick —— 孩子这会儿点一下，
  听见的会是上一位主人的回答（票 04 报的那个尾巴：方方正说话时点麦克风，
  冒出一句「先在格子纸上涂六个格子」）。所以换人先把钮擦干净、把坞收下去，
  新主人自己会把它叫醒。
*/
const 调度 = 创建调度({
  on换主人: () => {
    if (!坞) return;
    坞.麦钮.onclick = null;
    管好重听钮(null);
    坞.备选行.innerHTML = '';
    坞状态('睡着');
  },
});

/**
 * 🔊 有活干就露面，没活干就整个拆掉。
 *
 * 从前只把 onclick 设成 null 就算了 —— 按钮还在那儿，还会 hover 变大，
 * 孩子点它什么也不会发生。沙盒里正是这样：它调 听一句() 不带重听，
 * 于是屏幕上常年杵着一个死按钮。这跟「没摄像头就不出现相机按钮」是同一条规矩：
 * **孩子不认字，按钮长什么样就是它全部的说明书 —— 按了没反应，那是骗他。**
 */
function 管好重听钮(重听) {
  if (!坞) return;
  坞.重听钮.onclick = 重听 ? () => { 音效.点一下(); 重听(); } : null;
  坞.重听钮.hidden = !重听;
}

const 默认座 = 调度.默认座();

export function 装麦克风坞(挂点) {
  const 盒 = document.createElement('div');
  盒.className = '麦克风坞 睡着';
  盒.innerHTML = `
    <!-- 🔊 不是 🔁：孩子不认字，图标就是这个钮全部的说明书。
         🔁 读作「重来一遍」，而左下角真有个「重来」—— 长得像那个的东西不能随便摆。
         🔊 是「有声音出来」，跟旁边 🎤「我说话」正好一对。 -->
    <button class="重听钮 热区" type="button" title="再听一遍" aria-label="再听一遍">🔊</button>
    <button class="麦钮" type="button" aria-label="说话"><span class="光环" aria-hidden="true"></span><span class="麦脸" aria-hidden="true">🎤</span></button>
    <div class="备选行"></div>`;
  挂点.appendChild(盒);
  默认挂点 = 挂点;
  坞 = {
    盒,
    重听钮: 盒.querySelector('.重听钮'),
    麦钮: 盒.querySelector('.麦钮'),
    光环: 盒.querySelector('.光环'),
    备选行: 盒.querySelector('.备选行'),
  };

  // 两个钮上的字只给读屏（孩子看见的是 🔊 和 🎤 两个图标），但读屏也得跟着换课。
  // 坞全站只此一个、从不重建，所以订一次就够，不用退订。
  const 摆标签 = () => {
    const 语 = 当前语言();
    const 重听 = 语 === 'en' ? 'Listen again' : '再听一遍';
    const 说话名 = 语 === 'en' ? 'Speak' : '说话';
    坞.重听钮.title = 重听;
    坞.重听钮.setAttribute('aria-label', 重听);
    坞.麦钮.setAttribute('aria-label', 说话名);
  };
  订阅语言(摆标签);
  摆标签();

  return 坞;
}

function 坞状态(名) {
  if (!坞) return;
  坞.盒.classList.remove('睡着', '待命', '录音中', '想想中');
  坞.盒.classList.add(名);
}

export function 收起麦克风() { 坞状态('睡着'); if (坞) 坞.备选行.innerHTML = ''; }

/** 把坞搬到借的人身边（不给挂点就搬回原位）。全站还是这一只坞、这一个大麦钮 */
function 坞归位(挂到) {
  const 去处 = 挂到 ?? 默认挂点;
  if (!坞 || !去处 || 坞.盒.parentElement === 去处) return;
  去处.appendChild(坞.盒);
}

// 前端超时：整条管子彻底死掉（后端/nginx 挂死、弱网 stall、一个字节都不回）时的安全网，
// 不是主 UX 边界（那是后端票06的超时）。ASR 比后端上限略长（20s → 24s）：正常的「慢但能成」
// 先由后端回一个干净的 502（下面的 catch 已接住降级），这一层只兜连 502 都发不出的沉默。
// judge 的 30s 兜不满后端最坏情况：后端是两道闸（每读 15s + 总墙钟 25s），流式慢吐时最坏
// 可叠到 ~40s，届时前端先 abort —— 有意如此：那种极端的慢对孩子和挂死无异，早点掐掉走
// 同一条 catch 降级（亮备选），比让孩子多干等 10 秒强。30s 只保证盖过后端的常规上限 25s。
const ASR超时 = 24_000;
const JUDGE超时 = 30_000;

async function 送后端(路径, 表单, 超时毫秒) {
  const 回 = await 带超时取(路径, { method: 'POST', body: 表单 }, 超时毫秒);
  if (!回.ok) throw new Error(`${路径} ${回.status}`);
  return 回.json();
}

async function 转写(blob, 上下文) {
  const 表单 = new FormData();
  表单.append('file', blob, '答.wav');
  if (上下文) 表单.append('context', 上下文);
  const { text } = await 送后端('/api/asr', 表单, ASR超时);
  return text || '';
}

async function 裁决(blob, 问题, 接受们) {
  const 表单 = new FormData();
  表单.append('file', blob, '答.wav');
  表单.append('question', 问题);
  表单.append('accept', JSON.stringify(接受们));
  const 回 = await 送后端('/api/judge', 表单, JUDGE超时);
  return 回.correct === true ? '对' : '错';
}

