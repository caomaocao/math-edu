/**
 * 听一句的真身。座位不是主人就当场回 `被打断`，一行 DOM 都不碰。
 *
 * @param {ReturnType<ReturnType<typeof 创建调度>['借']>} 座
 * @param {string} [上下文] ASR 热词
 * @param {(() => void)|null} [重听] 🔊 按下去干什么（不给就把 🔊 拆了）
 * @returns {Promise<string|null|typeof 被打断>}
 */
function 听一句核心(座, 上下文, 重听) {
  if (!座.是主人()) return Promise.resolve(被打断);
  if (!坞) throw new Error('先 装麦克风坞() 再听');
  坞.备选行.innerHTML = '';
  管好重听钮(重听);

  return new Promise((好) => {
    let 完了 = false;
    let 我的钮 = null;
    let 注销 = () => {};

    /** 收工：注销、把钮还原、交卷。被打断走的也是这儿（值 = 被打断） */
    const 收工 = (值) => {
      if (完了) return;
      完了 = true;
      注销();
      if (坞 && 坞.麦钮.onclick === 我的钮) 坞.麦钮.onclick = null;
      好(值);
    };

    注销 = 座.登记(收工);

    我的钮 = async () => {
      if (完了 || !座.是主人()) return;
      if (坞.盒.classList.contains('录音中') || 坞.盒.classList.contains('想想中')) return;
      闭嘴();
      音效.开录();
      坞状态('录音中');
      let 答 = null;
      let 开录失败 = false;
      try {
        答 = await 听答案({ 音量回调: (v) => 坞.光环.style.setProperty('--响', v) });
      } catch { 开录失败 = true; } // 麦克风打不开
      音效.收录();
      if (完了) return; // 录着的时候被别人借走了：这一段作废，别再去动坞
      // 麦克风打不开时别只剩一声音效 —— 说一句同问答核心的「麦克风没开」，孩子才知道该再点一下。
      // 「没出声」（答为空但没抛错）仍旧安静收工，交给沙盒循环重新招呼。
      if (开录失败) { 坞状态('待命'); await 说(问答台词表().麦克风没开); 收工(null); return; }
      if (!答) { 坞状态('待命'); 收工(null); return; }
      坞状态('想想中');
      try {
        const 文 = await 转写(答.blob, 上下文 || '');
        if (完了) return;
        坞状态('待命');
        收工(文 || null);
      } catch {
        if (完了) return;
        坞状态('待命');
        收工(null);
      }
    };

    坞.麦钮.onclick = 我的钮;
    坞状态('待命');
  });
}

/**
 * 听一句(上下文) → 转写文本 | null。
 * 给「开车」这类自由指挥的玩法用：只管听和转写，判断交给调用方。
 * 孩子点麦→录→转写；没出声/没听清返回 null。
 *
 * 老签名，一字未变：坞被别的玩法借走时也只是回 null（跟「没听清」一个待遇），
 * 「被打断」这个值只走新的把手那条路。
 */
export function 听一句(上下文) {
  return 听一句核心(默认座, 上下文).then((值) => (是被打断(值) ? null : 值));
}

