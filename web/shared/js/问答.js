/**
 * 问答的真身。
 *
 * @returns {Promise<{全对: boolean}|typeof 被打断>}
 */
async function 问答核心(座, 题) {
  if (!座.是主人()) return 被打断;
  if (!坞) throw new Error('先 装麦克风坞() 再提问');
  let 错次 = 0;
  let 没听清次 = 0;
  let 已裁决 = 0; // 兜底裁决最多 2 次，控成本
  坞.备选行.innerHTML = '';

  const 念题 = () => 说(题.问);
  管好重听钮(念题);

  await 念题();
  if (!座.是主人()) return 被打断; // 念题的工夫坞被借走了

  return new Promise((交卷) => {
    let 收摊 = false;
    let 我的钮 = null;
    let 注销 = () => {};

    const 收工 = (结果) => {
      if (收摊) return; 收摊 = true;
      注销();
      if (坞 && 坞.麦钮.onclick === 我的钮) 坞.麦钮.onclick = null;
      交卷(结果);
    };

    注销 = 座.登记(收工); // 被借走 → 收工(被打断)

    const 过关 = (全对) => {
      if (收摊) return;
      收起麦克风();
      收工({ 全对 });
    };

    /*
      答对了要把**正确的那个词**用当前这门课再说一遍 —— 英文课上答对一次就多听一次
      northeast，词汇是这么潜移默化记住的（spec 里那条「反馈语音始终用当前模式的语言
      复述正确词」）。光说一句「真棒」，这一讲就白上了半截。

      只在**答案恰好是一个词**时复述：判断题（能穿上／穿不上）、多解题复述起来是废话。
      题目自己给了 `答说`（已经挑好语言的词）就用它 —— 有些题的答案是动物名、行列，
      形状各不相同，那种只有出题的人知道怎么念。
    */
    const 复述词 = () => {
      if (题.答说) return 题.答说;
      const 接受们 = 题.接受们 || [];
      if (接受们.length !== 1) return null;
      return 说法(接受们[0], 当前语言(), 题.词表);
    };

    const 答对了 = async () => {
      音效.答对();
      const 话 = 问答台词表();
      const 夸 = 随一句(话.表扬们);
      const 词 = 复述词();
      // 一句话说完，不拆成两次 说() —— 拆了第二句会把第一句掐掉。
      // 怎么把两截接起来（中文不留空格、英文留）由各自那门课自己说了算
      await 说(词 ? 话.夸并复述(夸, 词) : 夸);
      过关(错次 === 0);
    };

    const 答错了 = async () => {
      错次 += 1;
      音效.答错();
      const 话 = 问答台词表();
      if (错次 === 1) {
        await 说(随一句(话.鼓励们));
      } else if (错次 === 2) {
        if (题.提示) await 题.提示();
        else await 说(话.听好提示);
      } else {
        if (题.教) await 题.教();
        // 兜底才走这儿。接受们是**中文规范名**，直接念进英文句子里是夹生的
        // （"the answer is 东北"），所以先翻成本门课的说法；翻不出来的才原样念。
        else {
          const 语 = 当前语言();
          const 答们 = (题.接受们 || []).map((名) => 说法(名, 语, 题.词表) || 名);
          await 说(话.告诉你(答们));
        }
        return 过关(false);
      }
      if (!收摊) 坞状态('待命');
    };

    const 听不清 = async () => {
      没听清次 += 1;
      if (没听清次 >= 2) 亮备选();
      await 说(随一句(问答台词表().没听清们));
      if (!收摊) 坞状态('待命');
    };

    const 评 = (裁定) => {
      if (裁定 === '对') return 答对了();
      if (裁定 === '错') return 答错了();
      return 听不清();
    };

    const 亮备选 = () => {
      if (!题.备选 || 收摊 || 坞.备选行.childElementCount) return;
      for (const { 图, 答 } of 题.备选) {
        const 钮 = document.createElement('button');
        钮.className = '备选钮';
        // 答 就是规范名（方位题的答是「上」「东」这种，查不到实体图，自然回落 图 里的方向牌）
        钮.append(画实体(答, 图, { 类名: '备选图' }));
        // 备选钮曾是全站唯一既不看状态、点后也不禁用的控件：连拍同一个错答三下会把 错次
        // 从 0 顶到 3，冒出「我告诉你答案」还判失败；录音在途误拍还会污染满星。补上和大麦钮
        // （我的钮）同一组守卫。判本身是同步的，「判定在途」= 反馈那一小段：点下即置「想想中」，
        // 这一下里的后续连拍全被下面第二道守卫挡掉；判完由 答对/答错各自把坞恢复到待命
        // （答错第 1、2 次，备选原地留着可再试）或收起（答对、教答案）。「想想中」还顺带和大麦钮
        // 互斥：反馈没说完，点麦克风也不作数。
        钮.onclick = () => {
          if (收摊 || !座.是主人()) return;
          if (坞.盒.classList.contains('录音中') || 坞.盒.classList.contains('想想中')) return;
          音效.点一下();
          坞状态('想想中');
          评(题.判(答));
        };
        坞.备选行.appendChild(钮);
      }
    };

    我的钮 = async () => {
      if (收摊 || !座.是主人()) return;
      if (坞.盒.classList.contains('录音中') || 坞.盒.classList.contains('想想中')) return;
      闭嘴(); // 别让孩子的话和机器的话叠着
      音效.开录();
      坞状态('录音中');
      let 答;
      try {
        答 = await 听答案({ 音量回调: (v) => 坞.光环.style.setProperty('--响', v) });
      } catch {
        if (收摊) return;
        坞状态('待命');
        亮备选();
        await 说(问答台词表().麦克风没开);
        return;
      }
      音效.收录();
      if (收摊) return; // 录着的时候被借走了
      if (!答) { 评('不确定'); return; }
      坞状态('想想中');
      try {
        /*
          没给上下文就拿本题的标准答案当 ASR 热词。走 `热词()` 而不是直接
          `接受们.join('、')`：接受们是**规范名**（永远是中文），照着喂进去，
          英文课上孩子说的 east / upper right 一个都不在热词里，识别率白白掉一截。
          `热词()` 把规范名摊成两语的全部说法 —— 判定本来就两语通吃（判对.js），
          识别这一关也不该先把另一语掐死。
        */
        const 文 = await 转写(答.blob, 题.上下文 || 热词(题.接受们 || [], 题.词表));
        let 裁定 = 题.判(文);
        if (裁定 === '不确定' && 已裁决 < 2 && 题.接受们?.length) {
          已裁决 += 1;
          try { 裁定 = await 裁决(答.blob, 题.问, 题.接受们); } catch { /* 兜底也挂了就当没听清 */ }
        }
        if (收摊) return;
        评(裁定);
      } catch {
        // ASR 接口整个不在（断网/没配 key）：直接亮备选按钮
        if (收摊) return;
        亮备选();
        坞状态('待命');
        await 说(问答台词表().耳朵不灵);
      }
    };

    坞.麦钮.onclick = 我的钮;
    坞状态('待命');
  });
}

/**
 * 问答(题) → {全对}   题目做完才 resolve（教完答案也算做完）。
 * 题：{
 *   问          要念的题目原文（🔊 重听念它）
 *   判(转写)    → '对' | '错' | '不确定'
 *   接受们      标准答案数组（给兜底裁决和「教」的缺省台词用）
 *   上下文      ASR 热词（不给就用 热词(接受们, 词表) 现摊，两语并集）
 *   词表        自定义词表（建词表() 的产出）。只用来把 接受们 摊成 ASR 热词 ——
 *               动物名、水果名这类词不在共享词典里，不给的话热词里只有那个规范名本身
 *   提示()     错第 2 次时叫它（活动里高亮参照物 + 说提示）
 *   教()       错第 3 次时叫它（缺省：念「答案是XX」）
 *   备选       [{图, 答}]  听不清 2 次后亮出的按钮；答 走同一个 判()
 * }
 *
 * 老签名，一字未变：坞被借走时回 {全对: false}（当他这一题没答对），
 * 「被打断」这个值只走新的把手那条路。
 */
export async function 问答(题) {
  const 出 = await 问答核心(默认座, 题);
  return 是被打断(出) ? { 全对: false } : 出;
}

