// 问答 —— 「机器问 → 孩子说 → 判对错」的整条流程，全站共用这一个。
//
// 规矩（票 00-spec 定的）：
//   错 1 次：鼓励再试。错 2 次：给提示。错 3 次：把答案教给他，照样过。
//   听不清 2 次：亮出可以点的备选按钮，嘴巴累了用手也能玩。
//   每道题随时可点 🔊 再听一遍。判不动的送后端 /api/judge 让全模态模型听原始音频。
//
// 坞只有一只，想用它的玩法有好几个 —— 谁是主人、被借走时上一位怎么醒过来，
// 那套规矩单独放在 问答调度.js 里（不碰 DOM，好测）。这个文件管的是另一半：
// 装 onclick、录音、转写、判对。
//
// 两条路，别混：
//   老路 `听一句()` / `问答()`  —— 走一个隐形的「默认主人」，签名和行为跟从前一字不差
//                                （第3讲全在这条路上）。
//   新路 `借麦克风(名)` → 把手  —— 一个玩法端一把，被别人借走时手上的 await
//                                当场解成 `被打断`，循环拿到它就退场。

