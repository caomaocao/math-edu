/**
 * 借走麦克风坞，拿一把「把手」。
 *
 * 借的那一刻上一位当场下台：他手上挂着的那个 `await` 立刻解开成 `被打断`，
 * 循环拿到它就退场（不然沙盒那个 `for(;;) await 听一句()` 会永远挂着，
 * 孩子回到穿衣服喊口令再也没人应 —— 这是票 08 要修的那个静默失效）。
 *
 * 一个玩法的用法长这样：
 * ```js
 * 麦 = 借麦克风('穿衣服');            // 进场
 * for (;;) {
 *   const 文 = await 麦.听一句('穿衣服、脱衣服');
 *   if (是被打断(文)) { if (!麦.是主人()) return; continue; } // 别人借走了就退场
 *   ...
 * }
 * 麦.还回去();                        // 离场
 * ```
 *
 * @param {string} 名 谁借的（调试好认）
 * @param {{挂到?: HTMLElement}} [选项] 挂到 = 把坞搬到自己这块界面里（判断关要它排在 ✅❌ 中间）；
 *   不给就搬回 `装麦克风坞()` 时那个挂点。还回去时自动搬回原位。
 */
export function 借麦克风(名, { 挂到 } = {}) {
  const 座 = 调度.借(名);
  坞归位(挂到);

  return {
    名,
    号: 座.号,
    /** 坞还在我手上吗。循环每转一圈问一句，是假就该退场了 */
    是主人: () => 座.是主人(),
    /** @returns {Promise<string|null|typeof 被打断>} */
    听一句: (上下文, { 重听 } = {}) => 听一句核心(座, 上下文, 重听),
    /** @returns {Promise<{全对: boolean}|typeof 被打断>} */
    问答: (题) => 问答核心(座, 题),
    /**
     * 叫停自己这一次听（换题了、孩子改用手点按钮了）。坞还是我的，
     * 循环拿到 `被打断` 之后一看 `是主人()` 还是真，就接着支耳朵。
     */
    打断自己: () => 座.打断自己(),
    /** 坞的长相：'睡着' | '待命' | '录音中' | '想想中'。不是主人就不许动 */
    状态(名字) { if (座.是主人()) 坞状态(名字); },
    /** 想自己画备选按钮的（图鉴数点点画的是几颗点，不是字）往这儿塞 */
    get 备选行() { return 座.是主人() ? (坞?.备选行 ?? null) : null; },
    /** 坞睡下去（display:none），备选清掉 */
    收起() { if (座.是主人()) 收起麦克风(); },
    /** 还回去：坞睡下、搬回原位、自己挂着的那次听解开。不是主人就只收拾自己 */
    还回去() {
      const 是我的 = 座.还回去();
      if (是我的) 坞归位(默认挂点);
      return 是我的;
    },
  };
}
