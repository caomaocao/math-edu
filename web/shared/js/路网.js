// 路网 —— 闯关「语音开车」的地图逻辑。纯模块：无 DOM、无网络，node 直接测。
//
// 地图是一张格子图，路格连成网。车只能沿路走：
// 喊「往东走」= 沿东一直开到下一个岔口/尽头/目的地才停（小孩喊一声想看车跑一段，
// 一格一格挪要喊到嗓子哑）。

import { 走一步, 位移 } from './罗盘.js';

export function 建路网(行数, 列数, 路格们) {
  const 路 = new Set(路格们.map(({ 行, 列 }) => `${行},${列}`));
  return { 行数, 列数, 路 };
}

export function 是路(网, 格) {
  return 格.行 >= 0 && 格.列 >= 0 && 格.行 < 网.行数 && 格.列 < 网.列数
    && 网.路.has(`${格.行},${格.列}`);
}

// 岔口 = 除了来路之外还有别的走法（或者正好压在目的地上）
function 是岔口(网, 格, 方位) {
  let 出口 = 0;
  for (const 名 of ['北', '南', '东', '西']) {
    if (名 === 反(方位)) continue; // 不算来路
    if (是路(网, 走一步(格, 名))) 出口++;
  }
  return 出口 > 1;
}

function 反(方位) {
  return { 北: '南', 南: '北', 东: '西', 西: '东' }[方位];
}

/**
 * 开车(网, 起点, 方位, 停靠点们?) → {终点, 经过}
 *   沿方位往前开，直到：前方不是路（尽头）、到达岔口、或压上停靠点。
 *   第一步就不是路 → 终点 === 起点，经过为空（前端念「这边没有路呀」）。
 */
export function 开车(网, 起点, 方位, 停靠点们 = []) {
  if (!位移[方位]) throw new Error(`不认识的方位: ${方位}`);
  const 停 = new Set(停靠点们.map(({ 行, 列 }) => `${行},${列}`));
  const 经过 = [];
  let 现 = 起点;
  while (true) {
    const 下 = 走一步(现, 方位);
    if (!是路(网, 下)) break;
    现 = 下;
    经过.push(现);
    if (停.has(`${现.行},${现.列}`)) break;
    if (是岔口(网, 现, 方位)) break;
  }
  return { 终点: 现, 经过 };
}
