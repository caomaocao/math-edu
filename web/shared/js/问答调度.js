// 问答调度 —— 麦克风坞的「借与还」。
//
// 全站只有一只麦克风坞（一个大麦钮，孩子认得它），可是想用它的玩法有五个：
// 沙盒等着孩子喊「穿衣服！」、猜一猜等着孩子喊「能！」、贴水果等着孩子说水果名……
// 谁都不能把它偷偷抢走 —— 抢走的那一刻，上一位主人正 `await` 着的那个 Promise
// 会永远挂在那儿，它的循环再也醒不过来（孩子回到沙盒喊口令没人应，就是这么来的）。
//
// 所以规矩只有三条，全在这个文件里：
//   1. 同一时刻只有一位主人；`借()` 一下就换人，谁也别想「悄悄」用。
//   2. 换人时，上一位挂着的那个 await **当场解开**，解成一个认得出来的值 `被打断`——
//      它的循环拿到这个值就知道该退场了。
//   3. 不是主人就什么都听不到（`登记()` 立刻回 `被打断`），绝不去动坞。
//
// 这个模块不碰 DOM、不认识麦克风、不发一次网络请求 —— 于是 node --test 直接跑得动。
// 真正去装 onclick、录音、转写的那一半在同目录的 问答.js。

/** 「你的麦克风被借走了／被叫停了」。认这一个值就够：`是被打断(x)` */
export const 被打断 = Symbol('麦克风·被打断');

/** @returns {boolean} 这个值是不是「被打断」 */
export function 是被打断(值) {
  return 值 === 被打断;
}

/** 没人开口借的时候，坞归这位隐形主人 —— 老的 `听一句()`／`问答()` 就走它 */
export const 默认主人名 = '默认';

/** 默认主人的号码牌。号是身份：号一样才是同一位主人 */
export const 默认号 = 0;

/**
 * 造一个调度。一个坞一个调度（问答.js 里就那么一个）。
 *
 * @param {{ on换主人?: (上一位: {名: string, 号: number}, 现在: {名: string, 号: number}) => void }} [挂钩]
 *   换主人时叫一声 —— 问答.js 拿它把坞上的 onclick 抹掉，
 *   免得孩子点着点着点到前一位主人的耳朵上。
 */
export function 创建调度({ on换主人 } = {}) {
  let 下一号 = 默认号 + 1;
  let 主人 = { 名: 默认主人名, 号: 默认号 };
  /** 号 → 那一位挂着的 resolve。一位主人同一时刻只挂一个 await */
  const 挂着 = new Map();

  /** 把某一位挂着的那个 await 解开。@returns {boolean} 本来有没有挂着 */
  function 松开(号, 值 = 被打断) {
    const 好 = 挂着.get(号);
    if (!好) return false;
    挂着.delete(号);
    好(值);
    return true;
  }

  function 换人(名, 号) {
    const 上一位 = 主人;
    主人 = { 名, 号 };
    // 整套借还的心脏就是这一行：上一位的 await 当场解开，它的循环才退得出去
    松开(上一位.号);
    on换主人?.({ ...上一位 }, { ...主人 });
  }

  /**
   * 一个「座位」= 一次借的凭证。号是身份牌，换过人以后旧座位永远回不来。
   */
  function 造座(名, 号) {
    return {
      名,
      号,
      是主人: () => 主人.号 === 号,

      /**
       * 挂一个 await 上去。被别人借走、或者自己叫停时，`好(被打断)` 会被调用。
       *
       * @param {(值: any) => void} 好 Promise 的 resolve
       * @returns {() => void} 注销 —— 正常收工时叫一下，免得后来的打断打到已经收工的人身上
       */
      登记(好) {
        if (主人.号 !== 号) {
          // 不是主人就别想听见孩子说话，更不许去抢坞上的 onclick
          好(被打断);
          return () => {};
        }
        松开(号); // 同一位主人开了第二次听：旧的那次先解开，别攒下一串永不醒的 await
        挂着.set(号, 好);
        return () => {
          if (挂着.get(号) === 好) 挂着.delete(号);
        };
      },

      /**
       * 自己叫停自己挂着的那次听（换题了、孩子改用手点按钮了）。
       * 坞还是我的 —— 循环拿到 `被打断` 之后一看 `是主人()` 还是真，就接着支耳朵。
       *
       * @returns {boolean} 本来有没有挂着一次听
       */
      打断自己() {
        if (主人.号 !== 号) return false;
        return 松开(号);
      },

      /**
       * 还回去：坞交还给默认主人，自己挂着的那次听当场解开。
       * 不是主人就只收拾自己（别把别人正用着的坞抢过来关掉）。
       *
       * @returns {boolean} 是不是真的从我手上还回去的
       */
      还回去() {
        if (主人.号 !== 号) {
          松开(号);
          return false;
        }
        换人(默认主人名, 默认号);
        return true;
      },
    };
  }

  const 默认座 = 造座(默认主人名, 默认号);

  return {
    /**
     * 借走坞。上一位当场被打断。
     * @param {string} 名 谁借的（只为看日志和调试好认）
     */
    借(名 = '无名') {
      const 号 = 下一号;
      下一号 += 1;
      换人(名, 号);
      return 造座(名, 号);
    },

    /** 老的 `听一句()`／`问答()` 走的那个隐形座位 */
    默认座: () => 默认座,

    /** 现在坞归谁（调试、测试用） */
    主人们: () => ({ ...主人 }),
  };
}
