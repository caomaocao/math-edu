/** 实体图(规范名) → 图片 URL；没有这张图时给 null（调用方回落 emoji） */
export function 实体图(名) {
  const 素 = 素材名(名);
  return 有图.has(素) ? `${目录}${encodeURIComponent(素)}.webp` : null;
}

/**
 * 图清单(名单) —— 一串规范名 → 去重、滤掉没有图的之后的图片 URL 清单。
 * 「画法」之外这一处也是纯逻辑：不碰 DOM、不碰网络，只把名字换成 URL。
 * 预热（/shared/js/预热.js）拿它决定空闲时段该把哪些图静静拉进浏览器缓存。
 *
 * 走的是跟渲染同一个门 实体图()：素材名归一（小狐狸 / 狐狸 共用一张图，只出一个
 * URL）、有图过滤（查不到的给 null，这儿丢掉）、URL 构造全都复用它，绝不自己拼路径 ——
 * 所以哪天扩展名换了（比如 .png → .webp），这儿一个字都不用动。
 */
export function 图清单(名单) {
  const 清单 = new Set();
  for (const 名 of 名单) {
    const url = 实体图(名);
    if (url) 清单.add(url);
  }
  return [...清单];
}

/**
 * 画法(规范名, 兜底emoji) —— 「这个实体该画成图还是画成字」的纯判断，不碰 DOM。
 * 渲染的决定只在这里做一次，各环节不许自己判断路径是不是以 '/' 开头。
 */
export function 画法(名, 兜底) {
  const url = 实体图(名);
  return url ? { 种: '图', url, 名 } : { 种: '字', 字: 兜底, 名 };
}

/**
 * 画实体(规范名, 兜底emoji, {尺寸, 类名}) → 可直接挂进 DOM 的元素。
 *
 * 尺寸给的是 CSS 像素，应当等于原先那个 emoji 的字号盒——换图不许让东西位移。
 * 素材是 256px，缩到 ≤64px 还有 4 倍 retina 余量。
 * 缺图时还回一个文本节点（emoji 原样），孩子的这一局永远不会因为缺素材而崩。
 */
export function 画实体(名, 兜底, { 尺寸, 类名 } = {}) {
  const 法 = 画法(名, 兜底);
  if (法.种 === '字') return document.createTextNode(法.字);
  const 图 = document.createElement('img');
  图.src = 法.url;
  图.alt = 名;
  图.draggable = false;          // 拖拽由各环节的 pointer 事件管，别让浏览器插一脚
  if (类名) 图.className = 类名;
  if (尺寸) {
    图.style.width = `${尺寸}px`;
    图.style.height = `${尺寸}px`;
  }
  return 图;
}

const SVG命名空间 = 'http://www.w3.org/2000/svg';

/**
 * 画实体SVG(规范名, 兜底emoji, {边, x, y, 类名}) → 可挂进 <svg> 的元素。
 *
 * 跟 画实体() 是同一件事的 SVG 版：关卡地图整张是 SVG，HTML 的 <img> 挂不进去。
 * 判断走同一个 画法()，所以「有图用图、没图用 emoji」全站仍然只有一处说了算。
 * 兜底还回的是 <text>：emoji 在 SVG 里本来就是当字画的，字号取 边。
 */
export function 画实体SVG(名, 兜底, { 边, x = 0, y = 0, 类名 } = {}) {
  const 法 = 画法(名, 兜底);
  if (法.种 === '字') {
    const 字 = document.createElementNS(SVG命名空间, 'text');
    字.setAttribute('font-size', 边);
    字.setAttribute('text-anchor', 'middle');
    // <text> 的 y 是基线，<image> 的 y 是上沿：这里把两者对到同一个视觉中心
    字.setAttribute('x', x + 边 / 2);
    字.setAttribute('y', y + 边 * 0.82);
    if (类名) 字.setAttribute('class', 类名);
    字.textContent = 法.字;
    return 字;
  }
  const 图 = document.createElementNS(SVG命名空间, 'image');
  图.setAttribute('href', 法.url);
  图.setAttribute('width', 边);
  图.setAttribute('height', 边);
  图.setAttribute('x', x);
  图.setAttribute('y', y);
  if (类名) 图.setAttribute('class', 类名);
  return 图;
}
