// 舞台 —— 讲内画面的基准坐标系。
//
// 一讲的几何（格子多大、玩偶落在哪、坞离底边几像素）全按一个恒定的逻辑分辨率画，
// 再把整块画面等比缩放到实际屏幕：手机上看到的就是桌面那一讲按比例缩小的样子，
// 十几个环节一个都不用为小屏重排。为什么走这条路而不是逐环节响应式，见 docs/adr/0004
// （一句话：两套布局必漂移，共享件已经栽过两次）。
//
// 三件事分开，别混：
//   算舞台()   —— 纯算术：给尺寸，算出系数与补边。不碰 DOM，所以能进 node --test。
//   装舞台()   —— 把算出来的数落到元素上，并盯着视口变化重算。
//   舞台系数() —— 谁要把「屏幕上的像素」换算成「舞台里的像素」就问它（装拖 在用）。
//
// 缩放对 position:fixed 是有影响的，而且这次是**帮忙**：transform 过的祖先会成为 fixed
// 后代的包含块，所以讲内那些「固定在角上」的东西（回家钮、麦克风坞、语言开关）跟着舞台
// 一起缩，落在舞台的角上而不是屏幕的角上 —— 这正是要的，它们和内容永远同一套比例。
// 开始遮罩和转屏拦罩故意留在舞台外面：它们要铺满整块屏幕。
//
// 补边不用画：讲内背景（渐变）在 body 上，舞台自己透明，所以缩放剩下的那圈空白
// 露出来的就是同一片背景，看不出边。别给舞台加底色，一加就露出接缝。
//
// 重名警告：第2讲里早就有一个 `#舞台` / `.舞台`，指的是那一讲装三维场景的那个盒子。
// 这儿说的是**基准舞台**（术语见根 CONTEXT.md）—— 整讲共用的那套恒定逻辑坐标系。
// 两者不是一回事，类名也刻意不一样（基准舞台 vs 舞台），改样式前先认准是哪个。
//
// 画布要留神：缩放是 CSS 层面的，canvas 的 clientWidth 量到的仍是**舞台像素**。
// 所以画布类渲染（第2讲的三维、拍照那块布、看见拍的照片）该按
// `devicePixelRatio * 舞台系数()` 定像素密度 —— 只按 devicePixelRatio 的话，
// 桌面上系数大于 1 时是把小图放大，糊给孩子看。矢量的（第3讲那张 SVG 地图）不用管。

/**
 * 给视口和基准尺寸，算出「整块等比缩放」的系数与居中补边。
 *
 * 系数取两轴的**小者**：宁可某一轴留白，也不许内容被切掉一块 —— 被切掉的
 * 可能正是孩子要点的那个格子。不设上限 1：桌面上放大到填满窗口，观感最接近从前
 * 那套流式布局（实体图是 256px 素材，放大到一点五倍也还锐）。
 *
 * 视口量到 0 是真会发生的（后台标签页、布局还没落地就问了一次），
 * 这时候按系数 1 兜着走：算出 scale(0) 的话整讲会在孩子眼前消失。
 */
export function 算舞台({ 视口宽, 视口高, 基准宽, 基准高 }) {
  const 能算 = [视口宽, 视口高, 基准宽, 基准高].every((数) => Number.isFinite(数) && 数 > 0);
  const 系数 = 能算 ? Math.min(视口宽 / 基准宽, 视口高 / 基准高) : 1;
  const 台宽 = 基准宽 * 系数;
  const 台高 = 基准高 * 系数;
  return {
    系数,
    台宽,
    台高,
    左偏: 能算 ? (视口宽 - 台宽) / 2 : 0,
    上偏: 能算 ? (视口高 - 台高) / 2 : 0,
  };
}

/** 屏幕上的一段长度 → 舞台里的长度（比如「手指离件左上角差多少」）。 */
export function 落到舞台的长度(长度, 系数) {
  return 长度 / (系数 > 0 ? 系数 : 1);
}

let 当前 = { 系数: 1, 台宽: 0, 台高: 0, 左偏: 0, 上偏: 0 };
const 听众们 = new Set();

/**
 * 舞台重算了就叫我一声。还回退订函数。
 *
 * 画布类的东西要这个：canvas 的像素密度得按 devicePixelRatio * 系数 定，而系数是会变的
 * （转屏、地址栏收缩、桌面改窗口大小）。没有这个口子的话，只能在「孩子进这一关时」
 * 补一次密度 —— 他正玩着的时候转个屏，那一关的画面就一直糊到他退出去再进来。
 */
export function 订阅舞台(回调) {
  听众们.add(回调);
  return () => 听众们.delete(回调);
}

/**
 * 现在的缩放系数。没装舞台的页面（首页、家长页）返回 1 —— 那些页面本来就没有舞台，
 * 拿到 1 的调用方等于「不换算」，行为和从前一模一样。
 */
export function 舞台系数() { return 当前.系数; }

/**
 * 一个元素的中心，折成**舞台坐标**（相对 台 的原点）。
 *
 * 「量一个格子的外框、把它的中心写进另一个元素的 style.left」是这套坐标系里最容易写错
 * 的一句话，而且写错了不报错 —— 只是东西落在别处。它出现过四回（吸到、开车的摆车、
 * 动物地图的两个端点），四回都是同一行算术，所以收在这儿一份：外框量到的是视觉像素，
 * 除掉系数才是舞台像素。
 *
 * 留神：拿它的结果减元素自己的 offsetWidth/2 时，**offsetWidth 不要再除** ——
 * 那是布局像素，transform 不改它，本来就已经是舞台单位了（见 搭台.js 的 吸到）。
 */
export function 框心到舞台(元素, 台, 系数 = 舞台系数()) {
  const 台框 = 台.getBoundingClientRect();
  const 框 = 元素.getBoundingClientRect();
  return {
    x: 落到舞台的长度(框.left - 台框.left + 框.width / 2, 系数),
    y: 落到舞台的长度(框.top - 台框.top + 框.height / 2, 系数),
  };
}

/**
 * 把 台 挂成基准舞台：定死逻辑尺寸，整块等比缩放居中，视口一变就重算。
 *
 * iOS 上用 visualViewport 而不是 innerHeight：Safari 的 innerHeight 在工具栏收缩的
 * 那几种状态里算的是工具栏底下那块也归你，照它铺会有一条被啃掉的边。
 * （讲内不给滚动，所以工具栏其实不会收缩，量到的高是稳的。）
 */
export function 装舞台(台, { 宽, 高 }) {
  台.classList.add('基准舞台');
  台.style.width = `${宽}px`;
  台.style.height = `${高}px`;

  const 重算 = () => {
    const 看 = window.visualViewport;
    当前 = 算舞台({
      视口宽: 看?.width || window.innerWidth,
      视口高: 看?.height || window.innerHeight,
      基准宽: 宽,
      基准高: 高,
    });
    台.style.left = `${当前.左偏}px`;
    台.style.top = `${当前.上偏}px`;
    台.style.transform = `scale(${当前.系数})`;
    /*
      给 CSS 留的三个口子。系数：隐形热区的外扩量、还有共享件那几个「物理尺寸 ÷ 系数」
      的触靶，都要按它反算。补边：安全区躲让要用（公式在 /shared/css/舞台.css 的
      --躲上/下/左/右，那儿写了为什么不能直接 env()）—— 少了补边这个数，那个公式就没法写。
    */
    const 根 = document.documentElement.style;
    根.setProperty('--舞台系数', String(当前.系数));
    根.setProperty('--舞台左偏', `${当前.左偏}px`);
    根.setProperty('--舞台上偏', `${当前.上偏}px`);
    for (const 回调 of 听众们) {
      // 一个听众炸了不许连累别人，也不许把 resize 变成一次崩溃
      try { 回调(当前); } catch (错) { console.error('舞台听众出错', 错); }
    }
  };

  重算();
  window.addEventListener('resize', 重算);
  window.addEventListener('orientationchange', 重算);
  window.visualViewport?.addEventListener('resize', 重算);

  return { 重算, 系数: () => 当前.系数 };
}
