// 后退 —— 把浏览器的后退手势接进讲内的层级导航。
//
// 讲内切换面板从不跳页（面板常驻、visibility 切换是两讲的地基），于是浏览器
// 根本不知道「进了一关」这回事：孩子在关卡里一个后退手势，整讲直接被退掉，
// 落回全站首页——地图和正玩的关全丢。这个模块把「进一层」压成一条历史记录，
// 后退手势就成了「回上一层」：关里 → 地图 → （浏览器自然的上一页）全站首页，
// 一层一层来。前进手势同理，能顺着原路走回去。
//
// 用法（每讲装一次）：
//   const 层级 = 装后退({ 起点: '地图', 切到: (层) => …切面板，别再碰历史… });
//   进一层：层级.进('货架')   —— 先压历史，再自己去切面板
//   回上层：层级.退()          —— 等价于按浏览器后退；真正的切换发生在 popstate 里
//
// 栈的纪律只有一条：**离开一层的唯一出口是 退()**。程序想自动回上层（比如导读
// 播完自动回地图）也走 退()，不许直接切面板——不然那条压进去的历史成了孤条，
// 下一次后退手势会把孩子传送回一个他已经离开的关。
//
// 刷新/新开标签落进来时，当前历史条目一律归位成起点：新会话永远从这一讲的
// 第一层开始（浏览器的音频解锁本来也要求重新点一次）。

export function 装后退({ 起点, 切到 }) {
  history.replaceState({ 层: 起点 }, '');
  window.addEventListener('popstate', (事) => {
    切到(事.state?.层 ?? 起点);
  });
  return {
    进(层) {
      history.pushState({ 层 }, '');
    },
    退() {
      history.back();
    },
  };
}
