// 罗盘 —— 八大方位的数学。纯模块：无 DOM、无网络，node 直接测。
//
// 地图约定与书一致：上北下南、左西右东。
// 网格坐标 {行, 列}：行往下增（往南），列往右增（往东）。

export const 八方位 = ['北', '东北', '东', '东南', '南', '西南', '西', '西北'];

// 生活方位（屏幕方向） ↔ 地图方位。「上北下南左西右东」的两张脸。
export const 生活对地图 = {
  上: '北', 下: '南', 左: '西', 右: '东',
  右上: '东北', 右下: '东南', 左上: '西北', 左下: '西南',
};
export const 地图对生活 = Object.fromEntries(
  Object.entries(生活对地图).map(([生, 图]) => [图, 生]),
);

// 每个方位在网格上走一步的位移
export const 位移 = {
  北: { 行: -1, 列: 0 }, 南: { 行: 1, 列: 0 }, 东: { 行: 0, 列: 1 }, 西: { 行: 0, 列: -1 },
  东北: { 行: -1, 列: 1 }, 东南: { 行: 1, 列: 1 }, 西北: { 行: -1, 列: -1 }, 西南: { 行: 1, 列: -1 },
};

// 罗盘表盘角度：北=0°，顺时针。给指针急转弯和 SVG 摆盘用。
export const 角度 = { 北: 0, 东北: 45, 东: 90, 东南: 135, 南: 180, 西南: 225, 西: 270, 西北: 315 };

export function 走一步(格, 方位) {
  const 差 = 位移[方位];
  if (!差) throw new Error(`不认识的方位: ${方位}`);
  return { 行: 格.行 + 差.行, 列: 格.列 + 差.列 };
}

export function 走多步(格, 方位, 步数) {
  let 现 = 格;
  for (let i = 0; i < 步数; i++) 现 = 走一步(现, 方位);
  return 现;
}

// 从 甲 看 乙 在什么方位（限对齐或对角线整齐的情况，教具场景都摆整齐）
export function 相对方位(甲, 乙) {
  const d行 = Math.sign(乙.行 - 甲.行);
  const d列 = Math.sign(乙.列 - 甲.列);
  for (const [名, 差] of Object.entries(位移)) {
    if (差.行 === d行 && 差.列 === d列) return 名;
  }
  return null; // 同一格
}
