// 进度 —— localStorage 里那一份带版本号的 JSON。
// 读到版本对不上的旧数据一律当没有；存不下（无痕模式、存满）绝不抛错。
//
// 云端同步接缝（票 07）：这一讲「直写」，没有订阅机制，所以三处挂钩都收在这个文件里——
//   · 每次本地写入（点星 / 写柜）**落盘之后**同步 记脏(存储键)，通知同步引擎该键待推；
//     同步性是硬约束：应用云端合并（收编）也走这条写路径，靠 云同步 的 正在收编 guard
//     把「云来的写」咽掉，不当成孩子的改动回推 —— guard 只在同步窗口里成立。
//   · 重来（清空）不删键，写一份带**新重置戳**的空包（删了就没内容可推、重置传不出去），
//     由 主.js 紧接着 立即推 把这份空包推上云端和别的设备。
//   · 合并(本地, 云端) 纯函数供同步引擎逐键调度用（星并集只增不减 / 柜冲突本地胜 /
//     整包重置戳胜出；有 node --test，见 chapters/03-fangwei/test/合并.test.js）。

import { 记脏 } from './云同步.js';

const 钥匙 = 'fangwei:进度:v1';

/** 这一讲进度在 localStorage 里的键，交给 云同步 的 登记() 用。 */
export const 存储键 = 钥匙;

function 读全部() {
  try {
    const 生 = JSON.parse(localStorage.getItem(钥匙) || 'null');
    if (生 && 生.版本 === 1) return 生; // 带着 重置戳（若有）原样返回，让 点星/写柜 保住它
  } catch { /* 坏数据当没有 */ }
  return { 版本: 1, 星: {}, 柜: {} };
}

function 写全部(数) {
  try {
    localStorage.setItem(钥匙, JSON.stringify(数));
    记脏(存储键); // 落盘成功后才记脏（同步）；收编期间这一记被 云同步 的 正在收编 guard 咽掉
  } catch { /* 存不下照样玩 */ }
}

// ── 云同步用的纯函数（不碰 localStorage / DOM / 网络，进 node --test）─────────────

/** 空的合规整包。重置戳缺省 0 —— 既有无戳的 v1 数据也按这个数参与比戳。 */
function 空包() {
  return { 版本: 1, 星: {}, 柜: {}, 重置戳: 0 };
}

/**
 * 把一份可能为 null / 坏形状 / 版本对不上的 payload 洗成规范整包，或 null（当没有）。
 * 照 读全部 的先例：版本 !== 1 一律当没有，绝不抛。兼容既有无戳的 v1 数据（重置戳 → 0）。
 */
function 净整包(包) {
  if (!包 || typeof 包 !== 'object' || 包.版本 !== 1) return null;
  const 星 = (包.星 && typeof 包.星 === 'object' && !Array.isArray(包.星)) ? 包.星 : {};
  const 柜 = (包.柜 && typeof 包.柜 === 'object' && !Array.isArray(包.柜)) ? 包.柜 : {};
  const 重置戳 = (typeof 包.重置戳 === 'number' && Number.isFinite(包.重置戳)) ? 包.重置戳 : 0;
  return { 版本: 1, 星, 柜, 重置戳 };
}

/**
 * 合并(本地, 云端) —— 云同步逐键调度调的纯函数。两参任一可能为 null（对方没这个键）。
 *
 * 语义（票 07）：
 *   · 先比**整包重置戳**（重来时打的戳）：某侧的戳更新 → 该侧整包胜出，**不做并集**
 *     （这就是解决「重来后星星从另一台设备诈尸」的那一手）。
 *   · 戳相同才按字段合：星取并集，**只增不减**；柜按格取有值的，同格两边都有且不同 → **本地胜**
 *     （正在用的这台是孩子刚玩出来的记忆）。
 *   · 云端版本对不上 / 坏形状 / null → 当没有（不炸），退化成「本地 ∪ 空」原样上云。
 *
 * @returns 合并后的规范整包 { 版本:1, 星, 柜, 重置戳 }。
 */
export function 合并(本地, 云端) {
  const 甲 = 净整包(本地); // 本地
  const 乙 = 净整包(云端); // 云端
  if (!甲 && !乙) return 空包();
  if (!甲) return 乙;
  if (!乙) return 甲;
  // 整包戳先行：谁的戳新谁整包胜出（重来向外传播；旧星不回流）
  if (甲.重置戳 > 乙.重置戳) return 甲;
  if (乙.重置戳 > 甲.重置戳) return 乙;
  // 戳相同才字段合并
  const 星 = { ...乙.星, ...甲.星 }; // 并集，只增不减
  const 柜 = { ...乙.柜, ...甲.柜 }; // 按格取有值的；同格冲突本地(甲)覆盖云端(乙) → 本地胜
  return { 版本: 1, 星, 柜, 重置戳: 甲.重置戳 };
}

// ── 讲内接口 ────────────────────────────────────────────────────────────────

export const 进度 = {
  有星(环节) { return !!读全部().星[环节]; },
  点星(环节) {
    const 数 = 读全部();
    if (数.星[环节]) return false;
    数.星[环节] = true;
    写全部(数);
    return true; // 新点亮才 true，庆祝只放一次
  },
  数星() { return Object.keys(读全部().星).length; },
  读柜(格) { return 读全部().柜[格]; },
  写柜(格, 值) { const 数 = 读全部(); 数.柜[格] = 值; 写全部(数); },
  清空() {
    // 不删键：写一份带**新重置戳**的空包，好让「重来」这件事能被推上云端、传到别的设备
    //（删了 localStorage 就没内容可推，重置永远传不出去）。紧接着由 主.js 立即推 这份空包。
    // 这里不 记脏 —— 重置走 立即推（不等防抖窗口），慢一步孩子可能已经关页面了。
    try {
      localStorage.setItem(钥匙, JSON.stringify({ 版本: 1, 星: {}, 柜: {}, 重置戳: Date.now() }));
    } catch { /* 存不下照样玩 */ }
  },
  落整包(数) {
    // 云同步合并好的整包落回本地（收编用）：走既有写路径 → 记脏，但收编期间被 正在收编 guard 咽掉。
    // 只认版本对的整包（合并() 正常不会产出坏包，这里是防御，坏了就不写、保住本地现状）。
    if (数 && 数.版本 === 1) 写全部(数);
  },
};
