import { test } from 'node:test';
import assert from 'node:assert/strict';
import { 算舞台, 落到舞台的长度 } from '../js/舞台.js';

/*
  基准舞台的那点算术。

  值得单测是因为这几个数错了，症状全是「孩子点不中」而不是报错：系数偏一点，
  拖拽写回去的坐标就整体偏一截；补边算错，屏幕坐标折回舞台时整块串位；
  视口量到 0 的那一刻要是算出 scale(0)，整讲在孩子眼前直接消失。
  这些在浏览器里得靠手感发现，在这儿只是几个断言。
*/

const 手机横屏 = { 视口宽: 912, 视口高: 390 }; // iPhone Air 横屏，扣掉 Chrome 工具栏

test('两轴取小者：矮屏幕由高度说话，内容一点不许切掉', () => {
  const { 系数 } = 算舞台({ ...手机横屏, 基准宽: 1280, 基准高: 620 });
  assert.equal(系数, 390 / 620);
  // 宽度那一轴本来能给到 0.7125，取了小的才装得下
  assert.ok(系数 < 912 / 1280);
});

test('瘦高的窗口由宽度说话', () => {
  const { 系数 } = 算舞台({ 视口宽: 640, 视口高: 1200, 基准宽: 1280, 基准高: 620 });
  assert.equal(系数, 0.5);
});

test('补边把台子摆在正中，两边一样宽', () => {
  const { 系数, 台宽, 台高, 左偏, 上偏 } = 算舞台({ 视口宽: 1000, 视口高: 800, 基准宽: 500, 基准高: 500 });
  assert.equal(系数, 1.6);
  assert.equal(台宽, 800);
  assert.equal(台高, 800);
  assert.equal(左偏, 100); // (1000-800)/2
  assert.equal(上偏, 0); // 高度这一轴正好填满
});

test('尺寸刚好对上就是 1 倍，不缩不放', () => {
  const { 系数, 左偏, 上偏 } = 算舞台({ 视口宽: 1280, 视口高: 620, 基准宽: 1280, 基准高: 620 });
  assert.equal(系数, 1);
  assert.equal(左偏, 0);
  assert.equal(上偏, 0);
});

test('桌面上放大到填满窗口 —— 系数不设上限 1', () => {
  const { 系数 } = 算舞台({ 视口宽: 2560, 视口高: 1240, 基准宽: 1280, 基准高: 620 });
  assert.equal(系数, 2);
});

test('视口量到 0 / NaN 时按 1 倍兜着走，绝不算出 scale(0)', () => {
  for (const 坏 of [
    { 视口宽: 0, 视口高: 0, 基准宽: 1280, 基准高: 620 },
    { 视口宽: 912, 视口高: NaN, 基准宽: 1280, 基准高: 620 },
    { 视口宽: 912, 视口高: 390, 基准宽: 0, 基准高: 620 },
  ]) {
    const { 系数, 左偏, 上偏 } = 算舞台(坏);
    assert.equal(系数, 1, `${JSON.stringify(坏)} 应该兜成 1 倍`);
    assert.equal(左偏, 0);
    assert.equal(上偏, 0);
  }
});

test('缩小时屏幕上量到的一段长度，在舞台里是更长的一段', () => {
  assert.equal(落到舞台的长度(50, 0.5), 100);
  assert.equal(落到舞台的长度(50, 1), 50);
  // 系数坏成 0 也不许除出 Infinity —— 拖拽会把件甩到宇宙外面去
  assert.equal(落到舞台的长度(50, 0), 50);
});
