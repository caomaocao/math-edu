import test from 'node:test';
import assert from 'node:assert/strict';

import {
  创建调度,
  是被打断,
  被打断,
  默认主人名,
  默认号,
} from '../js/问答调度.js';
import { 借麦克风, 听一句, 问答 } from '../js/问答.js';

/**
 * 挂一次「听」在座位上，把它变成一个看得见状态的小对象。
 * 真实世界里这个 Promise 是「孩子点了麦克风、说了一句话」才 resolve 的；
 * 这里我们只关心另一条路：**没人说话，坞就被别人借走了**，它醒不醒得过来。
 */
function 挂一次听(座) {
  const 记 = { 醒了: false, 拿到: undefined };
  const 承诺 = new Promise((好) => 座.登记(好)).then((值) => {
    记.醒了 = true;
    记.拿到 = 值;
    return 值;
  });
  记.承诺 = 承诺;
  return 记;
}

/** 让已经 resolve 的 Promise 把 .then 跑完 */
const 转一圈 = () => new Promise((好) => setTimeout(好, 0));

