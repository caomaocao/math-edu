test('被借走时，上一位挂着的那个 await 当场解开成「被打断」', async () => {
  const 调度 = 创建调度();
  const 沙盒 = 调度.借('沙盒');
  const 这一次听 = 挂一次听(沙盒);

  assert.equal(这一次听.醒了, false, '没人来借之前它就该一直挂着（孩子还没开口）');

  调度.借('猜一猜');
  await 转一圈();

  assert.ok(这一次听.醒了, '坞被借走了，沙盒那个 await 必须醒过来，不然它的循环永远退不出去');
  assert.ok(是被打断(这一次听.拿到));
});

test('「被打断」认得出来，不会跟 null／空串／undefined 混起来', () => {
  assert.ok(是被打断(被打断));
  for (const 别的 of [null, undefined, '', 0, false, '被打断', Symbol('被打断')]) {
    assert.ok(!是被打断(别的), `${String(别的)} 不该被当成「被打断」`);
  }
});

test('不是主人时登记，立刻拿到「被打断」—— 绝不悄悄抢坞', async () => {
  const 调度 = 创建调度();
  const 沙盒 = 调度.借('沙盒');
  调度.借('猜一猜');

  const 迟到的 = 挂一次听(沙盒);
  await 转一圈();
  assert.ok(迟到的.醒了);
  assert.ok(是被打断(迟到的.拿到));

  // 默认主人也一样：被借走以后老的 听一句() 也听不到东西
  const 老路 = 挂一次听(调度.默认座());
  await 转一圈();
  assert.ok(是被打断(老路.拿到));
});

test('同一位主人开第二次听，第一次当场解开（不攒永不醒的 await）', async () => {
  const 调度 = 创建调度();
  const 座 = 调度.借('贴水果');
  const 头一次 = 挂一次听(座);
  const 第二次 = 挂一次听(座);
  await 转一圈();

  assert.ok(是被打断(头一次.拿到));
  assert.equal(第二次.醒了, false, '最新的那一次还挂着等孩子说话');
});

test('自己叫停自己：await 解开，但坞还在自己手上 —— 循环接着支耳朵', async () => {
  const 调度 = 创建调度();
  const 座 = 调度.借('贴水果');
  const 这一次 = 挂一次听(座);

  assert.ok(座.打断自己());
  await 转一圈();

  assert.ok(是被打断(这一次.拿到));
  assert.ok(座.是主人(), '叫停的是「这一次听」，不是「这只麦克风」');
  assert.equal(座.打断自己(), false, '没挂着东西时叫停是空转');
});

test('正常收工注销以后，后来的换人不会再回头打搅它', async () => {
  const 调度 = 创建调度();
  const 座 = 调度.借('沙盒');
  let 叫过几次 = 0;
  const 注销 = 座.登记(() => {
    叫过几次 += 1;
  });
  注销(); // 孩子说完话了，这一次听正常收工

  调度.借('猜一猜');
  await 转一圈();
  assert.equal(叫过几次, 0);
});

