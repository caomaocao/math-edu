test('还回去：坞回到默认主人，自己挂着的那次听也解开', async () => {
  const 调度 = 创建调度();
  const 座 = 调度.借('贴水果');
  const 这一次 = 挂一次听(座);

  assert.ok(座.还回去());
  await 转一圈();

  assert.ok(是被打断(这一次.拿到));
  assert.equal(调度.主人们().名, 默认主人名);
  assert.ok(调度.默认座().是主人(), '还回去以后老的 听一句() 又能用了');
  assert.ok(!座.是主人());
});

test('不是主人时还回去，不许把别人正用着的坞关掉', async () => {
  const 调度 = 创建调度();
  const 贴水果 = 调度.借('贴水果');
  const 判断关 = 调度.借('判断关'); // 切玩法时新的先借、旧的后还，就是这个次序

  const 判断关这一次 = 挂一次听(判断关);
  assert.equal(贴水果.还回去(), false);
  await 转一圈();

  assert.ok(判断关.是主人(), '晚到的那声「还回去」不该把判断关的麦克风收走');
  assert.equal(判断关这一次.醒了, false);
});

test('还回去两次是空转，不会把新主人踢掉', () => {
  const 调度 = 创建调度();
  const 座 = 调度.借('图鉴');
  assert.ok(座.还回去());
  const 后来的 = 调度.借('沙盒');
  assert.equal(座.还回去(), false);
  assert.ok(后来的.是主人());
});

