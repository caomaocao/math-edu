test('把手不是主人时，听一句／问答 立刻回「被打断」，碰都不碰坞', async () => {
  const 早的 = 借麦克风('测试·早');
  const 晚的 = 借麦克风('测试·晚');

  assert.ok(是被打断(await 早的.听一句('随便')));
  assert.ok(是被打断(await 早的.问答({ 问: '不该被念出来', 判: () => '对' })));
  assert.ok(晚的.是主人());

  晚的.还回去();
});

test('老的 听一句()／问答() 被挤下台时，返回值还是老形状（null / {全对:false}）', async () => {
  const 别人 = 借麦克风('测试·别人');

  // 第3讲那两个签名不许变：听一句 → 文本|null，问答 → {全对}
  assert.equal(await 听一句('随便'), null);
  assert.deepEqual(await 问答({ 问: '不该被念出来', 判: () => '对' }), { 全对: false });

  别人.还回去();
});
