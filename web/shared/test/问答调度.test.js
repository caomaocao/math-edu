test('开局坞归默认主人 —— 老的 听一句()／问答() 照旧能用', () => {
  const 调度 = 创建调度();
  assert.deepEqual(调度.主人们(), { 名: 默认主人名, 号: 默认号 });
  assert.ok(调度.默认座().是主人());
});

test('借一下就换人：新的是主人，默认主人当场下台', () => {
  const 调度 = 创建调度();
  const 沙盒 = 调度.借('沙盒');
  assert.ok(沙盒.是主人());
  assert.ok(!调度.默认座().是主人());
  assert.equal(调度.主人们().名, '沙盒');
});

test('后来的把先来的挤下去，先来的再也当不回主人（除非重新借）', () => {
  const 调度 = 创建调度();
  const 沙盒 = 调度.借('沙盒');
  const 猜一猜 = 调度.借('猜一猜');
  assert.ok(!沙盒.是主人());
  assert.ok(猜一猜.是主人());

  const 沙盒二 = 调度.借('沙盒');
  assert.ok(沙盒二.是主人());
  assert.ok(!沙盒.是主人(), '旧把手不会因为同名就复活 —— 号才是身份');
  assert.notEqual(沙盒二.号, 沙盒.号);
});

