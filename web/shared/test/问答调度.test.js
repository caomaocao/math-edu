test('每次换人都叫一声挂钩，上一位和现在都报得出来', () => {
  const 记 = [];
  const 调度 = 创建调度({ on换主人: (上一位, 现在) => 记.push([上一位.名, 现在.名]) });
  const 沙盒 = 调度.借('沙盒');
  调度.借('猜一猜');
  沙盒.还回去(); // 不是主人了：这一下不该换人
  const 图鉴 = 调度.借('图鉴');
  图鉴.还回去();

  assert.deepEqual(记, [
    [默认主人名, '沙盒'],
    ['沙盒', '猜一猜'],
    ['猜一猜', '图鉴'],
    ['图鉴', 默认主人名],
  ]);
});

// ---------------------------------------------------------------------------
// 三个玩法接力：沙盒 → 贴水果 → 沙盒（手工验收里最要紧的那一条路）
// ---------------------------------------------------------------------------

test('沙盒 → 贴水果 → 回沙盒：两条循环各自退场、各自重起，没有谁被卡死', async () => {
  const 调度 = 创建调度();

  // 孩子打开页面：沙盒端着坞等他喊「穿衣服」
  const 沙盒一 = 调度.借('沙盒');
  const 沙盒这一次 = 挂一次听(沙盒一);

  // 切到贴水果：坞借走
  const 贴水果 = 调度.借('贴水果');
  await 转一圈();
  assert.ok(是被打断(沙盒这一次.拿到), '沙盒的循环拿到「被打断」就退场了');

  const 贴水果这一次 = 挂一次听(贴水果);

  // 切回沙盒：贴水果离场还坞，沙盒重新借
  贴水果.还回去();
  const 沙盒二 = 调度.借('沙盒');
  await 转一圈();
  assert.ok(是被打断(贴水果这一次.拿到));
  assert.ok(沙盒二.是主人());

  // 重起的循环挂得上、听得着 —— 「切回穿衣服再喊一声还灵」就是这一条
  const 又一次 = 挂一次听(沙盒二);
  await 转一圈();
  assert.equal(又一次.醒了, false);
});

