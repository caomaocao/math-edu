test('三二一，念出来是汉字 —— 孩子跟着一起数', () => {
  assert.deepEqual(倒数词(3), ['三', '二', '一']);
});

test('倒数几秒都行，一路数到一', () => {
  assert.deepEqual(倒数词(5), ['五', '四', '三', '二', '一']);
  assert.deepEqual(倒数词(1), ['一']);
});

test('倒数 0 秒或者负数：不数，直接拍', () => {
  assert.deepEqual(倒数词(0), []);
  assert.deepEqual(倒数词(-2), []);
  assert.deepEqual(倒数词(2.6), ['二', '一']);
});

// ---------------------------------------------------------------------------
// 提示词 —— 只夸不判的那道闸门在这儿
// ---------------------------------------------------------------------------

test('提示词把模型钉死：具体、正面、一句话、不评价对错', () => {
  const 词 = 夸奖提示词();
  assert.ok(词.length > 20);
  for (const 必须有 of ['一句', '夸', '不']) {
    assert.ok(词.includes(必须有), `提示词里没有「${必须有}」`);
  }
  // 「对错」「好坏」都得在禁令里点名，不能只靠模型自觉
  assert.ok(/对错|不对|错/.test(词), '提示词没禁掉判对错');
});

test('提示词能带上这一讲自己的场景，别的讲复用时换一句就行', () => {
  const 词 = 夸奖提示词({ 场景: '一个小朋友做的正方体纸盒子' });
  assert.ok(词.includes('正方体纸盒子'));
});

// ---------------------------------------------------------------------------
// 收拾夸奖 —— 模型翻车时最后一道闸门
// ---------------------------------------------------------------------------

test('去掉引号和换行，留下干干净净一句话', () => {
  assert.equal(收拾夸奖('“哇，你用了蓝色的纸！”\n'), '哇，你用了蓝色的纸！');
  assert.equal(收拾夸奖('"贴得真整齐！"'), '贴得真整齐！');
});

test('模型憋不住说了对错，整句作废换成保底夸奖', () => {
  for (const 翻车 of [
    '你折得不对哦',
    '这个正方体做错了',
    '有点可惜，边没对齐',
    '不过粘歪了',
    '虽然做得不太好，但是很努力',
    '正确！这就是正方体',
  ]) {
    const 出 = 收拾夸奖(翻车);
    assert.ok(保底夸奖表.includes(出), `「${翻车}」漏过去了，说出来的是「${出}」`);
  }
});

test('好好夸的那句原样留着', () => {
  for (const 好话 of ['哇，你用了蓝色的纸！', '这个小盒子六个面都贴上啦，真棒！', '黄黄的一只，好可爱']) {
    assert.equal(收拾夸奖(好话), 好话);
  }
});

test('空的、模型返回一团空白 → 保底夸奖，绝不冷场', () => {
  for (const 空 of ['', '   ', '\n', null, undefined]) {
    assert.ok(保底夸奖表.includes(收拾夸奖(空)));
  }
});

test('模型话痨了就只留第一句 —— 孩子听不了一段话', () => {
  const 出 = 收拾夸奖('哇，你用了蓝色的纸！我看到六个面都贴好了呢。真的很厉害呀。');
  assert.equal(出, '哇，你用了蓝色的纸！');
});

test('一句都没标点的长篇也砍短，不让方方念一分钟', () => {
  const 出 = 收拾夸奖('哇'.repeat(200));
  assert.ok(出.length <= 40, `太长了：${出.length} 字`);
});

test('保底夸奖每一句自己都过得了「只夸不判」这一关', () => {
  for (const 一句 of 保底夸奖表) {
    assert.equal(收拾夸奖(一句), 一句, `保底夸奖「${一句}」自己都被判成判对错了`);
    assert.ok(一句.length <= 20);
  }
});

test('保底夸奖挑哪一句可以外部指定 —— 好让测试和调试可复现', () => {
  assert.equal(收拾夸奖('', { 挑: () => 0 }), 保底夸奖表[0]);
  assert.equal(收拾夸奖('', { 挑: () => 保底夸奖表.length - 1 }), 保底夸奖表.at(-1));
});

