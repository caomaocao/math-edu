import test from 'node:test';
import assert from 'node:assert/strict';

import {
  倒数词,
  保底夸奖表,
  夸奖提示词,
  收拾夸奖,
  拆出base64,
  缩放尺寸,
  视觉接口,
} from '../js/看见.js';

// ---------------------------------------------------------------------------
// 尺寸换算 —— 一张 1080p 的照片直接发上去要几百 KB，孩子要等；缩到长边 768 就够看
// ---------------------------------------------------------------------------

test('横着的照片按长边缩，比例不变', () => {
  assert.deepEqual(缩放尺寸(1920, 1080, 768), { 宽: 768, 高: 432 });
});

test('竖着的照片也按长边缩', () => {
  assert.deepEqual(缩放尺寸(1080, 1920, 768), { 宽: 432, 高: 768 });
});

test('本来就小的照片不放大 —— 放大只是多传字节，看不出更多东西', () => {
  assert.deepEqual(缩放尺寸(320, 240, 768), { 宽: 320, 高: 240 });
});

test('正方形照片缩完还是正方形', () => {
  assert.deepEqual(缩放尺寸(1000, 1000, 500), { 宽: 500, 高: 500 });
});

test('缩出来永远是至少 1 像素的整数 —— 交给 canvas 的宽高不能是 0 或小数', () => {
  for (const [w, h] of [[1920, 1], [1, 1920], [3, 7], [1000, 3]]) {
    const 出 = 缩放尺寸(w, h, 768);
    assert.ok(Number.isInteger(出.宽) && Number.isInteger(出.高), `${w}×${h} 缩出了小数`);
    assert.ok(出.宽 >= 1 && 出.高 >= 1, `${w}×${h} 缩没了`);
  }
});

test('摄像头还没出画面（0×0）也不许炸，给一个能用的兜底尺寸', () => {
  const 出 = 缩放尺寸(0, 0, 768);
  assert.ok(出.宽 >= 1 && 出.高 >= 1);
});

// ---------------------------------------------------------------------------
// dataURL 拆开
// ---------------------------------------------------------------------------

test('把 canvas 吐出来的 dataURL 拆成 mime + 纯 base64', () => {
  assert.deepEqual(拆出base64('data:image/jpeg;base64,AAECAw=='), {
    mime: 'image/jpeg',
    数据: 'AAECAw==',
  });
});

test('png 也认', () => {
  assert.equal(拆出base64('data:image/png;base64,QUJD').mime, 'image/png');
});

test('裸 base64 当 jpeg 收下 —— 调用方少写一层拼接', () => {
  assert.deepEqual(拆出base64('QUJD'), { mime: 'image/jpeg', 数据: 'QUJD' });
});

test('空的、不是字符串的，拆出空数据而不是抛错', () => {
  for (const 坏 of ['', null, undefined, 42, {}]) {
    assert.deepEqual(拆出base64(坏), { mime: 'image/jpeg', 数据: '' });
  }
});

// ---------------------------------------------------------------------------
// 倒数
