test('记贴水果只动贴水果那一格，判断关和图鉴不受连累', () => {
  const 进度 = 创建进度存储({ 存储: 内存存储() });
  进度.解锁图鉴('一件衣服');
  进度.记判断关('例2-1', true);
  进度.记贴水果('例3-1', true);
  进度.记贴水果('例3-2', false);

  assert.equal(进度.贴水果成绩().答过, 2);
  assert.equal(进度.贴水果成绩().答对, 1);
  assert.equal(第几题(进度.贴水果成绩().作答), 2);

  进度.清贴水果();
  assert.equal(进度.贴水果成绩().答过, 0);
  assert.equal(进度.查判断关('例2-1'), true, '清贴水果不该动到判断关');
  assert.equal(进度.图鉴数(), 1, '清贴水果不该动到图鉴');
});
