import test from 'node:test';
import assert from 'node:assert/strict';

import {
  判贴对了,
  兔兔队,
  凑四个数,
  第几题,
  答对几只,
  贴够了,
  都做完了,
  查贴的,
} from '../src/ui/fruitLevel.js';
import { 数字题库, 对面下标, 贴水果题库, 题库, 题数 } from '../src/data/fruitQuestions.js';
import { 内存存储, 创建进度存储 } from '../src/state/progress.js';

const 号 = (i) => 题库[i].号;
/** 把前 n 题按「对/错」填上 */
const 答了 = (对错们) => Object.fromEntries(对错们.map((对不对, i) => [号(i), 对不对]));
/** 照标准答案把这一题贴齐 */
const 全贴对 = (一题) => new Map(一题.答案.map((一个) => [一个.贴到, 一个.槽位]));

// ---------------------------------------------------------------------------
// 走到第几题
//
// 孩子玩到一半跑掉是常态。回来接着上次那道，而不是从头再来。
// ---------------------------------------------------------------------------

test('一题没贴，从第一题开始', () => {
  assert.equal(第几题({}), 0);
});

test('答过的跳过去，停在第一道没答的', () => {
  assert.equal(第几题(答了([true])), 1);
  assert.equal(第几题(答了([true, false, true])), 3);
});

test('答错也算答过 —— 三次机会用完照样往下走，绝不卡关', () => {
  assert.equal(第几题(答了([false])), 1);
});

test('十三题全答过了就是 null', () => {
  const 全答了 = 答了(new Array(题数).fill(true));
  assert.equal(第几题(全答了), null);
  assert.ok(都做完了(全答了));
  assert.ok(!都做完了(答了([true])));
});

test('不认识的题号当没答过（换了题库的旧进度不许把人送到终点）', () => {
  assert.equal(第几题({ 不存在的题: true }), 0);
});

// ---------------------------------------------------------------------------
// 贴够了没有、贴对了没有
// ---------------------------------------------------------------------------

test('一个没贴：没贴够，也谈不上贴对', () => {
  const 一题 = 贴水果题库[0];
  assert.ok(!贴够了(一题, new Map()));
  assert.ok(!判贴对了(一题, new Map()));
});

test('照标准答案贴齐了：贴够了，而且贴对了', () => {
  for (const 一题 of 贴水果题库) {
    const 贴上的 = 全贴对(一题);
    assert.ok(贴够了(一题, 贴上的), 一题.号);
    assert.ok(判贴对了(一题, 贴上的), 一题.号);
  }
});

test('贴到了邻居格上：贴够了，但没贴对', () => {
  for (const 一题 of 贴水果题库) {
    const 一个 = 一题.答案[0];
    const 贴上的 = 全贴对(一题);
    贴上的.delete(一个.贴到);
    // 挑一个空着的、既不是它自己也不是它对面的格子 —— 那就是它的邻居
    const 邻居 = 一题.格子
      .map((_, i) => i)
      .find(
        (i) =>
          i !== 一个.从 &&
          i !== 一个.贴到 &&
          !贴上的.has(i) &&
          !一题.已贴.some((贴) => 贴.下标 === i),
      );
    贴上的.set(邻居, 一个.槽位);
    assert.ok(贴够了(一题, 贴上的), 一题.号);
    assert.ok(!判贴对了(一题, 贴上的), 一题.号);
  }
});

test('查贴的：说得出每个水果贴在哪一格、对不对', () => {
  const 一题 = 贴水果题库[0];
  const 一个 = 一题.答案[0];
  const 查 = 查贴的(一题, new Map([[一个.从, 一个.槽位]])); // 贴回它自己那一格，肯定不对
  const 这一条 = 查.find((条) => 条.槽位 === 一个.槽位);
  assert.equal(这一条.贴了哪格, 一个.从);
  assert.equal(这一条.对, false);
  assert.equal(这一条.贴到, 对面下标(一题.格子, 一个.从));
});

test('两个水果对调了位置：两条都算错，一条都不许算对', () => {
  const 一题 = 贴水果题库[4]; // 练一练那种三对全贴的
  const [甲, 乙] = 一题.答案;
  const 贴上的 = 全贴对(一题);
  贴上的.set(甲.贴到, 乙.槽位);
  贴上的.set(乙.贴到, 甲.槽位);
  const 查 = 查贴的(一题, 贴上的);
  assert.ok(!判贴对了(一题, 贴上的));
  assert.equal(查.filter((条) => 条.对).length, 1); // 第三对没动，还是对的
});

