// 数字题的备选按钮
// ---------------------------------------------------------------------------

test('凑四个数：里面一定有正确答案，四个都不重样、都在 0 到 9 之间', () => {
  for (const 答 of [0, 1, 3, 5, 8, 9]) {
    const 出 = 凑四个数(答);
    assert.equal(出.length, 4);
    assert.ok(出.includes(答));
    assert.equal(new Set(出).size, 4);
    for (const 数 of 出) assert.ok(数 >= 0 && 数 <= 9);
    assert.deepEqual(出, [...出].sort((a, b) => a - b));
  }
});

test('凑四个数：闯关三真正会问到的那几个数都凑得出来', () => {
  for (const 一题 of 数字题库) {
    for (const 答 of [一题.对面数, 一题.和]) {
      assert.ok(凑四个数(答).includes(答), `${一题.号} 的 ${答}`);
    }
  }
});

