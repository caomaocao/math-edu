import test from 'node:test';
import assert from 'node:assert/strict';

import { 第几题, 判对错, 猫猫队, 都做完了, 答对几只 } from '../src/ui/guessLevel.js';
import { 题库, 题数 } from '../src/data/bookQuestions.js';
import { 内存存储, 创建进度存储 } from '../src/state/progress.js';

const 号 = (i) => 题库[i].号;
/** 把前 n 题按「对/错」填上 */
const 答了 = (对错们) => Object.fromEntries(对错们.map((对不对, i) => [号(i), 对不对]));

// ---------------------------------------------------------------------------
// 走到第几题
//
// 孩子玩到一半跑掉是常态。回来接着上次那题，而不是从头再来 ——
// 从头再来意味着他要把已经答对的重答一遍才够得着新题，猫猫也会看起来没在长。
// ---------------------------------------------------------------------------

test('一题没答，从第一题开始', () => {
  assert.equal(第几题({}), 0);
});

test('答过的跳过去，停在第一道没答的', () => {
  assert.equal(第几题(答了([true])), 1);
  assert.equal(第几题(答了([true, false, true])), 3);
});

test('答错也算答过 —— 不会把孩子卡在同一题上过不去', () => {
  assert.equal(第几题(答了([false])), 1);
});

test('中间漏掉一题，回头补那一题', () => {
  assert.equal(第几题({ [号(0)]: true, [号(2)]: true }), 1);
});

test('17 题全答完就没有下一题了 —— 该放收尾庆祝了', () => {
  assert.equal(第几题(答了(Array(题数).fill(true))), null);
  assert.ok(都做完了(答了(Array(题数).fill(false))), '全答错也算做完');
});

test('没做完就是没做完', () => {
  assert.ok(!都做完了({}));
  assert.ok(!都做完了(答了(Array(题数 - 1).fill(true))));
});

test('存储里混进不认识的题号，不影响进度', () => {
  // 换过题库、或者手改过 localStorage 都可能这样
  assert.equal(第几题({ 张三: true, 李四: false }), 0);
  assert.ok(!都做完了({ 张三: true }));
});

// ---------------------------------------------------------------------------
// 判对错
//
// 「对不对」只跟孩子猜的和引擎算的有关，题库里一栏答案都不查（ADR-0001）。
// ---------------------------------------------------------------------------

test('猜的跟这张衣服折起来的结果一致就算对', () => {
  for (const 一题 of 题库) {
    assert.equal(判对错(一题.能合上, 一题), true, `${一题.号}：猜对了却判成错`);
    assert.equal(判对错(!一题.能合上, 一题), false, `${一题.号}：猜错了却判成对`);
  }
});

// ---------------------------------------------------------------------------
// 猫猫
//
// 一题一只，答对才点亮。答错的要跟没答的分得开 ——
// 全是灰的话孩子看不出自己走到哪儿了。
// ---------------------------------------------------------------------------

test('17 只猫猫，一题一只', () => {
  assert.equal(猫猫队({}).length, 题数);
  assert.equal(题数, 17, '题库变了猫猫也得跟着变 —— 一题一只是这一关的记分规则');
});

test('没答是「没答」，答对是「对」，答错是「错」', () => {
  const 队 = 猫猫队(答了([true, false]));
  assert.deepEqual(队.slice(0, 2), ['对', '错']);
  assert.ok(队.slice(2).every((x) => x === '没答'));
});

test('猫猫只数就是答对的题数', () => {
  assert.equal(答对几只({}), 0);
  assert.equal(答对几只(答了([true, false, true, true])), 3);
  assert.equal(答对几只(答了(Array(题数).fill(true))), 题数);
});

// ---------------------------------------------------------------------------
// 记分落盘 + 重玩
// ---------------------------------------------------------------------------

test('猫猫记分存得住，关了再开还在', () => {
  const 存储 = 内存存储();
  const 一号 = 创建进度存储({ 存储 });
  一号.记判断关(号(0), true);
  一号.记判断关(号(1), false);

  const 二号 = 创建进度存储({ 存储 }); // 模拟刷新页面
  assert.equal(答对几只(二号.判断关成绩().作答), 1);
  assert.equal(第几题(二号.判断关成绩().作答), 2);
});

test('重玩把这一关的作答清干净，图鉴不受连累', () => {
  const 进度 = 创建进度存储({ 存储: 内存存储() });
  进度.解锁图鉴('随便一件衣服');
  for (const 一题 of 题库) 进度.记判断关(一题.号, true);
  assert.ok(都做完了(进度.判断关成绩().作答));

  进度.清判断关();

  assert.deepEqual(进度.判断关成绩().作答, {}, '重玩没清干净');
  assert.equal(第几题(进度.判断关成绩().作答), 0);
  assert.equal(进度.图鉴数(), 1, '重玩把图鉴也清掉了 —— 那是另一个玩法的进度');
});
