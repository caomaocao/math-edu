// ---------------------------------------------------------------------------
// 从上一版搬过来的那几件，得在图鉴里认得出来
//
// 网站改版不能把孩子攒下的衣服清零。搬家这件事本身归 progress.js（那边有自己的测试），
// 这儿盯的是接头：搬过来的那串键，图鉴认不认得。两边的键都是 netFingerprint，
// 哪天有谁改了指纹的算法，孩子的收集册会整本变回问号 —— 这个测试就是那道警报。
// ---------------------------------------------------------------------------

test('v1 攒下的衣服搬进 v2 之后，图鉴照旧点得亮', () => {
  const 存储 = 内存存储();
  const 旧的仨 = 全部衣服().slice(0, 3);
  存储.setItem(
    上一版存储键,
    JSON.stringify({
      版本: 进度版本 - 1,
      图鉴: { 已解锁: 旧的仨.map((一件) => 一件.键) },
      判断关: { 作答: { 0: true, 12: false } }, // 题型变了，这些不该跟过来
      沙盒: { 格子: [{ row: 0, col: 0, 槽位: 0 }] },
    }),
  );

  const 进度 = 创建进度存储({ 存储 });

  assert.deepEqual(
    进度.已解锁图鉴().sort(),
    旧的仨.map((一件) => 一件.键).sort(),
    '旧版收集的三件一件不少',
  );
  assert.equal(进度.图鉴数(), 3);
  for (const 一件 of 旧的仨) {
    assert.equal(进度.是新衣服(一件.键), false, '搬过来的不该再当成没找到');
    assert.ok(认衣服(一件.格子), '搬过来的键得对得上图鉴里的某一格');
  }
  assert.equal(进度.判断关成绩().答过, 0, '判断关不迁：题目从 13 变 17，旧作答对不上号');
  assert.deepEqual(进度.取沙盒(), [], '没画完的那张也不迁，重画一下就有');

  // 搬完立刻落到新键上，下次打开不用再搬一遍
  const 落下来的 = JSON.parse(存储.getItem(存储键));
  assert.equal(落下来的.版本, 进度版本);
  assert.deepEqual(落下来的.图鉴.已解锁.sort(), 旧的仨.map((一件) => 一件.键).sort());
});

test('上一版的数据坏掉、或者根本没有，也不至于让图鉴打不开', () => {
  for (const 坏的 of ['{坏的', 'null', '[]', JSON.stringify({ 版本: 99, 图鉴: { 已解锁: ['x'] } })]) {
    const 存储 = 内存存储();
    存储.setItem(上一版存储键, 坏的);
    const 进度 = 创建进度存储({ 存储 });
    assert.equal(进度.图鉴数(), 0, `${坏的} 该当成没有进度`);
  }
});

