test('每件衣服都摆得进格子纸（4 行 × 5 列）—— 点一下装回沙盒就能接着折', () => {
  for (const 一件 of 全部衣服()) {
    const 高 = Math.max(...一件.格子.map((c) => c.row)) + 1;
    const 宽 = Math.max(...一件.格子.map((c) => c.col)) + 1;
    assert.ok(高 <= 格子纸行数, `${一件.编码} 有 ${高} 行，格子纸只有 ${格子纸行数} 行`);
    assert.ok(宽 <= 格子纸列数, `${一件.编码} 有 ${宽} 列，格子纸只有 ${格子纸列数} 列`);
    assert.ok(高 >= 1 && 宽 >= 1);
  }
});

test('摆正后每行的格数读出来正好是它的编码', () => {
  for (const 一件 of 全部衣服()) {
    const 高 = Math.max(...一件.格子.map((c) => c.row)) + 1;
    const 每行 = [];
    for (let r = 0; r < 高; r++) 每行.push(一件.格子.filter((c) => c.row === r).length);
    assert.equal(每行.join(''), 一件.编码);
  }
});

