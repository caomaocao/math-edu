test('英文台词里一样不许出现数字字符 —— 备选钮上、方方嘴里都不许', () => {
  const 台词 = 数点点台词(分排().map((一排) => 一排.编码), 'en');
  assert.ok(台词.length > 0);
  const 汉字 = /[\p{Script=Han}]/u;
  for (const 一句 of 台词) {
    assert.equal(/[0-9]/.test(一句), false, `英文台词里冒出了数字：${一句}`);
    assert.ok(!汉字.test(一句), `英文台词没翻：${一句}`);
  }
  for (const 一排 of 分排()) {
    assert.ok(台词.includes(整排念完(数数题(一排.编码, 'en'), 'en')), `${一排.编码} 数完那句没备上`);
  }
});

test('英文报数也算数 —— 判定跟现在上的是哪门课无关', () => {
  for (const 说法 of ['four', 'Four!', 'four dots', 'there are four dots', 'one, two, three, four']) {
    assert.equal(判数数(说法, 4), '对', `「${说法}」该算数对`);
  }
  assert.equal(判数数('three', 3), '对');
  assert.equal(抽点数('one two three four'), 4, '一路数过去，报的是最后那个');
  assert.equal(判数数('three', 4), '错', '数错了是错，不是没听清');
  assert.equal(判数数('I see some dots', 4), '不确定', '一个数都没提，那是没听清');
  // 中文课上顺口报了个英文数，一样算数对（两语并集）
  assert.equal(判数数('four', 4), '对');
  assert.equal(判数数('四', 4), '对');
});

test('孩子怎么报数都算数：中文、阿拉伯、带量词、一路数过去', () => {
  for (const 说法 of ['四', '4', '四个', '4个点', '有四个点点', '一、二、三、四', '一共有四个']) {
    assert.equal(判数数(说法, 4), '对', `「${说法}」该算数对`);
  }
  assert.equal(判数数('两个', 2), '对', '「两」也是二');
  assert.equal(判数数('一', 1), '对');
});

test('孩子一路数过去，转写没标点粘成一串，也照样算对', () => {
  // 这是数数玩法里最常见的一句话，ASR 多半不给标点：「一二三四」→「1234」
  assert.equal(判数数('一二三四', 4), '对');
  assert.equal(判数数('1234', 4), '对');
  assert.equal(判数数('一二三', 3), '对');
  assert.equal(判数数('一二', 2), '对');
  assert.equal(抽点数('一二三四'), 4);
  // 数漏了还是错的：数到三就停了，答案就是三
  assert.equal(判数数('一二三', 4), '错');
  // 结巴不算错
  assert.equal(判数数('四四四', 4), '对');
  // 不是从一开始一个一个数的，就按它本来的数读
  assert.equal(抽点数('十'), 10);
  assert.equal(抽点数('二四'), 24);
});

test('数错了是「错」，没听清是「不确定」—— 没听清不该扣孩子的机会', () => {
  assert.equal(判数数('三个', 4), '错');
  assert.equal(判数数('一二三', 4), '错', '数漏了一个也是错，不是没听清');
  for (const 没数 of ['嗯', '这个……', '', null, undefined, '不知道']) {
    assert.equal(判数数(没数, 4), '不确定', `「${没数}」里没有数，该当没听清`);
  }
});

