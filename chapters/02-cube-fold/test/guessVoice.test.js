import test from 'node:test';
import assert from 'node:assert/strict';

import { 听能不能, 猜词表 } from '../src/domain/guessVoice.js';

// ---------------------------------------------------------------------------
// 「能」的各种说法
//
// 五岁孩子不会照着按钮上的字回答。他会说「可以呀」「穿得上」「行」「当然啦」，
// 一样是「能」。判成「没听清」让他重说一遍，等于因为说法不同冤枉了他 ——
// 而他根本不知道自己该换个说法。
// ---------------------------------------------------------------------------

const 能的说法 = [
  '能', '能！', '能。', '能的', '能够', '可以', '可以呀', '可以的',
  '行', '行呀', '会', '是', '是的', '对', '对呀', '当然', '当然可以',
  '没问题', '穿得上', '穿上', '能穿得上', '我觉得能', '应该可以',
];

const 不能的说法 = [
  '不能', '不能！', '不能的', '不能够', '不可以', '不可以的', '不行', '不行呀',
  '不对', '不是', '不是的', '不会', '没法', '不可能',
  '穿不上', '穿不上去', '穿不了', '穿不进', '我觉得不能', '肯定不行',
];

for (const 说法 of 能的说法) {
  test(`「${说法}」算「能」`, () => {
    assert.equal(听能不能(说法), '能');
  });
}

for (const 说法 of 不能的说法) {
  test(`「${说法}」算「不能」`, () => {
    assert.equal(听能不能(说法), '不能');
  });
}

// ---------------------------------------------------------------------------
// 「不」字最要命
//
// 「不能」里含着「能」，「不可以」里含着「可以」，「穿不上」里含着「穿」。
// 词表按长度从长到短吃词，长的先吃掉才不会把否定听成肯定 ——
// 这是整张词表里唯一会把孩子答对的题判成答错的地方。
// ---------------------------------------------------------------------------

test('否定句里的肯定词不算数', () => {
  assert.equal(听能不能('不能穿'), '不能');
  assert.equal(听能不能('不可以呀'), '不能');
  assert.equal(听能不能('这件不行'), '不能');
  // 否定在前、肯定在后：光靠「后说的算数」会把这几句听成「能」
  assert.equal(听能不能('不能穿上'), '不能');
  assert.equal(听能不能('不能穿得上'), '不能');
  assert.equal(听能不能('不可以穿'), '不能');
  assert.equal(听能不能('不会穿上'), '不能');
});

test('肯定句照旧是肯定的 —— 别为了防否定把肯定也堵死了', () => {
  assert.equal(听能不能('能穿得上'), '能');
  assert.equal(听能不能('可以穿上'), '能');
  assert.equal(听能不能('我觉得能穿上'), '能');
});

test('后说的算数 —— 孩子会自我纠正', () => {
  assert.equal(听能不能('能……不对，不能！'), '不能');
  assert.equal(听能不能('不能，啊不是，能！'), '能');
});

// ---------------------------------------------------------------------------
// 听不出来就说听不出来
//
// 猜错了当作答，孩子会被判一次错、猫猫灰掉一只，而他明明什么都没答。
// 拿不准一律 null，交给上层重问一遍。
// ---------------------------------------------------------------------------

test('没答上来的一律 null，绝不替孩子猜', () => {
  for (const 文 of ['', null, undefined, '嗯……', '这个呀', '妈妈', '我要喝水', 'hello']) {
    assert.equal(听能不能(文), null, `「${文}」被当成作答了`);
  }
});

test('「不知道」不算作答', () => {
  // 里头有个「不」，不挡一下就会被当成「不能」—— 孩子说的是「我不知道」，不是答案
  assert.equal(听能不能('不知道'), null);
  assert.equal(听能不能('我不知道呀'), null);
  assert.equal(听能不能('忘了'), null);
});

test('标点和空格不影响判定', () => {
  assert.equal(听能不能('能 ， 能 ！'), '能');
  assert.equal(听能不能('不、能'), '不能');
});

// ---------------------------------------------------------------------------
// 词表本身
// ---------------------------------------------------------------------------

test('只有「能」和「不能」两条，没有第三种答案', () => {
  assert.deepEqual(Object.keys(猜词表), ['能', '不能']);
});

test('两条词表不共用说法 —— 共用一个词就有一半的题必错', () => {
  const 能们 = new Set(猜词表.能);
  for (const 说法 of 猜词表.不能) {
    assert.ok(!能们.has(说法), `「${说法}」同时算能和不能`);
  }
});

// ---------------------------------------------------------------------------
// 英文课
//
// 两语并集（判对.js 那条规矩）：英文课上答「能」算数，中文课上答 yes 也算数。
// 判定跟现在上的是哪门课无关，跟着语言走的只有方方的回话。
// ---------------------------------------------------------------------------

const 英文能的说法 = [
  'Yes!', 'yes', 'Yeah', 'yep', 'yup', 'Sure', 'Of course', 'definitely',
  'It can', 'it fits', 'It will fit', 'it works', 'I think so', 'correct',
];

const 英文不能的说法 = [
  'No!', 'no', 'Nope', 'nah', 'No way',
  'It cannot', "it can't", 'It does not fit', "it doesn't fit",
  "it won't fit", 'wrong', 'impossible',
];

for (const 说法 of 英文能的说法) {
  test(`英文「${说法}」算「能」`, () => {
    assert.equal(听能不能(说法), '能');
  });
}

for (const 说法 of 英文不能的说法) {
  test(`英文「${说法}」算「不能」`, () => {
    assert.equal(听能不能(说法), '不能');
  });
}

test('英文否定句里的肯定词不算数（长词先吃掉短词）', () => {
  // cannot 里含着 can，doesn't fit 里含着 fit —— 词表按长度降序吃词才不会听反
  assert.equal(听能不能('it cannot fit'), '不能');
  assert.equal(听能不能("it can't wear it"), '不能');
  assert.equal(听能不能("it doesn't fit"), '不能');
  assert.equal(听能不能("it won't fit"), '不能');
});

test('英文的自我纠正：后说的算数', () => {
  assert.equal(听能不能('yes, no, no!'), '不能');
  assert.equal(听能不能('no, wait, yes!'), '能');
});

test('藏着答案的英文词不算作答 —— know 里那两个字母不是 no', () => {
  assert.equal(听能不能("I don't know"), null, '这是求助，不是答案');
  assert.equal(听能不能('I know'), null, 'know 里的 no 不是「不能」');
  assert.equal(听能不能('not sure'), null);
  assert.equal(听能不能('no idea'), null);
  assert.equal(听能不能('I forgot'), null);
  assert.equal(听能不能('yesterday'), null, 'yesterday 里的 yes 不是「能」');
});

test('两语并集：中文课上说 yes、英文课上说「能」，都算数', () => {
  assert.equal(听能不能('能'), '能');
  assert.equal(听能不能('yes'), '能');
  assert.equal(听能不能('不能'), '不能');
  assert.equal(听能不能('no'), '不能');
});
