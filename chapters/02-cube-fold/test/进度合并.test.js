import test from 'node:test';
import assert from 'node:assert/strict';

import {
  合并,
  创建进度存储,
  内存存储,
  进度版本,
} from '../src/state/progress.js';

/*
  合并(本地, 云端) 是这一讲交给云同步引擎的纯函数接缝（仿判对 / 罗盘那样进 node --test）。
  跨设备的一句话规矩：星星 / 图鉴只增不减、作答冲突本地胜、沙盒谁新谁赢、
  重置戳更新的一侧整分区胜出。下面把这几条逐条钉死 —— 「一件都不少」是测试保证的，不是祈祷的。
*/

/** 攒一份 v2 payload（合并会先各自洗一遍，所以随便给形状，这儿给规规矩矩的） */
const 包 = ({ 图鉴 = [], 判断关 = {}, 贴水果 = {}, 沙盒 = [], 戳 = {} } = {}) => ({
  版本: 进度版本,
  图鉴: { 已解锁: 图鉴 },
  判断关: { 作答: 判断关 },
  贴水果: { 作答: 贴水果 },
  沙盒: { 格子: 沙盒 },
  戳: { 整包: 0, 判断关: 0, 贴水果: 0, 沙盒: 0, ...戳 },
});

// ---------------------------------------------------------------------------
// 图鉴：并集，只增不减
// ---------------------------------------------------------------------------

test('图鉴取并集，只增不减 —— 两台各攒各的，合起来一件不少', () => {
  const 果 = 合并(包({ 图鉴: ['a', 'b'] }), 包({ 图鉴: ['b', 'c'] }));
  assert.deepEqual(果.图鉴.已解锁, ['a', 'b', 'c'], '本地在前、云端里本地没有的接后面，去重');
});

test('两参任一为 null（对方还没这个键）也不炸', () => {
  assert.deepEqual(合并(包({ 图鉴: ['a'] }), null).图鉴.已解锁, ['a']);
  assert.deepEqual(合并(null, 包({ 图鉴: ['b'] })).图鉴.已解锁, ['b']);
  assert.deepEqual(合并(null, null).图鉴.已解锁, []);
});

test('合并(本地, null) = 本地原样上云（老设备首登：本地 ∪ 空云端）', () => {
  const 本地 = 包({ 图鉴: ['a'], 判断关: { 1: true }, 贴水果: { 2: false } });
  const 果 = 合并(本地, null);
  assert.deepEqual(果.图鉴.已解锁, ['a']);
  assert.deepEqual(果.判断关.作答, { 1: true });
  assert.deepEqual(果.贴水果.作答, { 2: false });
});

// ---------------------------------------------------------------------------
// 作答：逐题取有值的，冲突本地胜
// ---------------------------------------------------------------------------

test('作答逐题取有值的；两边同题都有值且不同 → 本地胜', () => {
  const 本地 = 包({ 判断关: { 1: true, 2: false }, 贴水果: { 5: true } });
  const 云端 = 包({ 判断关: { 1: false, 3: true }, 贴水果: { 5: false, 6: true } });
  const 果 = 合并(本地, 云端);
  assert.deepEqual(
    果.判断关.作答,
    { 1: true, 2: false, 3: true },
    'Q1 冲突本地胜；Q2 只本地有；Q3 只云端有',
  );
  assert.deepEqual(果.贴水果.作答, { 5: true, 6: true }, '贴水果同理：5 冲突本地胜，6 并进云端的');
});

// ---------------------------------------------------------------------------
// 沙盒：谁新谁赢，戳同本地胜
// ---------------------------------------------------------------------------

test('沙盒谁新谁赢；戳相同则本地胜', () => {
  const 本地格 = [{ row: 0, col: 0, 槽位: 0 }];
  const 云端格 = [{ row: 1, col: 1, 槽位: 1 }];

  assert.deepEqual(
    合并(包({ 沙盒: 本地格, 戳: { 沙盒: 100 } }), 包({ 沙盒: 云端格, 戳: { 沙盒: 200 } })).沙盒.格子,
    云端格,
    '云端沙盒戳更新 → 云端赢',
  );
  assert.deepEqual(
    合并(包({ 沙盒: 本地格, 戳: { 沙盒: 300 } }), 包({ 沙盒: 云端格, 戳: { 沙盒: 200 } })).沙盒.格子,
    本地格,
    '本地沙盒戳更新 → 本地赢',
  );
  assert.deepEqual(
    合并(包({ 沙盒: 本地格, 戳: { 沙盒: 200 } }), 包({ 沙盒: 云端格, 戳: { 沙盒: 200 } })).沙盒.格子,
    本地格,
    '戳相同 → 本地胜（那张没画完的以手边这台为准）',
  );
});

// ---------------------------------------------------------------------------
// 分区重置戳：清了判断关的一侧整关胜出，图鉴不受连累
// ---------------------------------------------------------------------------

test('分区重置戳：清了判断关的一侧整关胜出，图鉴照旧并集、不受连累', () => {
  const 本地 = 包({ 图鉴: ['a', 'b'], 判断关: {}, 戳: { 判断关: 200 } }); // 刚清过判断关
  const 云端 = 包({ 图鉴: ['a', 'b', 'c'], 判断关: { 1: true, 2: true, 3: false } });
  const 果 = 合并(本地, 云端);

  assert.deepEqual(果.判断关.作答, {}, '清过的一侧有效戳更大，整关作废，云端旧作答不回流');
  assert.deepEqual(果.图鉴.已解锁, ['a', 'b', 'c'], '图鉴不受判断关分区戳连累，照旧取并集');
  assert.equal(果.戳.判断关, 200, '合并后带上这个分区戳，下一轮同步不丢');
});

test('分区重置戳：反过来云端清了判断关，本地旧作答也不回流', () => {
  const 本地 = 包({ 判断关: { 1: true, 2: true } });
  const 云端 = 包({ 判断关: {}, 戳: { 判断关: 500 } });
  assert.deepEqual(合并(本地, 云端).判断关.作答, {}, '云端有效戳更大，本地旧作答作废');
});

test('分区戳只管自己那格：清了判断关，贴水果照旧逐题合并', () => {
  const 本地 = 包({ 判断关: {}, 贴水果: { 1: true }, 戳: { 判断关: 200 } });
  const 云端 = 包({ 判断关: { 1: true }, 贴水果: { 2: false } });
  const 果 = 合并(本地, 云端);
  assert.deepEqual(果.判断关.作答, {}, '判断关分区戳大 → 整关作废');
  assert.deepEqual(果.贴水果.作答, { 1: true, 2: false }, '贴水果没被判断关的分区戳连累');
});

// ---------------------------------------------------------------------------
// 整包重置戳：重来的一侧胜出，另一侧旧星不回流（防「重来后星星诈尸」）
// ---------------------------------------------------------------------------

test('整包重置戳：重来的一侧整包胜出，另一侧的旧星星不回流', () => {
  const 重来了 = 包({ 戳: { 整包: 1000 } }); // 空 + 整包新戳
  const 旧的 = 包({
    图鉴: ['a', 'b', 'c'],
    判断关: { 1: true },
    贴水果: { 2: true },
    沙盒: [{ row: 0, col: 0, 槽位: 0 }],
  });

  const 甲 = 合并(重来了, 旧的); // 本地重来、云端还是旧的
  assert.deepEqual(甲.图鉴.已解锁, [], '重来侧图鉴清空，云端旧星不回流');
  assert.deepEqual(甲.判断关.作答, {});
  assert.deepEqual(甲.贴水果.作答, {});
  assert.deepEqual(甲.沙盒.格子, []);

  const 乙 = 合并(旧的, 重来了); // 反过来：本地还是旧的、云端已被另一台重来
  assert.deepEqual(乙.图鉴.已解锁, [], '另一台的重来整包戳传过来，本地旧星也压下去 —— 这正是防诈尸');
  assert.deepEqual(乙.判断关.作答, {});
  assert.equal(乙.戳.整包, 1000, '整包戳原样带下去');
});

test('整包戳盖过一切分区：一侧重来，另一侧就算清过某关也整体作废', () => {
  const 重来了 = 包({ 戳: { 整包: 2000 } });
  const 清过判断关 = 包({ 图鉴: ['a', 'b'], 判断关: {}, 戳: { 判断关: 1500 } });
  assert.deepEqual(合并(重来了, 清过判断关).图鉴.已解锁, [], '重来侧整包戳 2000 盖过对方图鉴');
});

test('合并后每个戳取两侧较大值，最近一次重置的记忆不丢', () => {
  const 甲 = 包({ 戳: { 整包: 10, 判断关: 50, 贴水果: 0, 沙盒: 30 } });
  const 乙 = 包({ 戳: { 整包: 20, 判断关: 5, 贴水果: 40, 沙盒: 0 } });
  assert.deepEqual(合并(甲, 乙).戳, { 整包: 20, 判断关: 50, 贴水果: 40, 沙盒: 30 });
});

// ---------------------------------------------------------------------------
// 脏数据：云端可能是旧版本 / 坏形状，先洗一遍再合并，绝不炸
// ---------------------------------------------------------------------------

test('云端是旧版本：先迁移（只救图鉴）再并进来', () => {
  const 本地 = 包({ 图鉴: ['a'] });
  const 旧版 = { 版本: 进度版本 - 1, 图鉴: { 已解锁: ['b'] }, 判断关: { 作答: { 1: true } } };
  const 果 = 合并(本地, 旧版);
  assert.deepEqual(果.图鉴.已解锁.sort(), ['a', 'b'], '旧版云端的图鉴迁移后并进来');
  assert.deepEqual(果.判断关.作答, {}, '旧版的判断关作答不迁（题号对不上，和开站搬家一个规矩）');
});

test('云端是坏形状 / 缺字段 / 乱七八糟，都当空处理，本地原样留着', () => {
  const 本地 = 包({ 图鉴: ['a'] });
  for (const 坏 of [undefined, 42, 'hi', [], {}, { 版本: 999 }, { 图鉴: 7 }, { 戳: 'x' }]) {
    assert.doesNotThrow(() => 合并(本地, 坏), `${JSON.stringify(坏)} 不该抛`);
    const 果 = 合并(本地, 坏);
    assert.deepEqual(果.图鉴.已解锁, ['a'], '坏的云端当空，本地原样');
    assert.equal(果.版本, 进度版本);
  }
});

test('本地坏、云端好也不炸：以云端为准', () => {
  assert.deepEqual(合并('坏的本地', 包({ 图鉴: ['z'] })).图鉴.已解锁, ['z']);
  assert.deepEqual(合并(null, null).版本, 进度版本);
});

test('合并的产物永远是合法整包（版本对、四格 + 四个戳齐）', () => {
  const 果 = 合并(包({ 图鉴: ['a'] }), 包({ 判断关: { 1: true } }));
  assert.equal(果.版本, 进度版本);
  assert.ok(Array.isArray(果.图鉴.已解锁));
  assert.ok(果.判断关.作答 && typeof 果.判断关.作答 === 'object');
  assert.ok(果.贴水果.作答 && typeof 果.贴水果.作答 === 'object');
  assert.ok(Array.isArray(果.沙盒.格子));
  for (const 键 of ['整包', '判断关', '贴水果', '沙盒']) {
    assert.ok(Number.isInteger(果.戳[键]), `戳.${键} 得是整数`);
  }
});

// ---------------------------------------------------------------------------
// 存储那头：清 / 重来 / 存沙盒 真会打对应的戳（合并靠这些戳判胜负）
// ---------------------------------------------------------------------------

test('清判断关只打判断关的分区戳，别的分区戳一动不动', () => {
  const 进度 = 创建进度存储({ 存储: 内存存储() });
  进度.记判断关('1', true);
  进度.清判断关();
  const 读回 = 进度.读();
  assert.ok(读回.戳.判断关 > 0, '清判断关打了自己的分区戳');
  assert.equal(读回.戳.整包, 0, '不动整包戳');
  assert.equal(读回.戳.贴水果, 0, '不连累贴水果');
  assert.equal(读回.戳.沙盒, 0, '不连累沙盒');
});

test('清贴水果打贴水果戳、存沙盒打沙盒戳', () => {
  const 进度 = 创建进度存储({ 存储: 内存存储() });
  进度.清贴水果();
  assert.ok(进度.读().戳.贴水果 > 0, '清贴水果打贴水果分区戳');
  assert.equal(进度.读().戳.判断关, 0, '不连累判断关');

  进度.存沙盒([{ row: 0, col: 0, 槽位: 0 }]);
  assert.ok(进度.读().戳.沙盒 > 0, '每次存沙盒盖新戳');
});

test('收编：整包换掉内存态、四格 + 戳都以合并结果为准', () => {
  const 进度 = 创建进度存储({ 存储: 内存存储() });
  进度.解锁图鉴('a');
  进度.收编(合并(进度.读(), 包({ 图鉴: ['b'], 判断关: { 1: true } })));
  assert.deepEqual(进度.已解锁图鉴().sort(), ['a', 'b'], '收编把云端并进来的星星落进内存态');
  assert.equal(进度.查判断关('1'), true, '云端的作答也收编进来了');
});
