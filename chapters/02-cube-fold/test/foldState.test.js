import test from 'node:test';
import assert from 'node:assert/strict';

import { 创建折叠状态, 折到底 } from '../src/domain/foldState.js';

/**
 * 逐面折叠的状态机。
 *
 * 前代只有一个整体折叠度，滑块从左拖到右、六个面一起收拢。这一版每条折痕
 * 各有各的折叠度：孩子点一个格子，就只有那一片弹起来。折痕树的父子关系还在
 * （折父格子，子孙跟着走），那是 FoldedNet 的事；这里只管每条折痕现在折到哪、
 * 要折到哪，以及怎么从现在走到要去的地方。
 *
 * 纯的：不碰 three.js，不碰 DOM，时间由调用方喂进来。
 */

/** 一张十字衣服：根在中间，5 条折痕 */
const 六格 = { 格子数: 6, 根下标: 0 };

const 推到停 = (状态, 最多 = 600) => {
  let 步 = 0;
  while (状态.推进(1 / 60) && 步 < 最多) 步 += 1;
  return 步;
};

test('根格子折不动 —— 它是衣服贴着地的那一片，没有折痕可转', () => {
  const 状态 = 创建折叠状态(六格);
  assert.equal(状态.能折(0), false, '根就是不响应的那一片');
  assert.equal(状态.能折(1), true);
  assert.equal(状态.切(0), null, '点根格子什么也不该发生');
  assert.equal(状态.当前(0), 0);
});

test('范围外的下标当没有，不许把状态机搞崩', () => {
  const 状态 = 创建折叠状态(六格);
  assert.equal(状态.能折(-1), false);
  assert.equal(状态.能折(6), false);
  assert.equal(状态.能折(1.5), false);
  assert.equal(状态.切(99), null);
  assert.equal(状态.当前(99), 0);
});

test('点一下折起来，再点一下放回去', () => {
  const 状态 = 创建折叠状态(六格);

  assert.equal(状态.切(2), 1, '摊着的点一下就该往折起来走');
  推到停(状态);
  assert.equal(状态.当前(2), 1);

  assert.equal(状态.切(2), 0, '折着的点一下就该放回去');
  推到停(状态);
  assert.equal(状态.当前(2), 0);
});

test('折到一半时点一下：过了半路算折着（往回放），没过算摊着（继续折）', () => {
  const 状态 = 创建折叠状态(六格);

  状态.设当前(3, 0.7);
  assert.equal(状态.切(3), 0, '都折过大半了，孩子这一下的意思是放回去');

  状态.设当前(3, 0.2);
  assert.equal(状态.切(3), 1, '才刚抬起来一点，这一下的意思是接着折');
});

test('一片一片折，互不干扰 —— 点第 2 片不该带动第 4 片', () => {
  const 状态 = 创建折叠状态(六格);
  状态.切(2);
  推到停(状态);

  assert.equal(状态.当前(2), 1);
  for (const 别的 of [1, 3, 4, 5]) {
    assert.equal(状态.当前(别的), 0, `第 ${别的} 片不该跟着动`);
  }
});

test('按住不放：一点一点往上折，松手就停在那儿', () => {
  const 状态 = 创建折叠状态(六格);

  状态.按住推(1, 0.2); // 按住 0.2 秒
  const 折了一点 = 状态.当前(1);
  assert.ok(折了一点 > 0 && 折了一点 < 1, `按住该折到半路，现在是 ${折了一点}`);

  状态.按住推(1, 0.2);
  assert.ok(状态.当前(1) > 折了一点, '按着不松就该继续折');

  const 松手那一刻 = 状态.当前(1);
  状态.停住(1);
  推到停(状态);
  assert.equal(状态.当前(1), 松手那一刻, '松手就停在那儿，不许自己跑完');
});

test('按住不放也不会折过头，最多就是折到底', () => {
  const 状态 = 创建折叠状态(六格);
  状态.按住开始(1);
  状态.按住推(1, 99);
  assert.equal(状态.当前(1), 1);
});

test('按住已经折起来的那片：往回摊，不是继续往上顶', () => {
  const 状态 = 创建折叠状态(六格);
  状态.设当前(1, 1);

  状态.按住开始(1);
  状态.按住推(1, 0.2);
  assert.ok(状态.当前(1) < 1, '折着的按住就该往回走');
  assert.ok(状态.当前(1) > 0);
});

test('按住顶到底之后别抖 —— 一帧一帧按下去，到了 1 就老老实实停在 1', () => {
  const 状态 = 创建折叠状态(六格);
  状态.按住开始(1);
  // 孩子按着不放，一帧一帧地喂时间进去（真实的按住就是这样）
  const 走过的 = [];
  for (let i = 0; i < 90; i += 1) {
    状态.按住推(1, 1 / 60);
    走过的.push(状态.当前(1));
  }

  assert.equal(状态.当前(1), 1, '按到底就该停在 1');
  // 到顶之后不许再往回掉 —— 一掉一涨就是每帧抖一下，纸片在孩子手底下打摆子
  const 到顶以后 = 走过的.slice(走过的.indexOf(1));
  assert.deepEqual([...new Set(到顶以后)], [1], `到顶后又动了：${到顶以后.slice(0, 6)}`);
});

test('按住摊回去也一样：一路按到 0 就停在 0，不反弹', () => {
  const 状态 = 创建折叠状态(六格);
  状态.设当前(1, 1);
  状态.按住开始(1);

  const 走过的 = [];
  for (let i = 0; i < 90; i += 1) {
    状态.按住推(1, 1 / 60);
    走过的.push(状态.当前(1));
  }

  assert.equal(状态.当前(1), 0);
  const 到底以后 = 走过的.slice(走过的.indexOf(0));
  assert.deepEqual([...new Set(到底以后)], [0], `摊到底后又动了：${到底以后.slice(0, 6)}`);
});

test('按住的方向在按下那一刻定死，中途不掉头', () => {
  const 状态 = 创建折叠状态(六格);
  状态.设当前(1, 0.45); // 差一点点到半路
  状态.按住开始(1); // 这一按的意思是「接着往上折」

  for (let i = 0; i < 10; i += 1) 状态.按住推(1, 1 / 60);
  assert.ok(状态.当前(1) > 0.45, '越过 0.5 了也得接着往上，不能因为过了半路就掉头');
});

test('整体折叠度是所有折痕的平均 —— 镜头靠它决定站多远', () => {
  const 状态 = 创建折叠状态(六格);
  assert.equal(状态.整体折叠度(), 0);

  状态.设当前(1, 1);
  assert.equal(状态.整体折叠度(), 0.2, '5 条折痕折了 1 条');

  状态.全体设(1);
  推到停(状态);
  assert.equal(状态.整体折叠度(), 1);
});

test('合上了：每一条折痕都折到底才算，差一条都不算', () => {
  const 状态 = 创建折叠状态(六格);
  assert.equal(状态.合上了(), false);

  for (const 下标 of [1, 2, 3, 4]) 状态.设当前(下标, 1);
  assert.equal(状态.合上了(), false, '还差第 5 片，不算穿上');

  状态.设当前(5, 1);
  assert.equal(状态.合上了(), true);

  状态.设当前(5, 折到底 - 0.01);
  assert.equal(状态.合上了(), false, '差一点点也是差');
});

test('摊平了：一条都没折起来', () => {
  const 状态 = 创建折叠状态(六格);
  assert.equal(状态.摊平了(), true);

  状态.设当前(3, 0.05);
  assert.equal(状态.摊平了(), false, '抬起来一点就不算摊平了');
});

test('全体设：滑块和「穿衣服！」口令用的那一下，六片一起走', () => {
  const 状态 = 创建折叠状态(六格);
  状态.全体设(1);
  推到停(状态);

  assert.equal(状态.合上了(), true);
  assert.equal(状态.当前(0), 0, '根格子永远是 0，它没有折痕');

  状态.全体设(0);
  推到停(状态);
  assert.equal(状态.摊平了(), true);
});

test('设当前：滑块拖到哪就停在哪，不许自己再往目标跑', () => {
  const 状态 = 创建折叠状态(六格);
  状态.全体设当前(0.4);

  assert.equal(状态.推进(1 / 60), false, '拖着滑块的时候没有动画在跑');
  assert.equal(状态.当前(2), 0.4);
  assert.equal(状态.整体折叠度(), 0.4);
});

test('推进：动画会停下来，而且正好停在目标上（不许在附近抖一辈子）', () => {
  const 状态 = 创建折叠状态(六格);
  状态.切(1);

  const 步 = 推到停(状态);
  assert.ok(步 > 1, '得真的animate几帧，不是一步到位');
  assert.ok(步 < 240, `4 秒内该停下来，现在用了 ${步} 帧`);
  assert.equal(状态.推进(1 / 60), false, '停了就是停了');
  assert.equal(状态.当前(1), 1, '正好落在目标上');
});

test('合上只报一次 —— 弹簧荡回来的那几帧不许被当成「散开了又合上」', () => {
  const 状态 = 创建折叠状态(六格);
  状态.全体设(1);

  // 记下整段动画里「合上了」翻面的次数
  let 上一次 = 状态.合上了();
  let 翻面次数 = 0;
  for (let i = 0; i < 600 && 状态.推进(1 / 60); i += 1) {
    const 现在 = 状态.合上了();
    if (现在 !== 上一次) 翻面次数 += 1;
    上一次 = 现在;
  }

  assert.equal(状态.合上了(), true);
  assert.equal(
    翻面次数,
    1,
    '一次合拢只该报一次。弹簧冲过 1 再荡回来时若跌破判定线，' +
      '就会被判成「合上→散开→又合上」：孩子听见的「发现新衣……」会被下一句拦腰截断',
  );
});

test('真的摊开了还是要报散开 —— 迟滞不是把状态焊死', () => {
  const 状态 = 创建折叠状态(六格);
  状态.全体设(1);
  推到停(状态);
  assert.equal(状态.合上了(), true);

  状态.全体设(0);
  推到停(状态);
  assert.equal(状态.合上了(), false);
  assert.equal(状态.摊平了(), true);
});

test('推进：弹一下才有意思 —— 中途会冲过头一点点', () => {
  const 状态 = 创建折叠状态(六格);
  状态.切(1);

  let 最高 = 0;
  for (let i = 0; i < 240 && 状态.推进(1 / 60); i += 1) {
    最高 = Math.max(最高, 状态.当前(1));
  }
  assert.ok(最高 > 1, `弹性该冲过 1 一点点，最高才 ${最高}`);
  assert.ok(最高 < 1.15, `冲过头别太多，纸会穿模，现在 ${最高}`);
});

test('一帧卡很久也不许把动画崩掉（切后台回来那一下）', () => {
  const 状态 = 创建折叠状态(六格);
  状态.切(1);
  状态.推进(3); // 标签页切走了三秒

  assert.ok(Number.isFinite(状态.当前(1)), '不许算出 NaN');
  推到停(状态);
  assert.equal(状态.当前(1), 1);
});

test('两片都在动，一起推进', () => {
  const 状态 = 创建折叠状态(六格);
  状态.切(1);
  状态.推进(1 / 60);
  状态.切(4); // 第一片还在动的时候点了第二片

  推到停(状态);
  assert.equal(状态.当前(1), 1);
  assert.equal(状态.当前(4), 1);
});
