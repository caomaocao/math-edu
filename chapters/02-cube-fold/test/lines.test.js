// 两语同构
// ---------------------------------------------------------------------------

/** 把嵌套的表摊成「路径 → 长什么样」，好一条条比 */
function 摊成路径(值, 前缀 = '', 收 = new Map()) {
  if (Array.isArray(值)) {
    收.set(前缀, `数组${值.length}`);
    值.forEach((一个, i) => 摊成路径(一个, `${前缀}[${i}]`, 收));
  } else if (值 && typeof 值 === 'object') {
    收.set(前缀, '对象');
    for (const [键, 一个] of Object.entries(值)) 摊成路径(一个, 前缀 ? `${前缀}.${键}` : 键, 收);
  } else {
    收.set(前缀, typeof 值);
  }
  return 收;
}

test('两语台词表键对键同构 —— 漏译一句就红', () => {
  const 中 = 摊成路径(台词('cn'));
  const 英 = 摊成路径(台词('en'));

  const 中键 = [...中.keys()].sort();
  const 英键 = [...英.keys()].sort();
  const 少了 = 中键.filter((一条) => !英.has(一条));
  const 多了 = 英键.filter((一条) => !中.has(一条));

  assert.deepEqual(少了, [], '英文表少了这几条（漏译）');
  assert.deepEqual(多了, [], '英文表多出这几条（中文表忘了加）');
  for (const 一条 of 中键) {
    assert.equal(英.get(一条), 中.get(一条), `「${一条}」两边形状不一样（数组长度或类型）`);
  }
});

test('英文表里不许剩汉字 —— 剩下的就是没翻的', () => {
  const 汉字 = /[一-鿿]/;
  const 摊 = 摊成路径(台词('en'));
  for (const [路径] of 摊) {
    // 场景是说给**视觉模型**听的提示词，不是说给孩子听的：
    // 它得挤进共享 看见.js 那个中文提示词模板里（那个文件不归本讲改），
    // 所以英文那一栏里带着一句中文的「请用英文夸他」。孩子永远听不见这一句。
    if (路径 === '做一件真的.场景') continue;
    const 值 = 路径.split('.').reduce((里, 键) => {
      const 配 = /^(.*?)\[(\d+)\]$/.exec(键);
      return 配 ? 里[配[1]][Number(配[2])] : 里[键];
    }, 台词('en'));
    if (typeof 值 !== 'string') continue;
    assert.ok(!汉字.test(值), `英文表的「${路径}」还是中文：${值}`);
  }
});

test('两语模板键对键，两边都调得动', () => {
  assert.deepEqual(Object.keys(模板表('cn')).sort(), Object.keys(模板表('en')).sort());
  assert.deepEqual(Object.keys(模板).sort(), Object.keys(模板表('cn')).sort());

  const 参数表 = {
    猜一猜收尾: [17, 9],
    碰到头: ['apple'],
    已经贴上了: ['banana'],
    告诉你答案: [5],
    贴水果收尾: [7],
    问对面数: [数字题库[0]],
    问加起来: [数字题库[0]],
    发现新衣服: ['and then.'],
    找到几件: [3],
  };
  for (const [键, 参] of Object.entries(参数表)) {
    for (const 语 of ['cn', 'en']) {
      const 出 = 模板表(语)[键](...参);
      assert.equal(typeof 出, 'string', `${语} 的模板 ${键} 没吐出字符串`);
      assert.ok(出.trim(), `${语} 的模板 ${键} 吐了个空句子`);
    }
  }
});

