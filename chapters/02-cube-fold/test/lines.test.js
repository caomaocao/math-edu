for (const 语 of ['cn', 'en']) {
  test(`全部台词（${语}）：每一句都是非空字符串，没有重复`, () => {
    const 单子 = 全份(语);
    assert.ok(单子.length > 50, `台词表看着太短了（${单子.length} 句），是不是漏了一整个玩法`);
    for (const 一句 of 单子) {
      assert.equal(typeof 一句, 'string');
      assert.ok(一句.trim(), '空句子不该进单子 —— 备话 会白跑一趟');
    }
    assert.equal(new Set(单子).size, 单子.length, '同一句备两遍是白花一次往返');
  });

  test(`全部台词（${语}）：五个玩法的静态台词一句不落`, () => {
    const 单子 = new Set(全份(语));
    const 话 = 台词(语);
    const 该有的 = [];
    const 摊 = (值) => {
      if (typeof 值 === 'string') 该有的.push(值);
      else if (值 && typeof 值 === 'object') Object.values(值).forEach(摊);
    };
    摊(话.全站);
    摊(话.共用);
    摊(话.穿衣服);
    摊(话.猜一猜);
    摊(话.贴水果);
    摊(话.衣服图鉴);
    摊(话.做一件真的);

    for (const 一句 of 该有的) {
      // 场景是说给视觉模型听的，不是方方的台词，故意不备
      if (一句 === 话.做一件真的.场景) continue;
      assert.ok(单子.has(一句), `这一句没进预热单子：${一句}`);
    }
  });

  test(`全部台词（${语}）：说给模型听的提示词不许混进来`, () => {
    assert.equal(全份(语).includes(台词(语).做一件真的.场景), false, '场景是给视觉模型的，备了也没人听');
  });

  test(`全部台词（${语}）：出处得从别的模块递进来（玩法名字 / 图鉴编码）`, () => {
    const 名字们 = 模式列表.map((一个) => 玩法名字(一个, 语));
    const 单子 = new Set(全份(语));
    for (const 名字 of 名字们) assert.ok(单子.has(名字), `鼠标扫过图标念的「${名字}」没备上`);

    // 数点点彩蛋的台词跟着编码现算，编码的出处是图鉴
    for (const 一句 of 数点点台词(编码顺序, 语)) {
      assert.ok(单子.has(一句), `数点点那句没备上：${一句}`);
    }

    // 不递出处就少那两摊 —— 这条是提醒调用方别忘了递
    const 空的 = new Set(全部台词({}, 语));
    assert.equal(空的.has(名字们[0]), false);
  });

  test(`全部台词（${语}）：水果名和闯关三两道题的题面备成成品`, () => {
    const 单子 = new Set(全份(语));
    for (const 一个 of 水果们) {
      assert.ok(单子.has(水果名(一个.槽位, 语)), `鼠标扫过水果盘念的「${水果名(一个.槽位, 语)}」没备上`);
    }
    assert.equal(数字题库.length, 2, '闯关三是两张');
    for (const 题 of 数字题库) {
      // 变量来自题库（算出来就定死了），跟孩子怎么玩无关，所以展开成成品
      assert.ok(单子.has(模板表(语).问对面数(题)), `「${题.号}」第一问没备上`);
      assert.ok(单子.has(模板表(语).问加起来(题)), `「${题.号}」第二问没备上`);
    }
  });

  test(`全部台词（${语}）：拍照那一套（倒数、断网时的保底夸奖）也备上`, () => {
    const 单子 = new Set(全份(语));
    const 纸样话 = 台词(语).做一件真的;
    for (const 词 of 纸样话.倒数们) assert.ok(单子.has(词), `倒数「${词}」没备上`);
    // 接口挂了的时候更不能冷场，这几句必须是从盘上直接读出来的
    for (const 一句 of 纸样话.保底夸奖们) assert.ok(单子.has(一句), `保底夸奖没备上：${一句}`);
  });
}

test('全部台词：带变量的成品不进单子（收模板不收成品）', () => {
  const 单子 = 全份('cn');
  const 带变量的 = [
    模板表('cn').猜一猜收尾(17, 9),
    模板表('cn').贴水果收尾(7),
    模板表('cn').找到几件(3),
    模板表('cn').碰到头('苹果'),
    模板表('cn').已经贴上了('香蕉'),
    模板表('cn').告诉你答案(5),
    模板表('cn').发现新衣服('点一个面看看。'),
  ];
  for (const 一句 of 带变量的) {
    assert.equal(单子.includes(一句), false, `带变量的成品混进预热单子了：${一句}`);
  }
});

test('模板：变量落在句子里，读起来是一句人话', () => {
  assert.equal(模板表('cn').找到几件(3), '你已经找到 3 件衣服啦，还差几件呢！');
  assert.equal(模板表('cn').发现新衣服(), '发现新衣服！');
  assert.equal(模板表('cn').发现新衣服('点一个面看看。'), '发现新衣服！点一个面看看。');
  assert.equal(模板表('cn').碰到头('苹果'), '你看，两个苹果碰到头啦！它们是对面。');
  assert.match(模板表('cn').猜一猜收尾(17, 9), /^17道题全做完啦！你收到了9只小猫/);

  assert.match(模板表('en').找到几件(3), /\b3\b/);
  assert.match(模板表('en').猜一猜收尾(17, 9), /\b17\b.*\b9\b/);
  assert.match(模板表('en').碰到头('apple'), /apple/);
});

test('模板：不指名就跟着当前语言走（缺省是中文课）', () => {
  // 界面上写的是 模板.找到几件(3)，一个语言参数都不用管
  assert.equal(模板.找到几件(3), 模板表('cn').找到几件(3));
});

