/**
 * 台词表（票 07 起，票 05 补上英文那一半）—— 盯的是两条：
 * 「预热真的把孩子会听见的话都备上了」，和「两语的表键对键，一句都没漏译」。
 *
 * 句子好不好听不归测试管（那是家长听着定的），这里只管这几件机械的事：
 *   · 出处对得上：玩法名字、图鉴编码这两样从别的模块递进来，别递错了；
 *   · 该备的备上了、不该备的没混进去（带变量的成品、说给模型听的提示词）；
 *   · 顺序对：开场白和玩法名字打头，孩子最先听见的就是它们；
 *   · **两语同构**：键集合一模一样、数组一样长、英文表里不许剩汉字。
 *     漏译在这儿直接红，而不是等孩子在英文课上听见半句中文。
 */

const 全份 = (语) =>
  全部台词(
    {
      玩法名字们: 模式列表.map((一个) => 玩法名字(一个, 语)),
      图鉴编码们: 编码顺序,
    },
    语,
  );

