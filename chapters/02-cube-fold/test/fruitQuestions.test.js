test('对面是三对，六格全都配上，而且互为对面', () => {
  for (const 一题 of 题库) {
    const 配对 = 对面配对(一题.格子);
    assert.equal(配对.length, 3);
    assert.deepEqual([...配对.flat()].sort((a, b) => a - b), [0, 1, 2, 3, 4, 5]);
    for (let i = 0; i < 6; i++) {
      assert.equal(对面下标(一题.格子, 对面下标(一题.格子, i)), i, `${一题.号} 第 ${i} 格`);
      assert.notEqual(对面下标(一题.格子, i), i);
    }
  }
});

/**
 * 书上例题3 的标准答案。
 *
 * 不是从引擎里抄回来的 —— 是按书上【辅导方法】那条规律一格一格数出来的：
 * 「在展开图的同行（或同列）中，中间隔一个正方形；或者和中间一行（或列）均相连的
 * 两正方形也是相对的。」孩子拿书对答案，对的就是这四行。
 */
const 例题3的答案 = [
  { 号: '例3-1', 对: [[[0, 0], [2, 0]], [[1, 2], [1, 0]]] },
  { 号: '例3-2', 对: [[[2, 2], [0, 0]], [[1, 0], [1, 2]]] },
  { 号: '例3-3', 对: [[[1, 1], [1, 3]], [[0, 1], [2, 1]]] },
  { 号: '例3-4', 对: [[[1, 0], [1, 2]], [[2, 3], [0, 0]]] },
];

test('例题3 四张：书上涂了红黄两格，算出来的对面正是书上的答案', () => {
  for (const { 号, 对 } of 例题3的答案) {
    const 一题 = 题库.find((t) => t.号 === 号);
    for (const [[从行, 从列], [到行, 到列]] of 对) {
      const 从 = 找格(一题.格子, 从行, 从列);
      assert.notEqual(从, -1);
      assert.deepEqual(坐标(一题.格子, 对面下标(一题.格子, 从)), [到行, 到列], `${号} (${从行},${从列}) 的对面`);
    }
  }
});

test('例题3 用的就是书上那两种颜色：红=苹果、黄=香蕉', () => {
  for (const 号 of ['例3-1', '例3-2', '例3-3', '例3-4']) {
    const 一题 = 题库.find((t) => t.号 === 号);
    assert.deepEqual([...一题.水果槽位].sort(), [0, 1]);
    assert.equal(水果们[0].色, '#FF5A5A'); // 红
    assert.equal(水果们[1].色, '#FFC53D'); // 黄
  }
});

