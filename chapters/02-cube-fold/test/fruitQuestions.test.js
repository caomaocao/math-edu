test('水果名两语都有，英文那份不许剩汉字', () => {
  const 汉字 = /[\p{Script=Han}]/u;
  for (const 一个 of 水果们) {
    const 中 = 水果名(一个.槽位, 'cn');
    const 英 = 水果名(一个.槽位, 'en');
    assert.ok(中 && 英, `第 ${一个.槽位} 种水果缺名字`);
    assert.ok(!汉字.test(英), `第 ${一个.槽位} 种水果的英文名没翻：${英}`);
  }
  assert.equal(水果名(0, 'cn'), '苹果');
  assert.equal(水果名(0, 'en'), 'apple');
  assert.equal(水果名(0), '苹果', '不指名语言就跟着当前语言走（缺省是中文课）');
});

