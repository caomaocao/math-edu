test('贴纸板装得下每一张衣服', () => {
  for (const 一题 of 题库) {
    for (const 格 of 居中摆(一题.格子)) {
      assert.ok(格.row >= 0 && 格.row < 板行数, 一题.号);
      assert.ok(格.col >= 0 && 格.col < 板列数, 一题.号);
    }
  }
});

test('居中摆：格数不变、下标保序、形状不走样', () => {
  for (const 一题 of 题库) {
    const 摆好 = 居中摆(一题.格子);
    assert.equal(摆好.length, 一题.格子.length);
    assert.deepEqual(摆好.map((c) => c.下标), 一题.格子.map((_, i) => i));
    // 整体平移，格子之间的相对位置一格都不许变
    const d行 = 摆好[0].row - 一题.格子[0].row;
    const d列 = 摆好[0].col - 一题.格子[0].col;
    for (let i = 0; i < 摆好.length; i++) {
      assert.equal(摆好[i].row - 一题.格子[i].row, d行);
      assert.equal(摆好[i].col - 一题.格子[i].col, d列);
    }
  }
});
