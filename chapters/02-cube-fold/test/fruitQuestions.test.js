test('先贴好的那几格互相不是对面 —— 不然一对里两格都有水果，孩子没得贴', () => {
  for (const 一题 of 贴水果题库) {
    const 下标们 = 一题.已贴.map((一个) => 一个.下标);
    for (const i of 下标们) {
      assert.ok(!下标们.includes(对面下标(一题.格子, i)), `${一题.号} 第 ${i} 格`);
    }
    // 水果也不许重样，不然孩子分不清哪个苹果配哪个苹果
    assert.equal(new Set(一题.水果槽位).size, 一题.水果槽位.length, 一题.号);
  }
});

test('每道题的答案格都是空的，而且不重样', () => {
  for (const 一题 of 贴水果题库) {
    const 已贴 = 一题.已贴.map((一个) => 一个.下标);
    const 要贴 = 一题.答案.map((一个) => 一个.贴到);
    assert.equal(new Set(要贴).size, 要贴.length, 一题.号);
    for (const 一个 of 一题.答案) {
      assert.ok(!已贴.includes(一个.贴到), `${一题.号}：答案格上已经有水果了`);
      assert.equal(一个.贴到, 对面下标(一题.格子, 一个.从), 一题.号);
    }
  }
});

