/**
 * 贴水果题库的自检。
 *
 * 这个文件盖的是两件事：
 *   一、13 张图的坐标是不是照着书誊对了（誊错一格，整道题的对面全变）；
 *   二、「谁和谁是对面」算得对不对 —— 用一套**跟 net.js 完全无关**的算法复算一遍。
 *
 * 第二件事是这一关的地基：孩子贴对贴错全由它裁决。net.js 那边是「把每个格子绕折痕
 * 转 90°，看落在正方体哪个面上」（嵌套矩阵）；这边是**在纸上滚骰子** ——
 * 一个正方体压在起点格上，走一步就翻一次，记下每一格上贴着地的是骰子的哪一面。
 * 两种算法一个用矩阵、一个用置换，除了「正方体有六个面」之外没有任何共同前提，
 * 同时算错到一块儿去的可能微乎其微。
 */

// ---------------------------------------------------------------------------
// 独立算法：在纸上滚骰子
// ---------------------------------------------------------------------------

/** 骰子的六个面，对面成对 */
const 面的对面 = { 上: '下', 下: '上', 北: '南', 南: '北', 东: '西', 西: '东' };

/** 往某个方向翻一次：四个面轮转，另外两个面不动 */
const 翻 = {
  // 往南（row+1）滚：南→下，下→北，北→上，上→南
  南: (骰) => ({ ...骰, 下: 骰.南, 北: 骰.下, 上: 骰.北, 南: 骰.上 }),
  北: (骰) => ({ ...骰, 下: 骰.北, 南: 骰.下, 上: 骰.南, 北: 骰.上 }),
  东: (骰) => ({ ...骰, 下: 骰.东, 西: 骰.下, 上: 骰.西, 东: 骰.上 }),
  西: (骰) => ({ ...骰, 下: 骰.西, 东: 骰.下, 上: 骰.东, 西: 骰.上 }),
};

const 走向 = [
  { d行: 1, d列: 0, 名: '南' },
  { d行: -1, d列: 0, 名: '北' },
  { d行: 0, d列: 1, 名: '东' },
  { d行: 0, d列: -1, 名: '西' },
];

/**
 * 让一个正方体在这张衣服上滚一遍，返回每一格上「贴着地的是哪一面」。
 * 折起来之后，这一格盖住的正是那一面 —— 所以两格是对面 ⟺ 两个面是对面。
 */
function 滚一遍(格子) {
  const 位置 = 格子.map((c) => `${c.row},${c.col}`);
  const 落在 = new Array(格子.length).fill(null);
  落在[0] = { 上: '上', 下: '下', 北: '北', 南: '南', 东: '东', 西: '西' };

  const 队 = [0];
  while (队.length > 0) {
    const i = 队.shift();
    for (const { d行, d列, 名 } of 走向) {
      const j = 位置.indexOf(`${格子[i].row + d行},${格子[i].col + d列}`);
      if (j === -1 || 落在[j]) continue;
      落在[j] = 翻[名](落在[i]);
      队.push(j);
    }
  }
  return 落在.map((骰) => 骰.下);
}

/** 滚骰子算出来的三对对面（每对里的下标排好序，两套算法好直接比） */
function 滚出来的对面(格子) {
  const 面 = 滚一遍(格子);
  const 对 = [];
  for (let i = 0; i < 格子.length; i++) {
    for (let j = i + 1; j < 格子.length; j++) {
      if (面[j] === 面的对面[面[i]]) 对.push([i, j]);
    }
  }
  return 对;
}

const 排好 = (对们) => 对们.map((一对) => [...一对].sort((a, b) => a - b)).sort((a, b) => a[0] - b[0]);

const 找格 = (格子, row, col) => 格子.findIndex((c) => c.row === row && c.col === col);
const 坐标 = (格子, 下标) => [格子[下标].row, 格子[下标].col];

