test('图标上不出现文字，念的是孩子叫法不是术语', () => {
  const 有字 = /[\p{Script=Han}A-Za-z0-9]/u;
  for (const 一个 of 模式列表) {
    assert.ok(!有字.test(一个.图标), `「${一个.键}」的图标里混进了文字：${一个.图标}`);
  }
  assert.deepEqual(
    模式列表.map((一个) => 玩法名字(一个, 'cn')),
    ['穿衣服', '猜一猜', '贴水果', '衣服图鉴', '做一件真的'],
    '念给孩子听的是孩子叫法；「判断关」「对面关」「纸样」这些词只活在代码里',
  );
});

test('五个玩法名字两语都有，英文那份不许剩汉字', () => {
  const 汉字 = /[\p{Script=Han}]/u;
  for (const 一个 of 模式列表) {
    const 中 = 玩法名字(一个, 'cn');
    const 英 = 玩法名字(一个, 'en');
    assert.ok(中 && typeof 中 === 'string', `「${一个.键}」缺中文名字`);
    assert.ok(英 && typeof 英 === 'string', `「${一个.键}」缺英文名字`);
    assert.ok(!汉字.test(英), `「${一个.键}」的英文名字没翻：${英}`);
    assert.notEqual(中, 英, `「${一个.键}」两语的名字一模一样，多半是漏译`);
  }
});

