/**
 * 重来之后：四格数据全空。
 * 不拿 空进度() 整份比 —— 重来会打一个整包重置戳（戳.整包 > 0，跨设备同步用），
 * 那不是「残渣」，是「我清过了」的记号；空的是数据，不是戳。
 */
function 数据全空(读回, 说明 = '') {
  assert.deepEqual(读回.图鉴.已解锁, [], 说明);
  assert.deepEqual(读回.判断关.作答, {}, 说明);
  assert.deepEqual(读回.贴水果.作答, {}, 说明);
  assert.deepEqual(读回.沙盒.格子, [], 说明);
}

test('重来：全部清掉，存储里也不留残渣', () => {
  const { 底, 进度 } = 新存储();
  进度.解锁图鉴('141a');
  进度.记判断关('例题2_1', true);
  进度.记贴水果('例题3_1', true);

  进度.重来();
  数据全空(进度.读());
  assert.ok(进度.读().戳.整包 > 0, '重来打一个整包重置戳，好把「清空」传给另一台设备');
  const 下次打开 = 创建进度存储({ 存储: 底 }).读();
  数据全空(下次打开, '下次打开也是干净的');
  assert.ok(下次打开.戳.整包 > 0, '整包戳也得落盘，换台设备才压得住旧数据');
});

test('重来：旧版那份也一并清掉，别下次打开又诈尸搬回来', () => {
  const 底 = 内存存储();
  底.setItem(上一版存储键, JSON.stringify({ 版本: 进度版本 - 1, 图鉴: { 已解锁: ['141a'] } }));

  const 进度 = 创建进度存储({ 存储: 底 });
  assert.deepEqual(进度.已解锁图鉴(), ['141a'], '先确认真的搬过来了');

  进度.重来();
  数据全空(创建进度存储({ 存储: 底 }).读(), '孩子说了清，就得真的清干净');
});

test('订阅：进度一变就叫一声，退订之后就不叫了', () => {
  const { 进度 } = 新存储();
  const 叫过 = [];
  const 退订 = 进度.订阅((一份) => 叫过.push(一份.图鉴.已解锁.length));

  进度.解锁图鉴('141a');
  进度.解锁图鉴('141a'); // 没变，不该叫
  进度.记判断关('例题2_1', true);
  assert.deepEqual(叫过, [1, 1]);

  退订();
  进度.解锁图鉴('33');
  assert.deepEqual(叫过, [1, 1]);
});

test('存储坏掉（无痕模式、存满了）也不许抛错', () => {
  const 死存储 = {
    getItem() {
      throw new Error('读不了');
    },
    setItem() {
      throw new Error('写不了');
    },
    removeItem() {
      throw new Error('删不了');
    },
  };
  const 进度 = 创建进度存储({ 存储: 死存储 });
  assert.deepEqual(进度.读(), 空进度());
  assert.equal(进度.解锁图鉴('141a'), true, '这一局照样玩得下去，只是攒不住');
  assert.equal(进度.图鉴数(), 1);
  assert.doesNotThrow(() => 进度.重来());
});

