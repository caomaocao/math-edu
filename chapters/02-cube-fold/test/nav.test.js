test('hover、focus、click 连着三下，同一个名字只念一遍', () => {
  const 念过 = [];
  let 表 = 0;
  const 念 = 创建不复读的朗读((话) => 念过.push(话), () => 表);

  念('穿衣服'); // pointerenter
  念('穿衣服'); // focus
  念('穿衣服'); // click
  assert.deepEqual(念过, ['穿衣服'], '孩子听见的应该是一句完整的话，不是被打断三次的半句');

  念('猜一猜');
  assert.deepEqual(念过, ['穿衣服', '猜一猜'], '换了一个就得念');

  表 += 5000; // 过一会儿孩子又转回来了
  念('猜一猜');
  assert.deepEqual(念过, ['穿衣服', '猜一猜', '猜一猜']);
});

