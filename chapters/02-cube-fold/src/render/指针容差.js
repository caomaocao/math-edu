/**
 * 「他是想点这一片，还是想转镜头？」—— 这个门槛两处都要用，所以只定一次。
 *
 * 三维舞台上同一块画布挂着三样东西：轨道控制（拖着转）、折纸手（点着折）、
 * 点面看对面（点着亮）。后两样都靠「按下到松开挪了多少」把自己跟拖拽分开，
 * 从前各写一个 `= 7`，改一个忘一个的下场是：折得动、点不亮（或者反过来）。
 */

/**
 * 鼠标：7px。鼠标不抖，按下和松开几乎在同一个点上，超过 7px 就是真拖了。
 *
 * 手指：18px。这一档不是「因为舞台缩过所以要换算」—— 指针事件报的 clientX 是
 * 视觉坐标，缩放不进这笔账；换的是**手**。五岁的手指按下去会滚、会晃，
 * 一次干脆的点在 iPhone 上轻松走出 3–5px（≈1.5mm），7px 的门槛会把一多半
 * 「我想折这一片」判成「我想转镜头」，而孩子看到的是点了没反应 ——
 * 他不认字，也问不出为什么。
 *
 * 两头的代价不对称，所以宁可往「算点」这边偏：
 *   判成点、其实他想转 → 纸片折一下，再点一下就放回来，转镜头照样能接着转（多转 18px 而已）。
 *   判成转、其实他想点 → 什么都没发生。对一个不认字的孩子，这是死路。
 * 18px 在 iPhone 上大约 6mm：真要转体的那一拖远远超过它。
 */
const 门槛 = { 鼠标: 7, 手指: 18 };

/**
 * 这一下指针，挪出多少才算「他在转镜头」。
 * @param {string} [指针类型] pointer 事件自带的 pointerType；认不出来的按鼠标算
 */
export function 算挪了的位移(指针类型) {
  return 指针类型 === 'touch' || 指针类型 === 'pen' ? 门槛.手指 : 门槛.鼠标;
}
