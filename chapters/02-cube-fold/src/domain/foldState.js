/**
 * 逐面折叠的状态机 —— 每条折痕现在折到哪、要折到哪。
 *
 * 前代只有一个整体折叠度：滑块从左拖到右，六个面一起收拢。孩子只是在
 * 「播放一段动画」，不是在折纸。这一版每条折痕各有各的折叠度，孩子点一个格子，
 * 就只有那一片「啪」地弹起来 —— 每折一面都是一次他自己动手换来的反馈。
 *
 * 格子和折痕是一一对应的：折痕树上每个非根格子恰好挂在一条折痕上（ADR-0001），
 * 所以这里按格子下标存。根格子贴着地，没有折痕，永远折不动。
 * 父子关系不在这里 —— 折父格子时子孙跟着走，那是 FoldedNet 的场景树干的活。
 *
 * 纯的：不碰 three.js，不碰 DOM，时间由调用方一帧一帧喂进来。
 */

/** 折到这儿就算折到底了。弹性动画停不到精确的 1，得留一丝余地 */
export const 折到底 = 0.999;

/** 按住不放时，一秒折完整个 90° 的多少 —— 慢到孩子能停在他想看的地方 */
const 按住的速度 = 1.6;

/** 弹簧：硬一点弹得脆，阻尼小一点才有那下「啪」的过冲 */
const 刚度 = 190;
const 阻尼 = 17;
/** 离目标够近、又几乎不动了，就直接落到目标上，别在附近抖一辈子 */
const 算停了的距离 = 0.001;
const 算停了的速度 = 0.02;
/** 一帧最多按这么长算。标签页切走再回来会攒出一个几秒的 dt，弹簧会被它炸飞 */
const 一帧最长 = 1 / 30;

const 夹住 = (值) => Math.min(1, Math.max(0, 值));

/**
 * @param {{格子数: number, 根下标: number}} 衣服
 */
export function 创建折叠状态({ 格子数, 根下标 }) {
  const 当前 = new Array(格子数).fill(0);
  const 目标 = new Array(格子数).fill(0);
  const 速度 = new Array(格子数).fill(0);
  /** 正被手按着的那几片，各自往哪个方向走（+1 往上折，-1 往回摊）。0 = 没按着 */
  const 按着的方向 = new Array(格子数).fill(0);
  /** 谁在动。空着就没有动画在跑，省得每帧空转一遍 */
  const 动着的 = new Set();

  function 能折(下标) {
    return Number.isInteger(下标) && 下标 >= 0 && 下标 < 格子数 && 下标 !== 根下标;
  }

  /** 除了根，都是折痕 */
  function 每条折痕(做点什么) {
    for (let i = 0; i < 格子数; i += 1) {
      if (i !== 根下标) 做点什么(i);
    }
  }

  function 设当前(下标, 值) {
    if (!能折(下标)) return;
    当前[下标] = 夹住(值);
    目标[下标] = 当前[下标];
    速度[下标] = 0;
    动着的.delete(下标);
  }

  function 设目标(下标, 值) {
    if (!能折(下标)) return;
    目标[下标] = 夹住(值);
    if (目标[下标] !== 当前[下标]) 动着的.add(下标);
  }

  return {
    根下标,
    能折,

    当前(下标) {
      return 能折(下标) ? 当前[下标] : 0;
    },
    目标(下标) {
      return 能折(下标) ? 目标[下标] : 0;
    },

    设当前,
    设目标,

    /**
     * 点一下。折过大半了就放回去，还没到半路就接着折。
     * @returns {0|1|null} 这一下要往哪儿去；根格子返回 null（什么也不该发生）
     */
    切(下标) {
      if (!能折(下标)) return null;
      const 去哪 = 当前[下标] >= 0.5 ? 0 : 1;
      设目标(下标, 去哪);
      return 去哪;
    },

    /**
     * 手按到这一片上了：定下这一按是往上折还是往回摊。
     *
     * 方向**必须**在按下这一刻定死。每帧现算的话，折到顶那一帧会算出「该往回了」，
     * 下一帧掉回 0.97 又算出「该往上」—— 孩子按着不动，纸片在他手底下每秒抖六十下。
     * 同理，按住已经折起来的那片就永远摊不开：它只会在 1 和 0.97 之间来回蹦。
     */
    按住开始(下标) {
      if (!能折(下标)) return;
      // 和「点一下」同一条线：过了半路就是往回，没过就是接着折
      按着的方向[下标] = 当前[下标] >= 0.5 ? -1 : 1;
    },

    /** 按住不放：按多久折多少。方向是 按住开始 那一刻定下的，中途不掉头 */
    按住推(下标, 秒) {
      if (!能折(下标)) return;
      const 方向 = 按着的方向[下标] || (当前[下标] >= 0.5 ? -1 : 1);
      当前[下标] = 夹住(当前[下标] + 按住的速度 * Math.max(0, 秒) * 方向);
      目标[下标] = 当前[下标];
      速度[下标] = 0;
      动着的.delete(下标);
    },

    /** 松手：就停在这儿，不许自己跑完剩下的路 */
    停住(下标) {
      if (!能折(下标)) return;
      目标[下标] = 当前[下标];
      速度[下标] = 0;
      按着的方向[下标] = 0;
      动着的.delete(下标);
    },

    /** 滑块 / 「穿衣服！」口令：所有折痕一起走，带动画 */
    全体设(值) {
      每条折痕((i) => 设目标(i, 值));
    },

    /** 拖滑块：拖到哪就立刻停在哪，不要动画在后面追 */
    全体设当前(值) {
      每条折痕((i) => 设当前(i, 值));
    },

    /** 平均折叠度。镜头靠它决定站多远：摊平退远看纸，合上凑近看正方体 */
    整体折叠度() {
      const 条数 = 格子数 - 1;
      if (条数 <= 0) return 0;
      let 和 = 0;
      每条折痕((i) => {
        和 += Math.min(1, 当前[i]);
      });
      return 和 / 条数;
    },

    /** 每一条折痕都折到底才算穿上了，差一条都不算 */
    合上了() {
      let 齐了 = true;
      每条折痕((i) => {
        if (当前[i] < 折到底) 齐了 = false;
      });
      return 齐了;
    },

    摊平了() {
      let 平的 = true;
      每条折痕((i) => {
        if (当前[i] > 0) 平的 = false;
      });
      return 平的;
    },

    /**
     * 往前走一帧。
     * @param {number} 秒 距上一帧多久
     * @returns {boolean} 还有东西在动吗（false 就可以歇了）
     */
    推进(秒) {
      if (动着的.size === 0) return false;
      const 步 = Math.min(Math.max(0, 秒), 一帧最长);

      for (const i of [...动着的]) {
        const 差 = 目标[i] - 当前[i];
        速度[i] += 差 * 刚度 * 步;
        速度[i] -= 速度[i] * 阻尼 * 步;
        当前[i] += 速度[i] * 步;

        if (Math.abs(目标[i] - 当前[i]) < 算停了的距离 && Math.abs(速度[i]) < 算停了的速度) {
          当前[i] = 目标[i];
          速度[i] = 0;
          动着的.delete(i);
        }
      }
      return 动着的.size > 0;
    },
  };
}
