/**
 * 六个格子的颜色和水果。
 * 一个格子折起来就成了一个面 —— 颜色和水果跟着格子走，所以摊平和折起来是同一张纸。
 * 后面的票（格子纸、图鉴、打印纸样）都从这里取同一套配色，保证屏幕上和纸上一模一样。
 */
export const CELL_STYLES = [
  { 名: '苹果', color: '#FF5A5A', fruit: '🍎' },
  { 名: '香蕉', color: '#FFC53D', fruit: '🍌' },
  { 名: '葡萄', color: '#9B6BFF', fruit: '🍇' },
  { 名: '橘子', color: '#FF9235', fruit: '🍊' },
  { 名: '草莓', color: '#FF4D9E', fruit: '🍓' },
  { 名: '猕猴桃', color: '#2ED8A5', fruit: '🥝' },
];

/**
 * 这一讲屏幕上出现的实体（规范名）—— 六个格子的水果，加上两位小助手
 * （贴水果关的兔子、猜一猜关的小猫）。
 *
 * 跟第 3 讲每个环节各自导出 实体们 是同一个约定：实体图覆盖测试拿它对账。
 * 这一讲的实体全都从这张调色板长出来，所以清单也放在这里，不散到各个 UI 模块。
 */
export const 实体们 = [...CELL_STYLES.map((样) => 样.名), '兔子', '小猫'];

/** 第 n 个格子长什么样（多于 6 个就绕回来） */
export function cellStyle(index) {
  return CELL_STYLES[index % CELL_STYLES.length];
}

/**
 * 三对对面各自的发光色，次序跟 net.js 的「对面轴」一一对应（x / y / z）。
 *
 * 挑的是荧光感很强的电光色，故意跟上面六种水果色离得远 ——
 * 发光是**蒙在格子颜色上面**的，跟水果色撞了孩子就分不清是这一格本来的颜色
 * 还是它正在发光。三种颜色互相也要一眼分得开：孩子连点三次凑齐 3 对，
 * 靠的就是「刚才亮的是青的，这回是绿的」。
 */
export const 对面发光色 = ['#22E3FF', '#B6FF3D', '#FF3DD1'];

/** 第 n 对对面的发光色（3 对，超了就绕回来） */
export function 对面色(序) {
  return 对面发光色[序 % 对面发光色.length];
}
