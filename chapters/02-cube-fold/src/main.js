// 折到底那一刻：能合上，还是穿不上
// ---------------------------------------------------------------------------

function 判一判() {
  if (!(当前展示 instanceof FoldedNet)) return;

  // 用舞台上这张衣服实际的根格子来算，红黄标出来的面才跟画面上的对得上
  const 结果 = foldResult(当前展示.cells, 当前展示.tree.root);

  if (结果.valid) {
    // 合上了才谈得上对面：这一份存下来，孩子点面的时候直接查
    合上的结果 = 结果;

    /*
      折成正方体的**这一刻**就把衣服交给图鉴。是不是没画过的种类由图鉴判
      （判重无视旋转和翻转），是就当场点亮那一格 + 语音喊「发现新衣服！」——
      孩子不用跑到图鉴那一页去看。

      「点一个面看看」交给图鉴跟庆祝合成同一句说出去：说() 是后一句掐掉前一句的，
      分两次说，孩子听见的就是被拦腰打断的「发现新衣……点一个面看看」。
    */
    方方.情绪('跳舞'); // 穿上新衣服，转圈蹦跶
    音效.答对();

    const 收获 = 图鉴?.收下衣服(当前展示.cells, { 接着说: 沙盒话().接着看对面 });
    if (!收获?.新) 说(沙盒话().穿上了);
    return;
  }

  提示.显示(结果);

  const 重叠面 = 结果.overlaps.map((一组) => 结果.faces[一组[0]]);
  舞台.转镜头到(失败视角(重叠面, 结果.holes));
  音效.答错();
  演一遍穿不上();
}

/**
 * 穿不上的那出戏：先为叠着的地方喊痒，再为漏着的地方打喷嚏。
 *
 * 重叠和漏洞必定成对出现（有两片撞一起，就必然有一个面露着），两处都得指出来 ——
 * 孩子不认字，红黄两块颜色是「哪儿不对」，方方的反应才是「为什么不对」。
 *
 * **两句话说完才开始摊回。** 早先是说第一句的同时就按 2.6 秒定时摊回，
 * 而摊回一开始黄牌子就跟着正方体散掉了 —— 方方说「那边还漏了个洞」的时候，
 * 那个洞已经没了，孩子顺着话看过去什么也看不见。
 */
async function 演一遍穿不上() {
  const 这一局 = 这一件衣服;

  方方.情绪('发抖');
  await 说(台词().共用.痒);
  if (这一局 !== 这一件衣服) return; // 孩子已经改格子了，这出戏别接着演

  方方.情绪('喷嚏');
  await 说(台词().共用.漏风);
  if (这一局 !== 这一件衣服) return;

  安排摊回();
}

/** 失败以后自己慢慢摊回平地。孩子不用点任何「重试」，直接改格子就行 */
function 安排摊回() {
  const 这一次 = ++摊回请求;
  setTimeout(() => {
    if (这一次 !== 摊回请求) return;
    // 交给折叠状态自己弹回去，跟孩子手点出来的那种回弹是同一种手感
    摊回中 = true;
    折叠?.全体设(0); // 动画交给折叠状态，滑块只是跟着把手往回走
    滑块.跟着走(0);
  }, 讲完再留一会);
}

function 取消摊回() {
  摊回请求++;
  摊回中 = false;
}

