/*
  接缝和 说话.js / 预热.js 一个套路：引擎（/shared/js/云同步.js）管拉、合并调度、
  推送防抖、失败静默；这一讲只交三样 —— 存储键、纯函数 合并()（state/progress.js 里，
  有 node 测试）、收编回调（把合并结果落回内存态并刷界面）。

  收编 走进度既有的落盘 + 广播路（进度.收编 是**同步**的，满足引擎「收编期间压住 记脏」的约束）：
  图鉴、贴水果各自订阅了进度，广播时自刷；判断关没订阅（它靠 进场 读最新进度），
  所以只有它正当台上时才补叫一手 重头来过 —— 不在台上就别在这儿白建一整个判断关的 WebGL 场景，
  孩子切过去时 进场 会自己读到最新的进度重画。
*/
登记({
  存储键,
  合并,
  收编(合并后) {
    进度.收编(合并后);
    if (导航?.当前 === '判断关') 判断关?.重头来过?.();
  },
});

/*
  每次本地进度写入（解锁图鉴 / 记判断关 / 记贴水果 / 存沙盒 / 清 / 重来）都会广播一声，
  订一处就够：广播在**落盘之后**，正好是引擎要的「记脏在落盘后同步调」。收编自己的那次广播
  由引擎压着 记脏（正在收编期间空转），不会把云来的写当本地改动回推。
*/
进度.订阅(() => 记脏(存储键));

