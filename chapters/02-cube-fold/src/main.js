/**
 * 折叠状态一变就叫这儿一声 —— 不管这一下是点出来的、按出来的、拖出来的还是喊出来的。
 *
 * 只在「合上了 ↔ 没合上」翻面的那一刻做事。每帧无脑清一遍提示的话，
 * 红黄两块标记刚亮起来就会被下一帧抹掉。
 */
function 折叠动过() {
  if (!折叠) return;
  const 合上 = 折叠.合上了();
  if (合上 === 判过) return;
  判过 = 合上;

  if (合上) {
    判一判();
    return;
  }
  // 散开了：正方体没了，对面也就不存在了，高亮别留在半折的纸上
  合上的结果 = null;
  收起对面();
  // 摊回途中红的留着，孩子能一路盯住是哪两格闯的祸；黄牌子跟着正方体一起散掉
  if (摊回中) 提示?.收起漏洞();
  else 提示?.清除();
}

