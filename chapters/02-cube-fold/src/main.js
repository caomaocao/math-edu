const 方方站位 = new THREE.Vector3();
const 这一片的位置 = new THREE.Vector3();
const 这一片的朝向 = new THREE.Vector3();
const 选中的朝向 = new THREE.Vector3();
const 朝镜头 = new THREE.Vector3();
const 身子中心 = new THREE.Vector3();
const 向上 = new THREE.Vector3(0, 1, 0);

/** 脸从那一片表面浮出来多少（格），够躲开纸的厚度、不至于飘在半空 */
const 浮出表面 = 0.14;

/**
 * 朝天／朝地的那一片扣多少分。
 *
 * 光比「谁最正对镜头」是不够的：孩子的镜头是俯视的（约 40°），顶面的法线笔直朝上，
 * 算出来比两个侧面还正，脸就爬到正方体顶上去了 —— 看着像被压扁贴在盖子上。
 * 角色的脸长在竖直的那一面，不长在头顶。扣这一刀之后，只要还看得见侧面就选侧面；
 * 孩子真把镜头转到正上方俯瞰时，侧面全都侧过去了，顶面照样会赢。
 */
const 朝天要扣的分 = 0.35;

/**
 * 方方的脸这一帧摆在哪儿（世界坐标）；返回 null = 这一帧别露脸。
 *
 * **只在纸停稳的两个时候露脸：摊平躺着，和穿好了。折到半路一律收起来。**
 *
 * 半路上没有一个位置是对的，这不是没调好参数，是几何上就不成立：折到一半时六片纸
 * 全是斜的，从孩子的角度看每一片都只有一条窄边，脸摆到哪一片上都是贴在一片刀刃上。
 * （之前按「谁最朝着镜头」连续地挑，挑出来的就是那条最扁的侧棱 —— 脸飘在纸外面。）
 * 收起来反而讲得通：换衣服的时候脸埋在衣服里，穿好了才探出来朝孩子笑。
 *
 * 停稳的两头就都好定位了，各一行：
 *   · 摊平 → 根格子。它是整张衣服里唯一不会转的一片，永远平躺着朝上。
 *   · 穿好 → 最朝着孩子的那一面。正方体的六个面法线正正好好指向六个方向，
 *     总有一面是完整地对着孩子的，脸就摆在那一面正中央。
 *
 * 走过的弯路留在这儿，免得下次又踩：
 *   一、把脸焊在根格子上。摊平时很好，但衣服折起来之后根格子可能翻到侧面甚至背面去。
 *   二、摆在正方体正中心，再朝镜头方向推出去。推多远都没用 ——
 *       孩子多半是斜着看正方体的（镜头对着一条棱），而**正方体的中心正好投影在那条前棱上**，
 *       沿视线推只改深度、不改它在屏幕上的位置，脸永远骑在棱上：
 *       左眼落在一个面、右眼落在另一个面、嘴压在棱中间。
 *
 * 穿不上的形状（PaperPreview）没有折痕树，那会儿方方也没身子可站。
 */
function 方方站哪儿() {
  if (!(当前展示 instanceof FoldedNet) || !折叠) return null;

  // 摊平躺着：钉在根格子上。脸不会随着孩子转镜头在格子间跳来跳去
  if (折叠.摊平了()) {
    const 根 = 当前展示.cellGroups[当前展示.tree.root];
    if (!根) return null;
    根.getWorldPosition(方方站位);
    return 方方站位.addScaledVector(向上, CELL_SIZE * 浮出表面);
  }

  // 正折着：半路上没有好位置，收起来（穿不上的那件也是「合上了」，戏照演）
  if (!折叠.合上了()) return null;

  当前展示.boundingBox().getCenter(身子中心);
  朝镜头.subVectors(舞台.camera.position, 身子中心);
  if (朝镜头.lengthSq() < 1e-12) return null; // 镜头正好压在身上，这一帧不摆了
  朝镜头.normalize();

  let 最正的分 = -Infinity;
  let 挑中了 = false;

  for (let i = 0; i < 当前展示.cellGroups.length; i += 1) {
    const 片 = 当前展示.cellGroups[i];
    if (!片) continue;

    片.getWorldPosition(这一片的位置);

    /*
      「朝外」用的是「从身子中心指向这一片」，不是那张纸的法线。
      纸有正反两面，法线指哪边全看它是怎么折上去的 —— 背面那一片的法线常常正好
      朝着镜头，用法线算的话它分数最高，脸就被塞进正方体肚子里去了（真踩过）。
      从中心指出来的方向没有这个歧义：朝着镜头的那一面，一定是孩子看得见的那一面。
    */
    这一片的朝向.subVectors(这一片的位置, 身子中心);
    if (这一片的朝向.lengthSq() < 1e-9) 这一片的朝向.copy(向上); // 正压在中心上，随便给个方向别让它 NaN
    else 这一片的朝向.normalize();

    const 分 = 这一片的朝向.dot(朝镜头) - Math.abs(这一片的朝向.y) * 朝天要扣的分;
    if (分 <= 最正的分) continue;

    最正的分 = 分;
    挑中了 = true;
    方方站位.copy(这一片的位置);
    选中的朝向.copy(这一片的朝向);
  }

  if (!挑中了) return null;
  return 方方站位.addScaledVector(选中的朝向, CELL_SIZE * 浮出表面);
}

/** 镜头跟着折叠度一起收：摊平时退远看整张纸，合上时凑近看正方体 */
function 对准衣服() {
  if (!当前展示) return;
  舞台.框住(当前展示.boundingBox());
}

