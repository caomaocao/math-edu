/**
 * 只有折到底、而且真的合上了才让点。
 * 半折和摊平的时候「对面」根本还不存在 —— 那会儿六个格子还是平摊的一张纸，
 * 这时候亮两格等于凭空告诉孩子一条规则，正是这一票要避免的。
 */
function 能看对面() {
  return Boolean(合上的结果 && 对面高亮 && 当前展示 instanceof FoldedNet);
}

function 点中一个面(格子下标) {
  if (!能看对面()) return;
  const 一对 = 找对面(合上的结果, 格子下标);
  if (!一对) return;

  // 三维和平面必须**同一时刻**亮：孩子就是靠这一下把正方体上的关系搬回衣服上的
  对面高亮.显示(一对.格子, 一对.序);
  格子纸.设对面高亮(
    一对.格子.map((下标) => 当前展示.cells[下标]),
    对面色(一对.序),
  );
  说(沙盒话().这是对面);
}

/** 点空白处：取消高亮，正方体恢复不透明。不说话 —— 没什么可说的 */
function 收起对面() {
  对面高亮?.清除();
  格子纸?.设对面高亮([]);
}

