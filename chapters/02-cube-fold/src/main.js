/*
  开始遮罩 —— Chrome 不许没人动过手的页面自己出声。
  孩子点那个 ▶ 就是「动过手了」：这一下解锁音频，遮罩收起来，方方才开得了口。
  没有这一下，孩子进来看见的是一个哑巴网站，而他不认字，等于什么提示都没有。
*/
function 开场() {
  const 遮 = document.getElementById('开始遮罩');
  const 钮 = document.getElementById('开始钮');
  // 预热不用在这儿排队了：`备话(供话)` 自己会给正在说的话让路（票 07）
  const 说开场白 = () => Promise.resolve(说(开场白()));
  if (!遮 || !钮) return 说开场白();

  钮.addEventListener(
    'click',
    () => {
      /*
        解锁音频要是抛了（没有 AudioContext、浏览器不给），遮罩也必须照样收起来。
        这是孩子进门的唯一一扇门，而且只响应一次 —— 在它前面放任何可能抛错的东西，
        代价就是孩子对着一个点不动的开始页干等，他不认字，连出了什么事都问不出来。
      */
      try {
        解锁音频();
      } catch {
        // 没声音也让他玩，说() 那边还有 Web Speech 兜底
      }
      遮.classList.add('收起');
      遮.inert = true;
      说开场白();
    },
    { once: true },
  );
}

