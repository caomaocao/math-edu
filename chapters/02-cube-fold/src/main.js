/** @type {ReturnType<typeof 借麦克风>|null} 沙盒手里那一把。不是主人了就说明被借走了 */
let 沙盒麦 = null;

async function 一直听着(麦) {
  for (;;) {
    let 文;
    try {
      // 带上 🔊：沙盒里它就是「方方刚才说啥来着」。不给的话 问答.js 会把它拆了，
      // 而不是留一个点了没反应的死按钮在孩子面前
      文 = await 麦.听一句(口令热词(), { 重听: 再说一遍 });
    } catch {
      return; // 坞根本没装起来：语音这条路今天没有，孩子照样用手点着折
    }
    if (是被打断(文)) {
      // 别的玩法把坞借走了（或者沙盒自己离场了）：退场，切回沙盒时再起一条新的
      if (!麦.是主人()) return;
      continue;
    }
    const 口令 = 听口令(文);

    if (!折叠) {
      // 还没画出一件能折的衣服，先别让他以为喊错了
      await 说(沙盒话().先画一件);
      continue;
    }
    if (口令 === '穿衣服') {
      取消摊回();
      折纸声({ 轻重: 1 });
      折叠.全体设(1); // 六条折痕一起走，动画交给折叠状态
    } else if (口令 === '脱衣服') {
      取消摊回();
      折纸声({ 轻重: 0.7 });
      折叠.全体设(0);
      折叠动过();
    } else if (文) {
      await 说(沙盒话().没听清口令);
    }
  }
}

/** 切回沙盒：重新借一把、重新起循环。已经端着就什么都不做（别开出第二条来） */
function 起听着() {
  if (沙盒麦?.是主人()) return;
  沙盒麦 = 借麦克风('沙盒');
  一直听着(沙盒麦);
}

