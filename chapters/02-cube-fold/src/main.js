/**
 * 孩子每点一格，整张衣服就重建一次。材质要是跟着重建，
 * 每点一下就要重画六张 canvas 贴图再传一次显卡 —— 所以按槽位存下来一直用。
 * FoldedNet / PaperPreview 的 dispose 只收自己造的材质，不会把这几份收掉。
 */
const 材质池 = new Map();
function 槽位材质(槽位) {
  if (!材质池.has(槽位)) {
    材质池.set(
      槽位,
      new THREE.MeshBasicMaterial({
        map: makeCellTexture(cellStyle(槽位)),
        side: THREE.DoubleSide,
        toneMapped: false,
      }),
    );
  }
  const 材质 = 材质池.get(槽位);
  // 是共用的，取用前先把上一张衣服借去用的那几项全归位
  材质.color.setHex(0xffffff);
  材质.transparent = false; // 点面看对面时借去当半透明用（见 oppositeGlow.js）
  材质.opacity = 1;
  材质.depthWrite = true;
  材质.needsUpdate = true;
  return 材质;
}

