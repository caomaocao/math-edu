// ---------------------------------------------------------------------------
// 对面：一律现算
// ---------------------------------------------------------------------------

const 找一格 = (格子, row, col) => 格子.findIndex((c) => c.row === row && c.col === col);

/**
 * 这张衣服折起来以后，哪三对格子成了对面。
 *
 * @param {ReadonlyArray<{row:number, col:number}>} 格子
 * @returns {Array<[number, number]>} 3 对格子下标，按 x/y/z 三条轴排（次序稳定）
 */
export function 对面配对(格子) {
  if (!isNet(格子) || !canClose(格子)) {
    // 书上「找对面」的题必然是能折成正方体的。誊错了坐标要当场炸，
    // 别等孩子贴了半天水果才发现这张衣服根本穿不上、压根没有对面可言。
    throw new Error('这张衣服折不成正方体，谈不上对面');
  }
  return 对面格子对(foldResult(格子)).map((一对) => [...一对.格子]);
}

/**
 * 某一格的对面是哪一格。
 * @returns {number} 格子下标
 */
export function 对面下标(格子, 下标) {
  const 一对 = 对面配对(格子).find((对) => 对.includes(下标));
  if (!一对) throw new Error(`格子下标越界：${下标}`);
  return 一对.find((i) => i !== 下标);
}

