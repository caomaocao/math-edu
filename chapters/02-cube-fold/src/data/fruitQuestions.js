/** 贴纸板的框子：够装下最宽最高的那张衣服，所有题共用一个尺寸，换题时板子不跳 */
export const 板列数 = Math.max(...题库.map((t) => Math.max(...t.格子.map((c) => c.col)) + 1));
export const 板行数 = Math.max(...题库.map((t) => Math.max(...t.格子.map((c) => c.row)) + 1));

/**
 * 把一张衣服摆到贴纸板的正中间。纯函数，不碰 DOM。
 *
 * 判断关的 data/bookQuestions.js 里有一个同样的 摆中间 —— 这里刻意不引它：
 * 那份是判断关自己题卡（另一个尺寸）的东西，两关的题库不该为了省八行互相拴住。
 *
 * @returns {Array<{row:number, col:number, 下标:number}>} 下标 = 在 `格子` 里的位置，
 *   平面板上第 n 格和三维里第 n 个面是同一格
 */
export function 居中摆(格子, 列数 = 板列数, 行数 = 板行数) {
  const rows = 格子.map((c) => c.row);
  const cols = 格子.map((c) => c.col);
  const 高 = Math.max(...rows) - Math.min(...rows) + 1;
  const 宽 = Math.max(...cols) - Math.min(...cols) + 1;
  const 挪行 = Math.floor((行数 - 高) / 2) - Math.min(...rows);
  const 挪列 = Math.floor((列数 - 宽) / 2) - Math.min(...cols);
  return 格子.map((c, 下标) => ({ row: c.row + 挪行, col: c.col + 挪列, 下标 }));
}
