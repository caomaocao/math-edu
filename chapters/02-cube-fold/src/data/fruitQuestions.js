/**
 * 判对.js 的数字表里没有零 —— 两语都没有（那边是「第几行第几列」，行列从 1 起，
 * 用不上 0）。闯关三的格子上印着 0，孩子多半会说「零」或者 "zero"，
 * 先换成数字再交给 抽数字。
 */
const 补零 = (转写) =>
  String(转写 ?? '')
    .replace(/[零〇]/g, '0')
    .replace(/\b(?:zero|nought|nil)\b/gi, ' 0 ');

/** 从孩子说的话里抽出他答的那个数。听不出来是 null */
export function 听出数字(转写) {
  return 抽数字(补零(转写));
}

/**
 * 数字题判对。中文数字、「是三」「不是二，是三」都算（放宽交给 判对.js 的 抽数字）。
 * @returns {'对'|'错'|'不确定'}
 */
export function 判数字(转写, 正确) {
  const 说的 = 听出数字(转写);
  if (说的 === null) return '不确定';
  return 说的 === 正确 ? '对' : '错';
}

