export const 水果 = (槽位) => 水果们[槽位 % 水果们.length];

/**
 * 这个水果这一语怎么叫。界面上要念名字的地方（鼠标扫过水果盘、贴上去以后的读屏标签）
 * 一律走它，不许直接摸 `.名`。
 * @param {number} 槽位
 * @param {'cn'|'en'} [语]
 */
export function 水果名(槽位, 语 = 当前语言()) {
  const 名 = 水果(槽位).名;
  return 名[语] ?? 名.cn;
}

/**
 * 孩子对着麦克风说了个水果名，说的是哪一个。
 *
 * 判定只在**这一题摆出来的几种水果**里做：题上只有苹果和香蕉时，
 * 孩子随口说的别的词不该被认成第三种水果贴上去。
 * 「最后提到的算数」跟 判对.js 一个规矩，给自我纠正留门（「香蕉……不对，苹果！」）。
 * 接受集合恒为**两语并集**，跟现在是哪一语无关。
 *
 * @param {string} 转写
 * @param {number[]} [可选槽位] 这一题摆出来的水果
 * @returns {number|null} 水果槽位；一个都没听出来是 null
 */
export function 听出水果(转写, 可选槽位 = 水果们.map((一个) => 一个.槽位)) {
  const 命中 = 找方位词(归一化(转写), 水果词表(可选槽位));
  if (命中.length === 0) return null;
  const 名 = 命中[命中.length - 1];
  return 水果们.find((一个) => 一个.名.cn === 名)?.槽位 ?? null;
}

/** 这一题几种水果的两语词表。`听出水果` 和喂给 ASR 的热词共用它 */
export function 水果词表(可选槽位 = 水果们.map((一个) => 一个.槽位)) {
  return 建词表(
    可选槽位.map((槽位) => ({
      答: 水果(槽位).名.cn,
      别名: [水果(槽位).名.en, ...水果(槽位).别名],
      英: [...水果(槽位).英],
    })),
  );
}

