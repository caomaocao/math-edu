/**
 * 一张贴水果的题：哪几格书上已经有水果了，孩子要往哪几格贴。
 *
 * 两种来源，规矩不同，都照着书来：
 *   · 例题3 —— 书上已经涂好红、黄两格，孩子只要补这两格的对面（另外两格留白，书上也是留白的）。
 *   · 练一练 / 闯关二 —— 书上是空白的，题面是「找到对面，涂上相同的颜色」，
 *     所以三对各先贴好一格（每对里下标小的那一格），孩子把剩下三格补齐，
 *     六格正好三对，跟书上一张图涂满三种颜色对得上。
 *
 * 「每对里下标小的那一格」是算出来的，不是挑出来的 —— 换句话说，
 * 这里也没有第二份对面表。
 */
function 建贴水果题(一张) {
  const { 格子 } = 一张;
  const 配对 = 对面配对(格子);

  const 已贴 = 一张.书上涂了
    ? 一张.书上涂了.map(({ row, col, 槽位 }) => {
        const 下标 = 找一格(格子, row, col);
        if (下标 === -1) throw new Error(`「${一张.号}」书上涂的那一格 (${row},${col}) 不在衣服上`);
        return { 下标, 槽位 };
      })
    : 配对.map((一对, 序) => ({ 下标: Math.min(...一对), 槽位: 序 }));

  const 答案 = 已贴.map(({ 下标, 槽位 }) => ({ 从: 下标, 贴到: 对面下标(格子, 下标), 槽位 }));

  return Object.freeze({
    ...一张,
    种类: '水果',
    格子: Object.freeze(格子),
    已贴: Object.freeze(已贴.map(Object.freeze)),
    答案: Object.freeze(答案.map(Object.freeze)),
    /** 这一题摆出来的几种水果（水果盘就摆这几个，语音也只在这几个里认） */
    水果槽位: Object.freeze(已贴.map((一个) => 一个.槽位)),
  });
}

function 建数字题(一张) {
  const { 格子, 数字 } = 一张;
  if (数字.length !== 格子.length) throw new Error(`「${一张.号}」数字和格子对不上`);
  const 问下标 = 找一格(格子, ...一张.问哪格);
  if (问下标 === -1) throw new Error(`「${一张.号}」要问的那一格不在衣服上`);
  const 答下标 = 对面下标(格子, 问下标);

  return Object.freeze({
    ...一张,
    种类: '数字',
    格子: Object.freeze(格子),
    数字: Object.freeze(数字),
    问下标,
    答下标,
    /** 被问那一格上的数 */
    问的数: 数字[问下标],
    /** 它对面那一格上的数 —— 孩子要喊出来的第一个答案 */
    对面数: 数字[答下标],
    /** 两个加起来 —— 第二个答案 */
    和: 数字[问下标] + 数字[答下标],
  });
}

