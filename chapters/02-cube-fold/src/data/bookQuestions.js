/**
 * 题库。每题的 `能合上` 是 canClose 现算出来的，不是抄的答案页。
 * @type {ReadonlyArray<{号: string, 出处: string, 格子: ReadonlyArray<{row:number, col:number}>, 能合上: boolean}>}
 */
export const 题库 = Object.freeze(
  书上的形状.map((一题) => {
    if (!isNet(一题.格子)) {
      // 誊错了坐标（少一格、多一格、断开了）就在这儿炸，别等孩子做到第九题才发现
      throw new Error(`题库里「${一题.号}」不是一张能拿去折的衣服，坐标誊错了`);
    }
    return Object.freeze({ ...一题, 格子: Object.freeze(一题.格子), 能合上: canClose(一题.格子) });
  }),
);

/** 一共几题 */
export const 题数 = 题库.length;

/** 题卡的框子：够装下题库里最宽最高的那张衣服，所有题共用同一个尺寸，换题时卡片不跳 */
export const 题卡列数 = Math.max(...题库.map((t) => Math.max(...t.格子.map((c) => c.col)) + 1));
export const 题卡行数 = Math.max(...题库.map((t) => Math.max(...t.格子.map((c) => c.row)) + 1));

/**
 * 把一张衣服摆到题卡框子的正中间。
 * 纯函数，不碰 DOM。
 *
 * @param {ReadonlyArray<{row:number, col:number}>} 格子
 * @returns {Array<{row:number, col:number, 槽位:number}>} 槽位 = 原来的下标，
 *   所以平面上第 n 格和三维里第 n 个面是同一个颜色、同一个水果
 */
export function 摆中间(格子, 列数 = 题卡列数, 行数 = 题卡行数) {
  const rows = 格子.map((c) => c.row);
  const cols = 格子.map((c) => c.col);
  const 高 = Math.max(...rows) - Math.min(...rows) + 1;
  const 宽 = Math.max(...cols) - Math.min(...cols) + 1;
  const 挪行 = Math.floor((行数 - 高) / 2) - Math.min(...rows);
  const 挪列 = Math.floor((列数 - 宽) / 2) - Math.min(...cols);
  return 格子.map((c, 下标) => ({ row: c.row + 挪行, col: c.col + 挪列, 槽位: 下标 }));
}
