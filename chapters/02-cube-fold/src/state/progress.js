/**
 * 进度 —— 孩子攒下来的东西，存在浏览器里，关掉再开还在。
 *
 * 一份进度里四格，一个玩法一格：
 *   图鉴   —— 11 种衣服点亮了哪几种，存的是「规范键」，转个方向画出来的算同一种
 *   判断关 —— 猜一猜每题对没对，存 题目号 → true/false
 *   贴水果 —— 对面关每题对没对，同上
 *   沙盒   —— 孩子手上那张没画完的衣服，刷新回来还在
 *
 * 这里只负责**存**，不负责往里填东西。所以它不认识什么叫「有效展开图」，
 * 也不认识题目长什么样，只认键和布尔值。
 *
 * 任何一步都不许抛错 —— 浏览器可能是无痕模式、可能存满了、
 * 上一版的数据可能对不上号。存不下就当没存过，孩子照样能玩，只是攒不住。
 */

/** 换了 schema 就换这个数字，读到对不上的旧数据一律当没有 */
export const 进度版本 = 2;
const 键前缀 = 'cube-fold:进度:v';
export const 存储键 = `${键前缀}${进度版本}`;
/** 上一版的键。新版第一次打开时去这儿把孩子收集的衣服接过来 */
export const 上一版存储键 = `${键前缀}${进度版本 - 1}`;

/**
 * 一份干干净净的空进度。
 *
 * `戳` 是**重置戳**（epoch 毫秒），跨设备同步时用来判「谁清过、谁没清」，
 * 免得 A 机点了重来、B 机的旧本地一同步又把星星刷活（详见 合并()）：
 *   · 整包  —— 「重来」打，盖过一切分区
 *   · 判断关/贴水果 —— 各自「清」打，只盖自己那格
 *   · 沙盒  —— 每次「存沙盒」打，用来判那张没画完的衣服哪台更新
 * 没有 `清图鉴` 这种操作，所以图鉴不带自己的戳，只受整包戳管（并集只增不减）。
 * 老 v2 数据没有这个字段，读回来当全 0（= 从没重置过），向后兼容，所以**不升版本**。
 */
export function 空进度() {
  return {
    版本: 进度版本,
    图鉴: { 已解锁: [] },
    判断关: { 作答: {} },
    贴水果: { 作答: {} },
    沙盒: { 格子: [] },
    戳: { 整包: 0, 判断关: 0, 贴水果: 0, 沙盒: 0 },
  };
}

const 是对象 = (x) => typeof x === 'object' && x !== null && !Array.isArray(x);
const 是整数 = (x) => Number.isInteger(x);
const 是非负整数 = (x) => Number.isInteger(x) && x >= 0;

/** 当前时刻（epoch 毫秒）—— 重置戳、沙盒新旧都用它。抽成一处，语义清楚。 */
const 现在 = () => Date.now();

/** 洗一份「题目号 → 对错」出来，只认布尔值 */
function 洗作答(原始) {
  const 干净 = {};
  if (!是对象(原始) || !是对象(原始.作答)) return 干净;
  for (const [题目, 对不对] of Object.entries(原始.作答)) {
    if (typeof 对不对 === 'boolean') 干净[题目] = 对不对;
  }
  return 干净;
}

/** 洗一份重置戳出来：四格各要一个非负整数，缺的、坏的一律当 0（从没重置过） */
function 洗戳(原始) {
  const 干净 = { 整包: 0, 判断关: 0, 贴水果: 0, 沙盒: 0 };
  if (!是对象(原始)) return 干净;
  for (const 键 of Object.keys(干净)) {
    if (是非负整数(原始[键])) 干净[键] = 原始[键];
  }
  return 干净;
}

/** 洗一串图鉴键出来：去重、丢掉空的和不是字符串的 */
function 洗图鉴(原始) {
  const 干净 = [];
  if (!是对象(原始) || !Array.isArray(原始.已解锁)) return 干净;
  const 见过 = new Set();
  for (const 键 of 原始.已解锁) {
    if (typeof 键 !== 'string' || 键 === '' || 见过.has(键)) continue;
    见过.add(键);
    干净.push(键);
  }
  return 干净;
}

/**
 * 把从存储里读回来的东西洗成一份合法的进度。
 * 缺的补上、多的丢掉、类型不对的当没有 —— 只进不出地保证后面的代码拿到的形状是对的。
 *
 * 纯函数，不碰存储，可以直接跑单元测试。
 *
 * @param {unknown} 原始
 * @returns {ReturnType<typeof 空进度>}
 */
export function 规范化进度(原始) {
  const 干净 = 空进度();
  if (!是对象(原始)) return 干净;
  if (原始.版本 !== 进度版本) return 干净;

  干净.图鉴.已解锁 = 洗图鉴(原始.图鉴);
  干净.判断关.作答 = 洗作答(原始.判断关);
  干净.贴水果.作答 = 洗作答(原始.贴水果);
  干净.戳 = 洗戳(原始.戳);

  if (是对象(原始.沙盒) && Array.isArray(原始.沙盒.格子)) {
    for (const 格 of 原始.沙盒.格子) {
      if (!是对象(格)) continue;
      if (!是整数(格.row) || !是整数(格.col) || !是整数(格.槽位)) continue;
      干净.沙盒.格子.push({ row: 格.row, col: 格.col, 槽位: 格.槽位 });
    }
  }

  return 干净;
}

/**
 * 把上一版的进度搬进这一版。
 *
 * **只搬图鉴。** 孩子在旧版里画出来的那几件衣服是他真实攒下的东西，
 * 网站改版不能把它清零 —— 收集册空了，对五岁孩子是实实在在的损失。
 * 判断关不搬：题目从 13 道变成 17 道，旧作答对不上新题号，
 * 搬过来只会让猫猫亮在错误的位置上。沙盒那张没画完的衣服也不搬，重画一下就有。
 *
 * 纯函数，不碰存储。
 *
 * @param {unknown} 旧的 上一版存储键里那份东西
 * @returns {ReturnType<typeof 空进度>} 搬不动就是一份空进度
 */
export function 迁移旧进度(旧的) {
  const 新的 = 空进度();
  if (!是对象(旧的)) return 新的;
  if (旧的.版本 !== 进度版本 - 1) return 新的; // 不是上一版就别乱认
  新的.图鉴.已解锁 = 洗图鉴(旧的.图鉴);
  return 新的;
}

