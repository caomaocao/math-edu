/**
 * 把任意一端（可能 null / 旧版本 / 坏形状）洗成一份合法整包，喂给 合并()。
 * 正是这一版 → 规范化；上一版 → 迁移（和「开张」一个规矩，只救得回图鉴）；其它 → 空。
 * 云端存的可能是别台设备旧代码写的老 payload，脏数据在这儿一次性挡住。
 */
function 洗一份(原始) {
  if (是对象(原始) && 原始.版本 === 进度版本 - 1) return 迁移旧进度(原始);
  return 规范化进度(原始);
}

/** 图鉴并集：本地在前、云端里本地没有的接在后面，去重。只增不减。 */
function 图鉴并集(甲们, 乙们) {
  const 结果 = [];
  const 见过 = new Set();
  for (const 键 of [...甲们, ...乙们]) {
    if (见过.has(键)) continue;
    见过.add(键);
    结果.push(键);
  }
  return 结果;
}

/** 逐题合并作答：只在一边有的都留着；两边同题都有值且不同 → **本地（甲）胜**。 */
function 合作答(甲, 乙) {
  return { ...乙, ...甲 }; // 甲 后展开：同题冲突本地压过云端，同时并进只在云端的题
}

/** 某一侧、某一分区的**有效重置戳** = max(整包戳, 该分区戳)。整包戳（重来打）盖过一切。 */
function 有效戳(一份, 分区) {
  return Math.max(一份.戳.整包, 一份.戳[分区] ?? 0);
}

/**
 * 合并本地与云端两份进度 —— 云同步.js 的接缝（那儿的 doc 讲了什么时候调）。
 *
 * 两参**任一可能为 null**（对方还没这个键），也可能是旧版本 / 坏形状；先各自过
 * 洗一份() 洗成合法整包再合并，脏数据炸不到这儿。返回一份合法整包（= 空进度() 的形状）。
 *
 * 逐分区决定谁说了算，靠「有效重置戳」比大小：
 *   一侧有效戳更大 → 该分区**整侧照搬**那一侧（**不做并集**）—— 这是「重来 / 清」压得住
 *     另一台旧数据的关键，不然重来后星星会从另一台诈尸回来；
 *   戳相同才按字段合并：
 *     · 图鉴 已解锁 —— 并集，只增不减（孩子攒的衣服一件不少；图鉴只受整包戳管）
 *     · 判断关 / 贴水果 作答 —— 逐题取有值的，冲突**本地胜**（这台是孩子刚玩出来的记忆）
 *     · 沙盒 格子 —— 谁新谁赢，戳同则本地胜（那张没画完的衣服以手边这台为准）
 * 合并后每个戳取两侧较大值，把「最近一次重置发生在何时」原样带下去，下一轮同步不丢。
 *
 * 纯函数，不碰存储 / 网络，进 node --test。本地 = 甲、云端 = 乙，一切「平手本地胜」都靠这个次序。
 *
 * @param {unknown} 本地
 * @param {unknown} 云端
 * @returns {ReturnType<typeof 空进度>}
 */
export function 合并(本地, 云端) {
  const 甲 = 洗一份(本地);
  const 乙 = 洗一份(云端);
  const 果 = 空进度();

  // 合并后的戳：两侧逐项取大，重置这件事的记忆只增不减
  for (const 键 of Object.keys(果.戳)) {
    果.戳[键] = Math.max(甲.戳[键], 乙.戳[键]);
  }

  // 图鉴：没有单分区清，有效戳就是整包戳
  if (甲.戳.整包 > 乙.戳.整包) 果.图鉴.已解锁 = [...甲.图鉴.已解锁];
  else if (乙.戳.整包 > 甲.戳.整包) 果.图鉴.已解锁 = [...乙.图鉴.已解锁];
  else 果.图鉴.已解锁 = 图鉴并集(甲.图鉴.已解锁, 乙.图鉴.已解锁);

  // 判断关 / 贴水果：整侧照搬，或逐题取有值、冲突本地胜
  for (const 关 of ['判断关', '贴水果']) {
    const 甲有效 = 有效戳(甲, 关);
    const 乙有效 = 有效戳(乙, 关);
    if (甲有效 > 乙有效) 果[关].作答 = { ...甲[关].作答 };
    else if (乙有效 > 甲有效) 果[关].作答 = { ...乙[关].作答 };
    else 果[关].作答 = 合作答(甲[关].作答, 乙[关].作答);
  }

  // 沙盒：整侧照搬，或谁新谁赢（戳同本地胜）
  const 甲沙 = 有效戳(甲, '沙盒');
  const 乙沙 = 有效戳(乙, '沙盒');
  const 胜出沙盒 = 乙沙 > 甲沙 ? 乙.沙盒.格子 : 甲.沙盒.格子;
  果.沙盒.格子 = 胜出沙盒.map((格) => ({ ...格 }));

  return 果;
}

/** 没有 localStorage（无痕模式、跑单元测试）时顶上，玩得了，只是关掉就没了 */
export function 内存存储() {
  const 里面 = new Map();
  return {
    getItem: (k) => (里面.has(k) ? 里面.get(k) : null),
    setItem: (k, v) => 里面.set(k, String(v)),
    removeItem: (k) => 里面.delete(k),
  };
}

function 默认存储() {
  try {
    const 存储 = globalThis.localStorage;
    if (!存储) return 内存存储();
    // 无痕模式下 localStorage 存在但一写就抛，先探一下
    const 探针 = `${存储键}:探针`;
    存储.setItem(探针, '1');
    存储.removeItem(探针);
    return 存储;
  } catch {
    return 内存存储();
  }
}

/**
 * 造一个进度存储。
 *
 * @param {{ 存储?: {getItem, setItem, removeItem} }} [选项] 不传就用 localStorage
 */
export function 创建进度存储({ 存储 = 默认存储() } = {}) {
  const 听众 = new Set();
  let 当前 = 开张();

  function 读键(键) {
    try {
      const 文本 = 存储.getItem(键);
      return 文本 ? JSON.parse(文本) : null;
    } catch {
      return null; // 读不了、或者存的是坏 JSON
    }
  }

  /**
   * 第一次读。这一版有数据就用这一版的；一点都没有才去上一版那儿搬。
   * 搬过来的立刻落到新键上，不然下次打开又要现搬一遍。
   */
  function 开张() {
    const 这一版 = 读键(存储键);
    if (是对象(这一版) && 这一版.版本 === 进度版本) return 规范化进度(这一版);

    const 搬来的 = 迁移旧进度(读键(上一版存储键));
    if (搬来的.图鉴.已解锁.length > 0) {
      try {
        存储.setItem(存储键, JSON.stringify(搬来的));
      } catch {
        // 落不了盘就算了，这一局照样是搬过来的样子
      }
    }
    return 搬来的;
  }

  function 落盘() {
    try {
      存储.setItem(存储键, JSON.stringify(当前));
    } catch {
      // 存满了或者不让存。孩子这一局照样玩得下去，只是攒不住，不打断他
    }
  }

  function 广播() {
    const 一份 = 读();
    for (const 听 of 听众) {
      try {
        听(一份);
      } catch {
        // 一个听众炸了不能连累别的
      }
    }
  }

  /** 读一份拷贝出来，外面怎么改都动不到里面 */
  function 读() {
    return structuredClone(当前);
  }

  /**
   * 改一改再存下去。`改法` 拿到的是一份可以随便改的草稿。
   * @param {(草稿: ReturnType<typeof 空进度>) => void} 改法
   */
  function 改(改法) {
    const 草稿 = structuredClone(当前);
    改法(草稿);
    当前 = 规范化进度(草稿);
    落盘();
    广播();
    return 读();
  }

  /** 这个键以前没点亮过吗 */
  function 是新衣服(键) {
    return typeof 键 === 'string' && 键 !== '' && !当前.图鉴.已解锁.includes(键);
  }

  /**
   * 一本关卡账本：记一题、查一题、清一关、报成绩。
   *
   * 猜一猜和贴水果攒的是同一种东西（题目号 → 对错），只有存哪一格不同，
   * 所以两关共用这一份，不各抄一遍 —— 抄一遍就意味着以后修一个 bug 要修两处，
   * 而漏掉的那一处会让某一关的猫猫算错分。
   *
   * @param {'判断关'|'贴水果'} 关名 进度里的哪一格
   */
  function 建账本(关名) {
    const 本子 = () => 当前[关名].作答;
    return {
      /** 记下某道题对没对。同一题再答一次会覆盖 */
      记(题目, 对不对) {
        改((草稿) => {
          草稿[关名].作答[String(题目)] = Boolean(对不对);
        });
      },
      /** @returns {boolean|null} 没答过是 null */
      查(题目) {
        const 值 = 本子()[String(题目)];
        return typeof 值 === 'boolean' ? 值 : null;
      },
      /**
       * 只清这一关的作答，全部题目从头再来一遍。
       *
       * 孩子做完一整关以后想再玩，猫猫得能重新一只一只点亮 ——
       * 猫猫要是一直亮着，重玩就没了盼头。别的玩法不受连累：
       * 那是别处攒下的东西，凭什么因为他想再猜一遍就没了。
       */
      清() {
        改((草稿) => {
          草稿[关名].作答 = {};
          // 打一个分区重置戳：另一台设备的旧作答同步回来时，别把这一关又刷活
          草稿.戳[关名] = 现在();
        });
      },
      /** @returns {{答过:number, 答对:number, 作答:Record<string, boolean>}} */
      成绩() {
        const 全部 = Object.values(本子());
        return {
          答过: 全部.length,
          答对: 全部.filter(Boolean).length,
          作答: { ...本子() },
        };
      },
    };
  }

  const 猜一猜 = 建账本('判断关');
  const 贴水果 = 建账本('贴水果');

  return {
    读,
    改,

    // --- 图鉴 -----------------------------------------------------------

    /** @returns {string[]} 点亮了哪几种衣服 */
    已解锁图鉴() {
      return [...当前.图鉴.已解锁];
    },
    图鉴数() {
      return 当前.图鉴.已解锁.length;
    },
    是新衣服,
    /**
     * 点亮一格。
     * @returns {boolean} 这一格是不是**刚刚**才点亮的 —— 只有 true 才该庆祝
     */
    解锁图鉴(键) {
      if (!是新衣服(键)) return false;
      改((草稿) => 草稿.图鉴.已解锁.push(键));
      return true;
    },

    // --- 两关的作答：同一本账本，各记各的 --------------------------------

    记判断关: 猜一猜.记,
    查判断关: 猜一猜.查,
    清判断关: 猜一猜.清,
    判断关成绩: 猜一猜.成绩,

    记贴水果: 贴水果.记,
    查贴水果: 贴水果.查,
    清贴水果: 贴水果.清,
    贴水果成绩: 贴水果.成绩,

    // --- 沙盒里没画完的那张衣服 ------------------------------------------

    存沙盒(格子) {
      改((草稿) => {
        草稿.沙盒.格子 = Array.isArray(格子) ? 格子 : [];
        // 每次存都盖一个新戳：跨设备合并时用它认出「那张没画完的衣服」哪台更新
        草稿.戳.沙盒 = 现在();
      });
    },
    取沙盒() {
      return 当前.沙盒.格子.map((c) => ({ ...c }));
    },

    // --- 重来 ------------------------------------------------------------

    /**
     * 全部清掉，从头开始。
     * 上一版那份也一并删掉 —— 留着的话下次打开又会被当成「有旧进度」搬回来，
     * 孩子明明点了清，衣服却还在，那这个按钮就是骗人的。
     */
    重来() {
      当前 = 空进度();
      // 整包重置戳：让「清空」这件事能跨设备传出去 —— 另一台的旧本地一同步，
      // 有效戳更小的那侧整块作废，星星不会从别处诈尸回来（云同步的 立即推 随后把它推上去）
      当前.戳.整包 = 现在();
      for (const 键 of [存储键, 上一版存储键]) {
        try {
          存储.removeItem(键);
        } catch {
          // 删不掉就算了，下面照样会写一份空的盖上去
        }
      }
      落盘();
      广播();
      return 读();
    },

    /**
     * 云同步把两端合并的结果交回来：整包换掉内存态、落盘、广播刷界面。
     *
     * **必须同步执行**：云同步引擎在调这个期间压着 记脏() 防 ping-pong，
     * 异步走就漏出了这个 guard（见 /shared/js/云同步.js 的约束 2）。
     * 走的是和 改() 一样的落盘 + 广播路，所以图鉴 / 贴水果那几个订阅了进度的界面会自动重画。
     */
    收编(整包) {
      当前 = 规范化进度(整包);
      落盘();
      广播();
      return 读();
    },

    /**
     * 进度一变就叫你一声（图鉴要靠它自己刷新）。
     * @returns {() => void} 退订
     */
    订阅(听) {
      听众.add(听);
      return () => 听众.delete(听);
    },
  };
}

