// 摆放站 —— 「开场 → 一轮一轮玩摆放 → 点星收尾」的车站工厂。
// 果盘 / 糖葫芦 / 装货 三站曾是逐字的三胞胎（只差数据、排布、台词键）——
// 三份必漂移（共享件那两次的老路），所以骨架收在这一处，三站各自只报数据。
// 各站文件仍单独存在：号=文件名=面板 id 的三方对齐、实体们 的覆盖/预热接缝都不变。

import { 说 } from '/shared/js/说话.js';
import { 做进度点 } from '/shared/js/搭台.js';
import { 玩一轮 } from '/shared/js/摆放.js';
import { 台词 } from './台词表.js';
import { 摆放配 } from './组件.js';

/**
 * 造摆放站({号, 排布, 轮们, 轮话键们}) → 创建(面板, 工具)。
 *   号       环节号（= 台词表里这一摊的键 = 完成() 点星的键）
 *   排布     '横' | '竖' | '塔'（传给摆放引擎）
 *   轮们     数据.js 里这一站的轮次数组（{实体?/料?, 值们, 空}）
 *   轮话键们 每轮开场那句在台词表这一摊里的键（['草莓轮','苹果轮']……）
 */
export function 造摆放站({ 号, 排布, 轮们, 轮话键们 }) {
  return function 创建(面板, 工具) {
    面板.innerHTML = `
      <div class="舞台布">
        <div class="大画框"><div class="摆放挂点"></div></div>
        <div class="进度点挂"></div>
      </div>`;
    const 挂 = 面板.querySelector('.摆放挂点');
    const 点 = 做进度点(面板.querySelector('.进度点挂'), 轮们.length);
    let 局 = 0;

    async function 进入() {
      const 本局 = ++局;
      const 还在 = () => 局 === 本局 && 面板.classList.contains('在前');
      const 话 = 台词[号]; // 读的这一刻取（合并视图），换语言重进自然换课
      点.清零();

      for (const [i, 题] of 轮们.entries()) {
        if (!还在()) return;
        // 先把台子摆出来再开口——空的 .摆放挂点 会让 .大画框 塌成一个只剩 padding 的
        // 小方块，孩子看着像卡住了。但摆出来的台子在念完话之前是**锁着的**（闸没开，
        // 玩一轮 的点击和汽笛一律不理）：花圃/山洞的先例摆的本就是不可交互的画面；
        // 台子一上来就活着的话，孩子抢在开场白里连拉三下汽笛，三次机会梯子会在题目
        // 念完前把这一轮自动演完（评审抓的雷）。
        let 闸开 = false;
        const 局内 = 玩一轮({ 挂点: 挂, 题: { ...题, 排布 }, 配: 摆放配, 走查: () => 闸开 && 还在() });
        if (i === 0) { await 说(话.开场); if (!还在()) return; }
        await 说(话[轮话键们[i]]);
        if (!还在()) return;
        闸开 = true;
        await 局内;
        if (!还在()) return;
        点.点亮(i);
      }

      if (!还在()) return;
      await 工具.完成(号);
      if (!还在()) return;
      await 说(话.收尾);
    }

    return { 进入 };
  };
}
