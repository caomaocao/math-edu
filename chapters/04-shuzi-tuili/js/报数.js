// 报数 —— 「机器问一个数 → 孩子开口报 / 点数字瓦片 → 判对错」的一道题，报数站共用。
//
// 走共享 问答()（防呆/超时/三次机会/没听清亮备选/双语反馈都在里头，磨过一整轮，不自建），
// 只把「这一讲的数字」接进去：
//   · 判定走 数词.判数（共享判对的中文数字只到十，"十六"会被拆成"106"，不能用）；
//   · ASR 热词用 数词.说法们（中/阿/英并集，两语通吃）；
//   · 答对复述用 答说（按语言挑好的念法，龙杰力豆读「十六 / sixteen」而不是生读 "16"）；
//   · 备选钮是数字瓦片：正确项 + 几个近邻干扰项，嗓子哑了用手也能玩。

import { 说 } from '/shared/js/说话.js';
import { 问答 } from '/shared/js/问答.js';
import { 选 } from '/shared/js/语言.js';
import { 说法们, 判数, 中文数, 英文数 } from '/shared/js/数词.js';
import { 台词, 模板 } from './台词表.js';

/** 目标附近凑几个干扰项（都在 0~99 内、去重、含正确项），洗牌。 */
function 备选数们(目标) {
  const 候选 = new Set([目标]);
  for (const d of [1, -1, 2, -2]) {
    const n = 目标 + d;
    if (n >= 0 && n <= 99 && 候选.size < 4) 候选.add(n);
  }
  const 出 = [...候选];
  for (let i = 出.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [出[i], 出[j]] = [出[j], 出[i]];
  }
  return 出;
}

/**
 * 报一个数(目标, 选项) → {全对}。目标是 0~99 的整数。
 * 选项.问     题面（缺省用共享的「接下来该是几呢」）
 * 选项.提示   错第 2 次时叫（高亮参照 + 说提示）
 * 选项.教     错第 3 次时叫（缺省念「是十六，跟我数一遍」）
 */
export function 报一个数(目标, { 问, 提示, 教 } = {}) {
  return 问答({
    问: 问 ?? 台词.报数.接下来,
    接受们: [String(目标)],
    判: (文) => 判数(文, 目标),
    上下文: 说法们(目标).join('、'),
    答说: 选({ cn: 中文数(目标), en: 英文数(目标) }),
    提示,
    教: 教 ?? (async () => 说(模板.报数.教(目标))),
    备选: 备选数们(目标).map((n) => ({ 图: String(n), 答: String(n) })),
  });
}
