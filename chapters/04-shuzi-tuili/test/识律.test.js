import { test } from 'node:test';
import assert from 'node:assert/strict';

import { 识律, 补下 } from '../js/识律.js';

/*
  识律 —— 认本讲教的三族数字规律（票 06）。出题官用它「认出规律就夸好题」，
  找错车厢用它反向验证题库。纯函数，node 直接测。

  三族：等差（含负差）、差递增（差本身成等差）、交替（隔项两条线各自恒定或等差）。
  认不出返回 null，绝不抛。判族优先级：等差 > 交替 > 差递增（取最简解释）。
*/

// ── 等差 ─────────────────────────────────────────────────────────────────────

test('等差：正差 / 负差 / 跳步都认得', () => {
  assert.deepEqual(识律([1, 2, 3, 4]), { 族: '等差', 差: 1 });
  assert.deepEqual(识律([10, 8, 6, 4, 2]), { 族: '等差', 差: -2 });
  assert.deepEqual(识律([2, 5, 8, 11]), { 族: '等差', 差: 3 });
  assert.deepEqual(识律([10, 20, 30, 40]), { 族: '等差', 差: 10 });
});

test('等差 补下：接着往下推', () => {
  assert.deepEqual(补下([1, 2, 3, 4], 1), [5]);
  assert.deepEqual(补下([10, 8, 6, 4, 2], 1), [0]);
  assert.deepEqual(补下([10, 20, 30, 40], 3), [50, 60, 70]);
});

// ── 差递增 ───────────────────────────────────────────────────────────────────

test('差递增：差本身成等差', () => {
  assert.deepEqual(识律([2, 3, 5, 8]), { 族: '差递增', 差增: 1, 首差: 1 });
  assert.deepEqual(识律([1, 2, 4, 7, 11]), { 族: '差递增', 差增: 1, 首差: 1 });
});

test('差递增 补下', () => {
  assert.deepEqual(补下([2, 3, 5, 8], 2), [12, 17]);
  assert.deepEqual(补下([1, 2, 4, 7, 11], 1), [16]);
});

// ── 交替 ─────────────────────────────────────────────────────────────────────

test('交替：一条恒定、一条等差', () => {
  const r1 = 识律([3, 1, 3, 2, 3, 3, 3, 4]);
  assert.equal(r1.族, '交替');
  assert.deepEqual(补下([3, 1, 3, 2, 3, 3, 3, 4], 2), [3, 5]);

  const r2 = 识律([10, 2, 10, 4, 10, 6, 10, 8]);
  assert.equal(r2.族, '交替');
  assert.deepEqual(补下([10, 2, 10, 4, 10, 6, 10, 8], 2), [10, 10]);
});

test('交替：短到分不清就不硬认（4 项的差递增不会被当成交替）', () => {
  assert.equal(识律([2, 3, 5, 8]).族, '差递增');
});

// ── 认不出 / 边界 ─────────────────────────────────────────────────────────────

test('识律：乱序、太短、非数组 → null，不抛', () => {
  assert.equal(识律([3, 7, 2, 9, 4]), null);
  assert.equal(识律([7]), null);
  assert.equal(识律([]), null);
  assert.equal(识律(null), null);
  assert.equal(识律([1, 2]), null); // 两项太短，不算一条规律
});

test('补下：认不出规律给 null', () => {
  assert.equal(补下([3, 7, 2, 9, 4], 1), null);
});

test('等差优先于交替：2 4 6 8 是等差不是交替', () => {
  assert.deepEqual(识律([2, 4, 6, 8]), { 族: '等差', 差: 2 });
});
