import { test } from 'node:test';
import assert from 'node:assert/strict';
import { 规划路线, 试走 } from '../js/路线.js';
import { 生成小镇 } from '../js/小镇.js';
import { 建路网, 开车 } from '/shared/js/路网.js';

/*
  开车关的分段步数提示（规划路线）。纯逻辑，node 直接测。

  唯一要钉死的性质：**照着提示喊一遍，车真能开到，而且每段的格数 = 那一喊车真走的格数。**
  验法就是拿真·开车() 把返回的每一段走一遍（目的地当停靠点传进去，跟游戏里一模一样），
  看是不是正好落在终点、每段实走格数是否跟提示的数字对得上。跨很多随机小镇 + 手搭的几张
  边角地图都得成立。
*/

const 行数 = 6;
const 列数 = 7;
const 站点数 = 5;

function 造rng(种子) {
  let a = 种子 >>> 0;
  return function () {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const 键 = ({ 行, 列 }) => `${行},${列}`;

/**
 * 照着提示把车开一遍。每一段用真·开车()（目的地当停靠点，同游戏），
 * 顺手断言实走格数 == 提示格数。返回车最后停在哪。
 */
function 照走(网, 起, 终, 步们, 记 = '') {
  let 当 = 起;
  for (const [方, 数] of 步们) {
    const { 终点, 经过 } = 开车(网, 当, 方, [终]);
    assert.equal(经过.length, 数, `${记} 段[${方},${数}] 实走 ${经过.length} 格，对不上`);
    assert.ok(数 >= 1, `${记} 段[${方},${数}] 格数应 ≥1`);
    当 = 终点;
  }
  return 当;
}

test('起就是终 → 空提示', () => {
  const 网 = 建路网(6, 7, [{ 行: 1, 列: 1 }, { 行: 1, 列: 2 }]);
  assert.deepEqual(规划路线(网, { 行: 1, 列: 1 }, { 行: 1, 列: 1 }), []);
});

test('手搭：T 字路口，先开到路口再拐', () => {
  // row1 是横街，(1,2) 是丁字口，上下各挂一格
  const 路 = [
    { 行: 0, 列: 2 },
    { 行: 1, 列: 0 }, { 行: 1, 列: 1 }, { 行: 1, 列: 2 }, { 行: 1, 列: 3 }, { 行: 1, 列: 4 },
    { 行: 2, 列: 2 },
  ];
  const 网 = 建路网(3, 5, 路);
  const 步们 = 规划路线(网, { 行: 1, 列: 0 }, { 行: 2, 列: 2 });
  assert.deepEqual(步们, [['东', 2], ['南', 1]]);
  assert.equal(键(照走(网, { 行: 1, 列: 0 }, { 行: 2, 列: 2 }, 步们, 'T')), '2,2');
});

test('手搭：目的地在直街中段，靠停靠点刹住（不冲过头）', () => {
  const 路 = [0, 1, 2, 3, 4].map((列) => ({ 行: 0, 列 }));
  const 网 = 建路网(1, 5, 路);
  const 步们 = 规划路线(网, { 行: 0, 列: 0 }, { 行: 0, 列: 3 });
  assert.deepEqual(步们, [['东', 3]]);
  assert.equal(键(照走(网, { 行: 0, 列: 0 }, { 行: 0, 列: 3 }, 步们, '中段')), '0,3');
});

test('手搭：L 形，尽头停下再转弯', () => {
  const 路 = [{ 行: 0, 列: 0 }, { 行: 1, 列: 0 }, { 行: 1, 列: 1 }];
  const 网 = 建路网(2, 2, 路);
  const 步们 = 规划路线(网, { 行: 0, 列: 0 }, { 行: 1, 列: 1 });
  assert.deepEqual(步们, [['南', 1], ['东', 1]]);
  assert.equal(键(照走(网, { 行: 0, 列: 0 }, { 行: 1, 列: 1 }, 步们, 'L')), '1,1');
});

test('随机镇：从起点到每个站点，照提示喊一遍正好到站、每段格数对得上、每段 ≤3', () => {
  for (let 种 = 1; 种 <= 200; 种++) {
    const 镇 = 生成小镇({ 行数, 列数, 站点数, rng: 造rng(种) });
    const 网 = 建路网(行数, 列数, 镇.路格们);
    for (const 站 of 镇.站点位置们) {
      const 步们 = 规划路线(网, 镇.起点, 站);
      assert.ok(步们, `种子${种}：起点到 ${键(站)} 竟规划不出路（连通镇不该发生）`);
      for (const [, 数] of 步们) assert.ok(数 <= 3, `种子${种}：有一段 ${数} 格 > 3`);
      const 落 = 照走(网, 镇.起点, 站, 步们, `种子${种}→${键(站)}`);
      assert.equal(键(落), 键(站), `种子${种}：照提示喊完没到 ${键(站)}，停在 ${键(落)}`);
    }
  }
});

test('随机镇：从任一路格重新规划（🔁 / 走岔了重念都从车当前位置算）', () => {
  for (let 种 = 1; 种 <= 40; 种++) {
    const 镇 = 生成小镇({ 行数, 列数, 站点数, rng: 造rng(种 * 7 + 3) });
    const 网 = 建路网(行数, 列数, 镇.路格们);
    for (const 从 of 镇.路格们) {
      for (const 站 of 镇.站点位置们) {
        const 步们 = 规划路线(网, 从, 站);
        if (键(从) === 键(站)) { assert.deepEqual(步们, []); continue; }
        assert.ok(步们, `种子${种}：${键(从)} 到 ${键(站)} 规划不出`);
        const 落 = 照走(网, 从, 站, 步们, `种子${种} ${键(从)}→${键(站)}`);
        assert.equal(键(落), 键(站), `种子${种}：从 ${键(从)} 照提示没到 ${键(站)}，停在 ${键(落)}`);
      }
    }
  }
});

// ── 试走：小朋友报「往{方}走{数}格」，车忠实挪那么多（这一步的格数由孩子定，不由机器报） ──

test('试走：全是路就走满报的格数', () => {
  const 路格们 = [{ 行: 0, 列: 0 }, { 行: 0, 列: 1 }, { 行: 0, 列: 2 }, { 行: 1, 列: 0 }, { 行: 2, 列: 0 }];
  const 网 = 建路网(3, 3, 路格们);
  const r = 试走(网, { 行: 0, 列: 0 }, '东', 2);
  assert.equal(r.走了, 2);
  assert.deepEqual(r.终点, { 行: 0, 列: 2 });
  assert.equal(r.到头, false);
  assert.equal(r.到站, false);
});

test('试走：报多了、前面到头就停，走了记实走的格数', () => {
  const 路格们 = [{ 行: 0, 列: 0 }, { 行: 0, 列: 1 }, { 行: 0, 列: 2 }, { 行: 1, 列: 0 }, { 行: 2, 列: 0 }];
  const 网 = 建路网(3, 3, 路格们);
  const r = 试走(网, { 行: 0, 列: 0 }, '东', 5);
  assert.equal(r.走了, 2);
  assert.deepEqual(r.终点, { 行: 0, 列: 2 });
  assert.equal(r.到头, true);
});

test('试走：头一格就不是路 → 走了 0（前端当「开不过去」）', () => {
  const 网 = 建路网(3, 3, [{ 行: 0, 列: 0 }, { 行: 0, 列: 1 }]);
  const r = 试走(网, { 行: 0, 列: 0 }, '北', 2);
  assert.equal(r.走了, 0);
  assert.equal(r.到头, true);
  assert.deepEqual(r.终点, { 行: 0, 列: 0 });
});

test('试走：正好压上目的地就停，不冲过去', () => {
  const 网 = 建路网(1, 4, [{ 行: 0, 列: 0 }, { 行: 0, 列: 1 }, { 行: 0, 列: 2 }, { 行: 0, 列: 3 }]);
  const r = 试走(网, { 行: 0, 列: 0 }, '东', 3, { 行: 0, 列: 1 });
  assert.equal(r.到站, true);
  assert.equal(r.走了, 1);
  assert.deepEqual(r.终点, { 行: 0, 列: 1 });
});
