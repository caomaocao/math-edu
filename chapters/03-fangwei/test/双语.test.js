/**
 * 第3讲的双语「数据面」—— 台词表之外，还有三摊东西必须两语齐全，而且它们
 * 都在浏览器里最难逮：
 *
 *   · **环节名**（鼠标划过地图节点念的那句）：出处在环节表，不在台词表；
 *   · **教学字符**（屏幕上唯一允许出现的字）：英文课上换成 NORTH / UP 这些单词本身；
 *   · **各环节题库的词表**：漏一个英文说法，孩子在英文课上明明答对了却被判错 ——
 *     这种毛病靠手验几乎撞不上，只有一句一句地跑才抓得住。
 */

const 汉字 = /[　-〿一-鿿＀-￯]/;
/** 一句话里有没有英文字母 —— 用来断言「这条是真的翻过，不是把中文抄了一遍」 */
const 有英文 = /[a-z]/i;

test.afterEach(() => 设语言('cn'));

// ---------------------------------------------------------------------------
// 环节名
// ---------------------------------------------------------------------------

test('环节表：14 关都有两语的名字，英文那份没有汉字', () => {
  assert.equal(环节表.length, 14);
  for (const 条 of 环节表) {
    assert.ok(条.名.cn?.trim(), `环节「${条.号}」没有中文名`);
    assert.ok(条.名.en?.trim(), `环节「${条.号}」还没起英文名`);
    assert.equal(汉字.test(条.名.en), false, `环节「${条.号}」的英文名还夹着中文：${条.名.en}`);
    assert.ok(有英文.test(条.名.en), `环节「${条.号}」的英文名看着不像英文：${条.名.en}`);
  }
});

test('环节表：14 个英文名各不相同（孩子靠听分辨点的是哪一关）', () => {
  const 英名们 = 环节表.map((条) => 条.名.en);
  assert.equal(new Set(英名们).size, 14, '有两关重名了');
});

test('环节名()：按语言取，认不出来的语言回落中文', () => {
  const 头一关 = 环节表[0];
  assert.equal(环节名(头一关, 'cn'), 头一关.名.cn);
  assert.equal(环节名(头一关, 'en'), 头一关.名.en);
  assert.equal(环节名(头一关, '火星文'), 头一关.名.cn);
  assert.equal(环节名(头一关), 头一关.名.cn, '不给语言就按缺省中文');
});

// ---------------------------------------------------------------------------
// 教学字符
// ---------------------------------------------------------------------------

test('方位词：印在屏上的和念出来的，两张表键完全一样', () => {
  assert.deepEqual(Object.keys(方位牌).sort(), Object.keys(方位说).sort());
});

test('方位词：这一讲会用到的方位一个不落', () => {
  const 要用的 = [
    '上面', '下面', '前面', '后面', '左边', '右边', // 六方位
    ...Object.keys(生活对地图), // 生活轮：上 / 右上 / …
    ...Object.values(生活对地图), // 地图轮：北 / 东北 / …
  ];
  for (const 方 of 要用的) {
    assert.ok(方位牌[方], `「${方}」还没有屏幕上的写法`);
    assert.ok(方位说[方], `「${方}」还没有念出来的说法`);
  }
});

test('方位词：每个方位的英文都填了，而且是英文', () => {
  for (const [方, 条] of Object.entries(方位牌)) {
    assert.ok(条.cn?.trim() && 条.en?.trim(), `「${方}」的牌面缺一门课`);
    assert.equal(汉字.test(条.en), false, `「${方}」的英文牌面还是汉字：${条.en}`);
    assert.ok(有英文.test(条.en), `「${方}」的英文牌面看着不像英文：${条.en}`);
  }
  for (const [方, 条] of Object.entries(方位说)) {
    assert.ok(条.cn?.trim() && 条.en?.trim(), `「${方}」的说法缺一门课`);
    assert.equal(汉字.test(条.en), false, `「${方}」的英文说法还是汉字：${条.en}`);
  }
});

test('方位词：英文说法一律小写 —— TTS 的缓存键就是这串文本，大小写不统一会白合成两份', () => {
  for (const [方, 条] of Object.entries(方位说)) {
    assert.equal(条.en, 条.en.toLowerCase(), `「${方}」的英文说法混进了大写：${条.en}`);
  }
});

test('牌字 / 说法：跟着当前语言走；教学字符换的是词本身，不是给汉字加注释', () => {
  assert.equal(牌字('北'), '北');
  assert.equal(说法('北'), '北');
  assert.equal(牌字('东北'), '东北');

  设语言('en');
  assert.equal(牌字('北'), 'NORTH');
  assert.equal(说法('北'), 'north');
  assert.equal(牌字('东北'), 'NORTHEAST');
  assert.equal(说法('右上'), 'upper right');
  assert.equal(牌字('上面'), 'UP');
});

test('说法()：给了语言就按那门课念，不看当前语言', () => {
  assert.equal(说法('北', 'en'), 'north');
  设语言('en');
  assert.equal(说法('北', 'cn'), '北');
});

test('名说()：题库里的名字按语言念，缺英文回落中文', () => {
  const 松鼠 = { 名: '松鼠', 英: 'squirrel' };
  const 没翻的 = { 名: '松鼠' };
  assert.equal(名说(松鼠), '松鼠');
  设语言('en');
  assert.equal(名说(松鼠), 'squirrel');
  assert.equal(名说(没翻的), '松鼠', '漏译该在测试里红，不该在孩子面前变成一声不吭');
});

test('行与列：标签跟着语言换，交给判对的那串永远是中文规范写法', () => {
  assert.equal(行标字(2), '第2行');
  assert.equal(列标字(3), '第3列');
  assert.equal(行列牌(2, 3), '2行3列');
  assert.equal(行列答(2, 3), '第2行第3列');

  设语言('en');
  assert.equal(行标字(2), 'Row 2');
  assert.equal(列标字(3), 'Col 3');
  assert.equal(行列牌(2, 3), 'R2C3');
  // 备选钮按下去走的是 判行列()，它认的是这一串 —— 换了语言也不许变
  assert.equal(行列答(2, 3), '第2行第3列');
});

// ---------------------------------------------------------------------------
// 各环节题库的词表
// ---------------------------------------------------------------------------

const 词表们 = {
  '蔬菜格子·食物': 食物词表,
  '学校地图·地点': 地点词表,
  '货架·水果': 水果词表,
  '动物地图·动物': 动物词表,
  'Boss·题五动物阵': 动物阵词表,
};

/** 一个词条里纯拉丁字母的那些说法 = 英文说法 */
const 英说法们 = (说法们) => 说法们.filter((说) => 有英文.test(说) && !汉字.test(说));

for (const [名号, 词表] of Object.entries(词表们)) {
  test(`${名号}：每个词条都补了英文说法`, () => {
    const 条数 = Object.keys(词表).length;
    assert.ok(条数 > 0, '词表是空的');
    for (const [规范, 说法们] of Object.entries(词表)) {
      assert.equal(汉字.test(规范), true, `规范名必须是中文（判对的键）：${规范}`);
      assert.ok(
        英说法们(说法们).length > 0,
        `「${规范}」还没有英文说法 —— 孩子在英文课上答对了也会被判错`,
      );
    }
  });

  test(`${名号}：两语并集 —— 英文说法和中文规范名都判对`, () => {
    for (const [规范, 说法们] of Object.entries(词表)) {
      assert.equal(判对(规范, [规范], { 词表 }), '对', `中文说法判错了：${规范}`);
      for (const 英说 of 英说法们(说法们)) {
        assert.equal(判对(英说, [规范], { 词表 }), '对', `英文说法判错了：${规范} ← ${英说}`);
      }
    }
  });

  test(`${名号}：答成别人还是判错（英文说法没把词条糊成一团）`, () => {
    const 规范们 = Object.keys(词表);
    for (const 规范 of 规范们) {
      const 别人 = 规范们.find((别) => 别 !== 规范);
      const 别人的英文 = 英说法们(词表[别人])[0];
      assert.equal(
        判对(别人的英文, [规范], { 词表 }), '错',
        `答的是「${别人}」，不该算「${规范}」对`,
      );
    }
  });

  test(`${名号}：孩子的英文答案裹着口头语也认得出来`, () => {
    for (const [规范, 说法们] of Object.entries(词表)) {
      const 英说 = 英说法们(说法们)[0];
      assert.equal(
        判对(`Um, I think it is the ${英说}.`, [规范], { 词表 }), '对',
        `裹着口头语就认不出来了：${规范} ← ${英说}`,
      );
    }
  });
}
