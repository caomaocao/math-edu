import { test } from 'node:test';
import assert from 'node:assert/strict';
import { 合并 } from '/shared/js/进度.js';

/*
  第 3 讲进度模块的 合并(本地, 云端) 纯函数 —— 云端进度同步的单接缝（票 07）。

  好测试只测外部行为：给两份 payload，断言并集/冲突本地胜/重置戳/坏形状容错，
  不窥探内部表示。合并 是纯函数，不碰 localStorage/DOM/网络，直接 import 得动。

  整包形状：{ 版本:1, 星:{环节:true}, 柜:{格:值}, 重置戳:epoch毫秒 }。
  重置戳缺省 0，兼容既有无戳的 v1 数据。
*/

// ── 星：取并集，只增不减 ──────────────────────────────────────────────────────

test('星取并集：两侧各有的都保留', () => {
  const 本地 = { 版本: 1, 星: { 罗盘: true, 开车: true }, 柜: {} };
  const 云端 = { 版本: 1, 星: { 罗盘: true, 宝藏: true }, 柜: {} };
  const 合 = 合并(本地, 云端);
  assert.deepEqual(合.星, { 罗盘: true, 开车: true, 宝藏: true });
});

test('星只增不减：云端多出来的星不会把本地的星抹掉', () => {
  const 本地 = { 版本: 1, 星: { 罗盘: true }, 柜: {} };
  const 云端 = { 版本: 1, 星: { 开车: true }, 柜: {} };
  const 合 = 合并(本地, 云端);
  assert.equal(合.星.罗盘, true);
  assert.equal(合.星.开车, true);
});

test('星并集：本地空、云端有 → 拿到云端的（存量上云的反向：换设备见到已有星）', () => {
  const 合 = 合并({ 版本: 1, 星: {}, 柜: {} }, { 版本: 1, 星: { 罗盘: true }, 柜: {} });
  assert.deepEqual(合.星, { 罗盘: true });
});

// ── 柜：按格取有值的，同格冲突本地胜 ─────────────────────────────────────────

test('柜按格取有值的：各有各的格都保留', () => {
  const 本地 = { 版本: 1, 星: {}, 柜: { 大庆祝放过: true } };
  const 云端 = { 版本: 1, 星: {}, 柜: { 别的格: 3 } };
  const 合 = 合并(本地, 云端);
  assert.deepEqual(合.柜, { 大庆祝放过: true, 别的格: 3 });
});

test('柜同格冲突：两边都有且不同 → 本地胜', () => {
  const 本地 = { 版本: 1, 星: {}, 柜: { 格: '本地值' } };
  const 云端 = { 版本: 1, 星: {}, 柜: { 格: '云端值' } };
  assert.equal(合并(本地, 云端).柜.格, '本地值');
});

// ── 整包重置戳：谁的戳新谁整包胜出，不做并集 ─────────────────────────────────

test('整包重置戳：本地刚重来（戳更新）→ 本地整包胜出，云端旧星不诈尸', () => {
  const 本地 = { 版本: 1, 星: {}, 柜: {}, 重置戳: 2000 }; // 刚点了重来
  const 云端 = { 版本: 1, 星: { 罗盘: true, 开车: true }, 柜: { 大庆祝放过: true }, 重置戳: 1000 };
  const 合 = 合并(本地, 云端);
  assert.deepEqual(合.星, {}, '重来后云端旧星不能并回来');
  assert.deepEqual(合.柜, {});
  assert.equal(合.重置戳, 2000);
});

test('整包重置戳：云端戳更新（别的设备重来了）→ 云端整包胜出，本地旧星被清', () => {
  const 本地 = { 版本: 1, 星: { 罗盘: true }, 柜: {}, 重置戳: 1000 };
  const 云端 = { 版本: 1, 星: {}, 柜: {}, 重置戳: 3000 }; // 别处推来的重置空包
  const 合 = 合并(本地, 云端);
  assert.deepEqual(合.星, {}, '别的设备重来后，这台的旧星要被清');
  assert.equal(合.重置戳, 3000);
});

test('整包重置戳：戳相同才回到字段并集（重来后又各自攒了星，合起来一颗不丢）', () => {
  const 本地 = { 版本: 1, 星: { 罗盘: true }, 柜: {}, 重置戳: 5000 };
  const 云端 = { 版本: 1, 星: { 开车: true }, 柜: {}, 重置戳: 5000 };
  const 合 = 合并(本地, 云端);
  assert.deepEqual(合.星, { 罗盘: true, 开车: true });
  assert.equal(合.重置戳, 5000);
});

test('无戳的既有 v1 数据按 0 参与比戳：一侧重来（戳>0）稳赢无戳的另一侧', () => {
  const 本地 = { 版本: 1, 星: {}, 柜: {}, 重置戳: 1 }; // 刚重来
  const 云端 = { 版本: 1, 星: { 罗盘: true, 开车: true }, 柜: {} }; // 老数据，没有重置戳字段
  const 合 = 合并(本地, 云端);
  assert.deepEqual(合.星, {}, '无戳当 0，重来（戳 1）应清掉旧星');
});

test('两侧都无重置戳字段：当 0=0，走字段并集（存量收编不受影响）', () => {
  const 本地 = { 版本: 1, 星: { 罗盘: true }, 柜: {} };
  const 云端 = { 版本: 1, 星: { 开车: true }, 柜: {} };
  const 合 = 合并(本地, 云端);
  assert.deepEqual(合.星, { 罗盘: true, 开车: true });
  assert.equal(合.重置戳, 0);
});

// ── 云端版本对不上 / 坏形状 / null：当没有，不炸 ─────────────────────────────

test('云端版本对不上 → 当没有，退化成本地原样（不炸）', () => {
  const 本地 = { 版本: 1, 星: { 罗盘: true }, 柜: {} };
  const 云端 = { 版本: 2, 星: { 开车: true }, 柜: {} }; // 未来版本 / 洗数据前的旧结构
  const 合 = 合并(本地, 云端);
  assert.deepEqual(合.星, { 罗盘: true }, '版本对不上的云端不参与合并');
});

test('云端坏形状（非对象 / null / 星不是对象）→ 当没有，不炸', () => {
  const 本地 = { 版本: 1, 星: { 罗盘: true }, 柜: {} };
  for (const 坏 of [null, undefined, 42, 'x', [], { 版本: 1, 星: '不是对象', 柜: null }]) {
    const 合 = 合并(本地, 坏);
    assert.equal(合.星.罗盘, true, `云端=${JSON.stringify(坏)} 时本地星应原样保住`);
    assert.equal(合.版本, 1);
  }
});

test('本地坏形状 / null，云端好 → 拿云端（换设备首次登录见到已有进度）', () => {
  const 云端 = { 版本: 1, 星: { 罗盘: true }, 柜: { 大庆祝放过: true } };
  for (const 坏 of [null, undefined, { 版本: 0 }, 'x']) {
    const 合 = 合并(坏, 云端);
    assert.deepEqual(合.星, { 罗盘: true }, `本地=${JSON.stringify(坏)} 时应拿云端`);
  }
});

test('两侧都坏 / 都 null → 空包，不炸', () => {
  const 合 = 合并(null, null);
  assert.deepEqual(合, { 版本: 1, 星: {}, 柜: {}, 重置戳: 0 });
});

// ── 纯函数：不改动入参 ────────────────────────────────────────────────────────

test('合并不改动传进来的两份 payload（纯函数）', () => {
  const 本地 = { 版本: 1, 星: { 罗盘: true }, 柜: { 格: '本地' } };
  const 云端 = { 版本: 1, 星: { 开车: true }, 柜: { 格: '云端' } };
  const 本地快照 = JSON.parse(JSON.stringify(本地));
  const 云端快照 = JSON.parse(JSON.stringify(云端));
  合并(本地, 云端);
  assert.deepEqual(本地, 本地快照);
  assert.deepEqual(云端, 云端快照);
});
