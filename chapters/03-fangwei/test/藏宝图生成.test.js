import { test } from 'node:test';
import assert from 'node:assert/strict';
import { 生成藏宝图, 地标名们, 宝物名们, 关数 } from '../js/藏宝图.js';
import { 走一步 } from '/shared/js/罗盘.js';

/*
  挖宝藏（第 12 关）那张海岛图的随机生成器。

  每次进关都摊开一张新图：三个地标随机落位，三关分别 1/2/3 段，起点地标、
  每段方向与步数、埋的宝物全随机。这一关孩子照着念出来的线索走格子去挖，
  所以「解得开」不是可选项 —— 下面每一条不变量，塌一条孩子就有一关挖不到。

  抽签那只手（rng）从外面递进来：浏览器用 Math.random，测试钉一个确定的 rng，
  才能一次跑几百个种子把每条不变量都验到，也才能把「怎么抽都退不出合法图」
  的兜底重试逼出来。
*/

const 四方 = ['北', '南', '东', '西'];
const 反 = { 北: '南', 南: '北', 东: '西', 西: '东' };
const 在界 = (格, 边) => 格.行 >= 0 && 格.行 < 边 && 格.列 >= 0 && 格.列 < 边;

/** mulberry32：一个种子一条确定的随机序列，测试跨种子扫不变量用 */
function 造rng(种子) {
  let a = 种子 >>> 0;
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** 把一张图的每条不变量都验一遍（验不过当场红，带上是哪一关哪一段） */
function 查这张图(图, 边 = 5, 标签 = '') {
  const { 地标位置们, 关卡们 } = 图;

  // —— 地标：恰好三个、都在界内、两两不同 ——
  assert.deepEqual(
    Object.keys(地标位置们).sort(),
    [...地标名们].sort(),
    `${标签} 地标名不对`,
  );
  const 地标键们 = [];
  for (const 名 of 地标名们) {
    const 格 = 地标位置们[名];
    assert.ok(在界(格, 边), `${标签} 地标「${名}」出界：${JSON.stringify(格)}`);
    地标键们.push(`${格.行},${格.列}`);
  }
  assert.equal(new Set(地标键们).size, 3, `${标签} 三个地标有重合`);
  const 地标键集 = new Set(地标键们);

  // —— 三关：段数 1/2/3、每段合法、逐步在界、终点避开地标与起点 ——
  assert.equal(关卡们.length, 关数, `${标签} 关卡数不对`);
  for (let 关 = 0; 关 < 关卡们.length; 关++) {
    const { 起, 步们, 宝, 目标 } = 关卡们[关];
    const 前缀 = `${标签} 关${关 + 1}`;
    assert.ok(地标名们.includes(起), `${前缀} 起点不是地标：${起}`);
    assert.equal(步们.length, 关 + 1, `${前缀} 段数应为 ${关 + 1}`);

    for (let s = 0; s < 步们.length; s++) {
      const [方, 数] = 步们[s];
      assert.ok(四方.includes(方), `${前缀} 第${s + 1}段方向不认识：${方}`);
      assert.ok(数 >= 1 && 数 <= 3, `${前缀} 第${s + 1}段步数越界：${数}`);
      if (s > 0) {
        assert.notEqual(
          方, 反[步们[s - 1][0]],
          `${前缀} 第${s}→${s + 1}段走了回头路（${步们[s - 1][0]}→${方}）`,
        );
      }
    }

    // 一格一格走 —— 脚印演示走的就是这条路，每一步都不许出界
    let 现 = { ...地标位置们[起] };
    for (const [方, 数] of 步们) {
      for (let k = 0; k < 数; k++) {
        现 = 走一步(现, 方);
        assert.ok(在界(现, 边), `${前缀} 走到界外了：${JSON.stringify(现)}`);
      }
    }
    assert.deepEqual(现, 目标, `${前缀} 目标与走出来的终点不符`);

    const 目标键 = `${目标.行},${目标.列}`;
    assert.ok(!地标键集.has(目标键), `${前缀} 目标压在地标上：${目标键}`);
    const 起格 = 地标位置们[起];
    assert.ok(
      !(目标.行 === 起格.行 && 目标.列 === 起格.列),
      `${前缀} 目标就是起点那一格`,
    );
  }

  // —— 三样宝物：金币/钻石/皇冠 各恰好一次 ——
  assert.deepEqual(
    关卡们.map((k) => k.宝).sort(),
    [...宝物名们].sort(),
    `${标签} 宝物不是三样的一个排列`,
  );
}

test('跨 300 个种子：每一张图都满足全部不变量', () => {
  for (let 种子 = 1; 种子 <= 300; 种子++) {
    const 图 = 生成藏宝图({ rng: 造rng(种子) });
    查这张图(图, 5, `种子${种子}`);
  }
});

test('默认 rng（Math.random）：连开 200 张都合法', () => {
  for (let i = 0; i < 200; i++) {
    查这张图(生成藏宝图(), 5, `随机第${i}张`);
  }
});

test('有限重试永远退得出合法图：怎么刁难的 rng 都不抛错、不死循环', () => {
  // 常数 rng 让每次「一次尝试」都一模一样：要么一次成、要么一路失败逼到兜底，
  // 两条路都得给出一张合法图。取 0 / 接近 1 / 0.5 各试，覆盖抽签的两个端。
  for (const 值 of [0, 0.9999999, 0.5, 0.999, 1e-9]) {
    const 图 = 生成藏宝图({ rng: () => 值 });
    查这张图(图, 5, `常数rng=${值}`);
  }
});

test('确实在随机（不是每次都回落到同一张兜底图）', () => {
  const 签名们 = new Set();
  for (let 种子 = 1; 种子 <= 200; 种子++) {
    const { 地标位置们, 关卡们 } = 生成藏宝图({ rng: 造rng(种子) });
    签名们.add(JSON.stringify([地标位置们, 关卡们]));
  }
  // 200 个种子理应铺出一大把不同的图；给个很松的下限，够挡住「永远兜底」这种塌陷
  assert.ok(签名们.size > 50, `图的花样太少（只有 ${签名们.size} 种），像是退回兜底了`);
});

test('相邻两段永远是直角拐弯（既不回头也不原地重复方向）', () => {
  // 比「不回头」更强的一条：线索念给五岁孩子听，「往北2再往北1」既绕又乱，
  // 生成器一律拐直角。这里把它钉死，顺带也就保证了不回头。
  const 垂直 = { 北: ['东', '西'], 南: ['东', '西'], 东: ['北', '南'], 西: ['北', '南'] };
  for (let 种子 = 1; 种子 <= 200; 种子++) {
    const { 关卡们 } = 生成藏宝图({ rng: 造rng(种子) });
    for (const { 步们 } of 关卡们) {
      for (let s = 1; s < 步们.length; s++) {
        assert.ok(
          垂直[步们[s - 1][0]].includes(步们[s][0]),
          `种子${种子}：${步们[s - 1][0]}→${步们[s][0]} 不是直角拐弯`,
        );
      }
    }
  }
});
