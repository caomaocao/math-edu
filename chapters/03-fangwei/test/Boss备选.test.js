import { test } from 'node:test';
import assert from 'node:assert/strict';
import { 凑题五备选 } from '../js/环节/Boss.js';
import { 走一步 } from '/shared/js/罗盘.js';

/*
  Boss 题五的备选钮。

  这一关是「从中间的小熊出发往某个方向走一格，那格是谁」，四颗钮里必须
  **正好一颗**是正确答案。从前干扰池只排掉了出发点小熊，没排掉答案自己 ——
  8 只里抽 3 只，3/8 的概率抽中答案，界面上就冒出两颗一模一样的按钮：
  孩子点哪颗都判对，但看着像网站坏了。手验撞不上（三次才一次），所以拿测试钉住。

  抽签那只手从外面递进来，这儿钉成「按原顺序取前几个」——最容易撞上答案的那种手。
*/
const 不洗 = (们) => [...们];

/** 题五走得到的四个答案：中心 (1,1) 往北南西东各走一步 */
const 可能的答案 = ['北', '南', '西', '东'].map((方) => {
  const 到 = 走一步({ 行: 1, 列: 1 }, 方);
  return [['小猫', '小狗', '小兔'], ['狐狸', '小熊', '熊猫'], ['青蛙', '小鸡', '奶牛']][到.行][到.列];
});

test('题五备选：四颗钮，正确答案恰好出现一次', () => {
  for (const 答 of 可能的答案) {
    const 备选 = 凑题五备选(答, 不洗);
    assert.equal(备选.length, 4, `${答}：备选钮不是四颗`);
    const 中的 = 备选.filter((一颗) => 一颗.答 === 答);
    assert.equal(中的.length, 1, `${答}：正确答案出现了 ${中的.length} 次（应当只有一次）`);
  }
});

test('题五备选：四颗互不相同', () => {
  for (const 答 of 可能的答案) {
    const 名们 = 凑题五备选(答, 不洗).map((一颗) => 一颗.答);
    assert.equal(new Set(名们).size, 名们.length, `${答}：有重复的钮 ${名们.join('、')}`);
  }
});

test('题五备选：出发点小熊不当干扰项（孩子刚从它那儿走出来）', () => {
  for (const 答 of 可能的答案) {
    const 名们 = 凑题五备选(答, 不洗).map((一颗) => 一颗.答);
    assert.equal(名们.includes('小熊'), false, `${答}：小熊混进备选了`);
  }
});

test('题五备选：每颗钮都带着自己那只动物的图', () => {
  const 图对名 = {
    小猫: '🐱', 小狗: '🐶', 小兔: '🐰', 狐狸: '🦊',
    小熊: '🐻', 熊猫: '🐼', 青蛙: '🐸', 小鸡: '🐤', 奶牛: '🐮',
  };
  for (const 答 of 可能的答案) {
    for (const 一颗 of 凑题五备选(答, 不洗)) {
      assert.equal(一颗.图, 图对名[一颗.答], `${一颗.答} 配错了图`);
    }
  }
});

test('题五备选：换一只抽签的手，答案照样只出现一次', () => {
  // 倒着取、随机取都试一遍 —— 不管手怎么抽，池子里本来就不该有答案
  const 手们 = [(们) => [...们].reverse(), (们) => [...们].sort(() => 0.5 - Math.random())];
  for (const 洗 of 手们) {
    for (const 答 of 可能的答案) {
      for (let 轮 = 0; 轮 < 30; 轮 += 1) {
        const 名们 = 凑题五备选(答, 洗).map((一颗) => 一颗.答);
        assert.equal(名们.filter((名) => 名 === 答).length, 1, `${答}：抽出了重复的正确答案`);
        assert.equal(new Set(名们).size, 4);
      }
    }
  }
});
