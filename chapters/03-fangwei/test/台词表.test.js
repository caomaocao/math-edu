test('台词 / 模板：读的那一刻才挑语言（环节模块在 import 时就把它存下来了）', () => {
  // 十四个环节模块开头都是这一行，跑在换语言之前
  const 话 = 台词.全站;
  const 模 = 模板.树桩行列;

  assert.equal(话.开场白, 两语台词.cn.全站.开场白);
  assert.equal(模.数行(2), '第2行！');

  设语言('en');
  assert.equal(话.开场白, 两语台词.en.全站.开场白, '换了语言，早就存下来的那份也得跟着换');
  assert.equal(模.数行(2), 'Row 2!');

  设语言('cn');
  assert.equal(话.开场白, 两语台词.cn.全站.开场白);
});

