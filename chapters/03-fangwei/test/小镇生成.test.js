import { test } from 'node:test';
import assert from 'node:assert/strict';
import { 生成小镇 } from '../js/小镇.js';
import { 建路网, 开车 } from '/shared/js/路网.js';

/*
  开车关的随机小镇生成器。纯逻辑、无 DOM，node 直接测。

  每次进关都现生成一座小镇（连通的路网 + 五个站点落在随机路格 + 随机起点）。
  下面把「孩子玩得动」拆成四条硬不变量，用**独立于生成器**的手（自写 BFS + 真·开车）
  逐条钉死，跨很多个种子都得成立：

    1. 起点和五个站点都落在路格上（车只能在路上开）。
    2. 六个位置两两不同（起点 + 五站，谁都不叠谁）。
    3. 路网连通 —— 从起点 BFS 能走到每一格路（于是每个站点从起点、从彼此都到得了）。
    4. 直行段 ≤3 格 —— 从任一路格朝任一方向喊一声，车最多开三格就停（孩子数得过来）。

  段 4 用**真正的 开车()** 验，跟生成器内部的校验走的是不同的判断，才算独立复核。
  测试注入定死的 rng（mulberry32），同种子同镇、可复现。
*/

const 行数 = 6;
const 列数 = 7;
const 站点数 = 5;

function 造rng(种子) {
  let a = 种子 >>> 0;
  return function () {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const 键 = ({ 行, 列 }) => `${行},${列}`;

/** 从起点在路格集合上做 4 邻 BFS，返回能走到的格子键集合 */
function 广搜(路集, 起点) {
  const 到过 = new Set([键(起点)]);
  const 队 = [起点];
  while (队.length) {
    const { 行, 列 } = 队.shift();
    for (const [d行, d列] of [[-1, 0], [1, 0], [0, -1], [0, 1]]) {
      const 邻 = { 行: 行 + d行, 列: 列 + d列 };
      if (路集.has(键(邻)) && !到过.has(键(邻))) { 到过.add(键(邻)); 队.push(邻); }
    }
  }
  return 到过;
}

/** 跑一批种子，把每座镇交给检查函数 */
function 每座镇(检查, 种子数 = 200) {
  for (let 种 = 1; 种 <= 种子数; 种++) {
    const 镇 = 生成小镇({ 行数, 列数, 站点数, rng: 造rng(种) });
    检查(镇, 种);
  }
}

test('形状：路格们非空、起点是格、五个站点位置', () => {
  每座镇((镇, 种) => {
    assert.ok(Array.isArray(镇.路格们) && 镇.路格们.length > 0, `种子${种}：路格们该是非空数组`);
    assert.ok(镇.起点 && Number.isInteger(镇.起点.行) && Number.isInteger(镇.起点.列), `种子${种}：起点该是 {行,列}`);
    assert.equal(镇.站点位置们.length, 站点数, `种子${种}：站点位置数不是 ${站点数}`);
  });
});

test('不变量1：起点和每个站点都落在路格上', () => {
  每座镇((镇, 种) => {
    const 路集 = new Set(镇.路格们.map(键));
    assert.ok(路集.has(键(镇.起点)), `种子${种}：起点不在路上`);
    for (const 站 of 镇.站点位置们) {
      assert.ok(路集.has(键(站)), `种子${种}：站点 ${键(站)} 不在路上`);
    }
  });
});

test('不变量2：起点 + 五站六个位置两两不同', () => {
  每座镇((镇, 种) => {
    const 六 = [镇.起点, ...镇.站点位置们].map(键);
    assert.equal(new Set(六).size, 六.length, `种子${种}：有位置重叠了 ${六.join(' / ')}`);
  });
});

test('不变量2b：所有路格都在 6×7 界内、且互不重复', () => {
  每座镇((镇, 种) => {
    const 键们 = 镇.路格们.map(键);
    assert.equal(new Set(键们).size, 键们.length, `种子${种}：路格里有重复`);
    for (const { 行, 列 } of 镇.路格们) {
      assert.ok(行 >= 0 && 行 < 行数 && 列 >= 0 && 列 < 列数, `种子${种}：路格 ${行},${列} 越界`);
    }
  });
});

test('不变量3：路网连通 —— 从起点能走到每一格路（含每个站点、站点彼此互通）', () => {
  每座镇((镇, 种) => {
    const 路集 = new Set(镇.路格们.map(键));
    const 到过 = 广搜(路集, 镇.起点);
    assert.equal(到过.size, 路集.size, `种子${种}：路网不连通（起点只到得了 ${到过.size}/${路集.size} 格）`);
    for (const 站 of 镇.站点位置们) {
      assert.ok(到过.has(键(站)), `种子${种}：站点 ${键(站)} 从起点走不到`);
    }
  });
});

test('不变量4：任一路格朝任一方向开，车最多走 3 格（直行段 ≤3）', () => {
  每座镇((镇, 种) => {
    const 网 = 建路网(行数, 列数, 镇.路格们);
    for (const 格 of 镇.路格们) {
      for (const 方 of ['北', '南', '西', '东']) {
        const { 经过 } = 开车(网, 格, 方);
        assert.ok(经过.length <= 3, `种子${种}：从 ${键(格)} 往${方}开了 ${经过.length} 格（>3，孩子数不过来）`);
      }
    }
  });
});

test('可复现：同种子生成同一座镇', () => {
  for (const 种 of [1, 7, 42, 123, 999]) {
    const 甲 = 生成小镇({ 行数, 列数, 站点数, rng: 造rng(种) });
    const 乙 = 生成小镇({ 行数, 列数, 站点数, rng: 造rng(种) });
    assert.deepEqual(甲, 乙, `种子${种}：同种子两次生成不一致`);
  }
});

test('有变化：不同种子会长出不同的镇（不是每次都同一张）', () => {
  const 指纹 = new Set();
  for (let 种 = 1; 种 <= 40; 种++) {
    const 镇 = 生成小镇({ 行数, 列数, 站点数, rng: 造rng(种) });
    指纹.add(JSON.stringify(镇));
  }
  assert.ok(指纹.size > 20, `40 个种子只长出 ${指纹.size} 种镇，随机性太弱`);
});

test('健壮：退化的 rng（永远 0 / 永远接近 1）也能还回一座合法的镇', () => {
  for (const 退化 of [() => 0, () => 0.9999999]) {
    const 镇 = 生成小镇({ 行数, 列数, 站点数, rng: 退化 });
    // essential 不变量：够 6 个位置、都在路上、两两不同、连通、直行 ≤3
    const 路集 = new Set(镇.路格们.map(键));
    const 六 = [镇.起点, ...镇.站点位置们];
    assert.equal(镇.站点位置们.length, 站点数);
    assert.equal(new Set(六.map(键)).size, 6);
    for (const 格 of 六) assert.ok(路集.has(键(格)), `退化 rng：${键(格)} 不在路上`);
    const 到过 = 广搜(路集, 镇.起点);
    assert.equal(到过.size, 路集.size, '退化 rng：路网不连通');
    const 网 = 建路网(行数, 列数, 镇.路格们);
    for (const 格 of 镇.路格们) for (const 方 of ['北', '南', '西', '东']) {
      assert.ok(开车(网, 格, 方).经过.length <= 3, '退化 rng：有直行段超过 3 格');
    }
  }
});
