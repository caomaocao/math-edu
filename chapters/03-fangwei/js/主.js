const 命名空间 = 'http://www.w3.org/2000/svg';

function 元素(名, 属性们 = {}, 文字) {
  const 元 = document.createElementNS(命名空间, 名);
  for (const [k, v] of Object.entries(属性们)) 元.setAttribute(k, v);
  if (文字 !== undefined) 元.textContent = 文字;
  return 元;
}

