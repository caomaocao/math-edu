const 节点们 = {};

function 画节点() {
  环节表.forEach(({ 号, 素, 图, 名 }, i) => {
    const [x, y] = 站们[i];
    const 组 = 元素('g', { class: '地图节点 没星', transform: `translate(${x},${y})` });
    组.append(
      // 隐形热区。/shared/css/热区.css 那个工具类靠 ::after，SVG 里没有这回事，
      // 所以这儿多画一个透明的大圆 —— 反正整个 <g> 才是被点的那一个，谁接住手指都一样。
      //
      // 半径挑 62 是算出来的。这张图按 viewBox 1200×760 塞进 1280×842 的舞台，
      // 取两轴的小者 = 1280/1200 ≈ 1.067，所以 1 个 viewBox 单位就是 1.067 舞台px：
      // 直径 124 × 1.067 ≈ 132 舞台px ≈ 56pt，过了 44pt 那条线（账在 styles.css 头上）。
      // 这个圆**不吃** /shared/css/热区.css 那份外扩（SVG 里没有 ::after），所以它得
      // 靠自己一次达标 —— 拿 104 舞台px 那条线量它，不是 57 那条。
      // 会不会抢邻居：小路上最近的两站中心相距 195 个 viewBox 单位，两个 62 的圆
      // 要 124 才碰上，还差得远。
      // 注意这个换算跟着基准高走 —— 基准一改，这儿和 styles.css 那笔账都得重算。
      元素('circle', { class: '节点热区', r: 62 }),
      元素('circle', { class: '节点圈', r: 42 }),
      // 44px 是原来那条 .节点图 的字号；实测这个尺寸下十四张贴纸都认得出
      画实体SVG(素, 图, { 边: 44, x: -22, y: -22, 类名: '节点图' }),
      元素('text', { class: '节点星', y: -46, 'text-anchor': 'middle' }, '⭐'),
    );
    // 名是 {cn, en}：读的这一刻才挑，孩子换了语言不用重画地图。
    //
    // 这一句**故意还是 mouseenter，不改 pointerenter**。触屏上 pointerenter 是随手指
    // 按下发的，紧接着这一下点击就进关，而进关第一句 说() 开头先 闭嘴() ——
    // 孩子只会听见关名的头一百毫秒被掐断，一句话咬掉半截比压根不念更糟。
    // 手机上认关靠的是节点上那张贴纸图和星星，进去之后每一关的开场白自己会说
    // 「这是学校旁边的小地图」；划过念名字就当桌面上白得的一份便利。
    组.addEventListener('mouseenter', () => 说(选(名)));
    组.addEventListener('click', () => { 音效.点一下(); 打开(号); });
    图纸.append(组);
    节点们[号] = 组;
  });
}

