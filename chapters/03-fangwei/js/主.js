// ---------------------------------------------------------------- 面板切换

function 摆正面板() {
  const 全部 = [地图面板, ...Object.values(面板们)];
  for (const 板 of 全部) {
    const 在前 = 板.dataset.环节 === 现在在 || (现在在 === '地图' && 板 === 地图面板);
    板.classList.toggle('在前', 在前);
    if (在前) 板.removeAttribute('inert');
    else 板.setAttribute('inert', '');
  }
}

async function 打开(号, { 从历史 = false } = {}) {
  // 双击同一个节点不压两条历史；从历史（后退/前进/换语言重进）不受这条拦
  if (!从历史 && 现在在 === 号) return;
  if (!从历史) 层级.进(号); // 先压历史再切面板：后退手势=回地图，见 后退.js
  闭嘴();
  收起麦克风();
  收重来确认(); // 离开地图层：把地图上悬着的「重来」确认立刻收掉，别让它 8 秒里在关里复活，见 装重来
  现在在 = 号;
  const 这代 = ++进关代; // 领号，见上；下面 await import 让出后，凭它认这次进关是不是还算数
  摆正面板();
  if (!模块池[号]) {
    模块池[号] = (async () => {
      try {
        const 模块 = await import(`./环节/${号}.js`);
        return 模块.创建(面板们[号], 工具);
      } catch (错) {
        console.error(`环节「${号}」还没盖好`, 错);
        return { async 进入() { await 说(台词.全站.还在施工); } };
      }
    })();
  }
  const 实例 = await 模块池[号];
  // 等 import 的空当里孩子可能又后退回地图、又点了别的关：只有仍是最新那次进关（这代）、
  // 且这一关还在最前（现在在），才真的开讲——不然重复 进入() 会把开场白念两遍。
  // 「回地图」不换号只改 现在在，所以两条都得查：换关靠 这代 拦，退回地图靠 现在在 拦。
  if (这代 !== 进关代 || 现在在 !== 号) return;
  await 实例.进入();
}

