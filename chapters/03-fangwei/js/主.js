/**
 * 这一讲的基准分辨率 —— 14 个环节的几何全按这一个尺寸画，整块画面再等比缩放到
 * 实际屏幕（见 docs/adr/0004 与 /shared/js/舞台.js）。**改屏幕只改这两个数**，
 * 环节里一个 px 都不用动；反过来说，谁在样式里写 vw / vh 就等于绕过了它，
 * 那两套单位量的是真屏幕，缩放之后必然对不上。
 *
 * 高度是**内容倒推**出来的，不是挑的：14 关里排得最高的是宝藏（五行沙格 498 + 画框
 * 边 44 + 线索钮 64 + 进度点 26 + 两道 18 的缝 = 668 舞台px），加上 .舞台布 上下留的
 * 174（24 顶 + 150 给麦克风坞）正好是这个数。关卡不为了迁就一个更矮的舞台重排 ——
 * 那等于改孩子看到的画面。
 *
 * 量的时候只算**排在流里**的那一列。回家钮、方向盘、麦克风坞、语言开关是
 * position: fixed，钉在舞台自己的四边上 —— 它们跟着舞台走，永远撑不高舞台，
 * 把它们算进包围盒会得出一个虚高的数（开车那一关最容易骗人：方向盘钉在右下角，
 * 连起来量像是 780 多高、1050 宽，其实那一列只有 592 高、710 宽）。
 * 它们真正的约束是**别跟这一列撞上**，那是逐关看位置的事，不是加进高度里。
 *
 * 这个数一改，触靶的物理尺寸全跟着变（系数 = 视口高 / 基准高），
 * 换句话说：**动它就得重算 styles.css 头上那笔账。**
 */
