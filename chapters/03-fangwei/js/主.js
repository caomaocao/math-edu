function 装重来() {
  const 角 = document.getElementById('重来角');
  const 重来 = document.createElement('button');
  重来.textContent = '↺';
  角.appendChild(重来);
  重来.onclick = async () => {
    if (角.childElementCount > 1) return;
    说(台词.全站.重来问);
    const 真清 = document.createElement('button');
    真清.className = '真清';
    真清.textContent = '✔';
    const 算了 = document.createElement('button');
    算了.className = '算了';
    算了.textContent = '✕';
    let 计时;
    // clearTimeout 是必须的：收掉之后那颗 8 秒定时器若还留着，等孩子回地图开了新一轮确认，
    // 它会晚点炸响、跑旧的 收 —— 旧 收 又把 收重来确认 抹回空操作，新一轮的「进关即收」就哑了。
    const 收 = () => { 真清.remove(); 算了.remove(); clearTimeout(计时); 收重来确认 = () => {}; };
    // 地图面板进关时只是让位（visibility+inert），没被卸载：8 秒里孩子进关又后退回来，
    // 这对 ✔✕ 会原样复活，早忘了在干嘛的孩子顺手拍到 ✔ 就清光星星。把「收」挂到模块级，
    // 打开() 一进关就调它（收重来确认()），确认态跟着离开地图一起收掉。
    收重来确认 = 收;
    // 清空 写的是带新重置戳的空包（不是删键）；立即推 紧跟着把这份空包推上云端和别的设备，
    // 让重置立刻传播、别的设备焦点切回来时星星不诈尸（休眠期 立即推 是空操作，本地照清）。
    真清.onclick = () => { 进度.清空(); 立即推(存储键); 收(); 刷星星(); 说(台词.全站.重来了); };
    算了.onclick = () => { 收(); 闭嘴(); };
    角.append(真清, 算了);
    计时 = setTimeout(收, 8000);
  };
}

