// 路线 —— 开车关的「分段步数提示」。纯模块：无 DOM、无网络，node 直接测（见 test/路线规划.test.js）。
//
// 目标：从车**现在**这一格算一条到目的地的路，切成「往某方向走 N 格」的段，念给孩子听，
// 让照着念一遍就真能开到。关键是**段数必须跟车实际会走的一样** —— 所以这里不自己走格子，
// 而是直接借 路网.js 的 开车()：它一喊就开到下一个路口/尽头/停靠点，返回 {终点, 经过}。
//
// 把「一次喊话」当作图上的一条边：从某格朝某方向 开车()，经过非空就得到一条通往「终点」、
// 标着 [方, 经过.length] 的边。在这张「路口图」上从 起 广搜到 终（把 终 当停靠点传进去，
// 半路正好压上目的地就停），最短路上那串边的标签，就是要念的分段提示。
// 于是「照提示喊 → 到站」和「每段格数 = 那一喊车真走的格数」都由构造保证。

import { 开车 } from '/shared/js/路网.js';

const 四向 = ['北', '南', '西', '东'];
const 键 = ({ 行, 列 }) => `${行},${列}`;

/**
 * 规划从 起 到 终 的分段路线。
 *
 * @returns {[string, number][] | null} 形如 [['北',2],['东',3]]；起就是终 → []；到不了 → null
 *   （连通的小镇里到不了不会发生，null 只是留个诚实的出口）。
 */
export function 规划路线(网, 起, 终) {
  const 起键 = 键(起);
  const 终键 = 键(终);
  if (起键 === 终键) return [];

  // 键 → {前键, 段:[方, 格数]}；起点记 null（没有来路）
  const 来自 = new Map([[起键, null]]);
  const 队 = [起];
  while (队.length) {
    const 格 = 队.shift();
    for (const 方 of 四向) {
      const { 终点, 经过 } = 开车(网, 格, 方, [终]);
      if (经过.length === 0) continue; // 这个方向头一步就不是路：原地不动，不是一条边
      const 到键 = 键(终点);
      if (来自.has(到键)) continue; // 更短的路已经先到过它
      来自.set(到键, { 前键: 键(格), 段: [方, 经过.length] });
      if (到键 === 终键) return 回溯(来自, 起键, 终键);
      队.push(终点);
    }
  }
  return null;
}

/** 顺着 来自 从终点倒着串回起点，再翻正 */
function 回溯(来自, 起键, 终键) {
  const 逆 = [];
  let 当 = 终键;
  while (当 !== 起键) {
    const 记 = 来自.get(当);
    逆.push(记.段);
    当 = 记.前键;
  }
  return 逆.reverse();
}
