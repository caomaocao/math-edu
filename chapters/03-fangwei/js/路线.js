// 路线 —— 开车关的路逻辑。纯模块：无 DOM、无网络，node 直接测（见 test/路线规划.test.js）。
// 两件事：
//   规划路线(网, 起, 终) —— 从车现在这一格到站的一条最短路，切成「往某方向走 N 格」的段。
//     不再念给孩子当答案（那是把路报了，家长反馈不对）；只在孩子**卡住时**取它第一段，
//     逐级搭手：先露方向、再不行才连格数一起露（见 环节/开车.js 的 也许提醒）。
//   试走(网, 起, 方, 数, 目的地?) —— 孩子自己报「往{方}走{数}格」，车忠实挪那么多格
//     （全是路就走满、压上目的地就停、前面到头就停）。往哪、走几格由孩子定，机器只执行。
//
// 规划路线 的算法：把「一次喊话」当作图上的一条边 —— 从某格朝某方向借 路网.js 的 开车()
// （一喊开到下一个路口/尽头/停靠点，返回 {终点, 经过}），经过非空就是一条通往「终点」、
// 标着 [方, 经过.length] 的边。在这张「路口图」上从 起 广搜到 终（终 当停靠点，半路压上就停），
// 最短路上那串边的标签即分段路线；每段格数 = 那一喊车真走的格数，由构造保证。

import { 开车, 是路 } from '/shared/js/路网.js';
import { 走一步 } from '/shared/js/罗盘.js';

const 四向 = ['北', '南', '西', '东'];

/**
 * 试走(网, 起, 方, 数, 目的地?) → { 经过, 终点, 走了, 到站, 到头 }
 *   小朋友喊「往{方}走{数}格」，车照着一格一格往前挪，直到：走满 数 格、正好压上目的地（就停，
 *   不冲过去）、或前面不是路（到头）。这一步「走多少格」是孩子自己报的，机器只忠实执行。
 *   走了 = 实际走的格数（0 = 头一格就不是路，压根没开动 → 前端当「开不过去」提醒）；
 *   到站 / 到头 记的是为什么停下的。
 */
export function 试走(网, 起, 方, 数, 目的地 = null) {
  const 经过 = [];
  let 现 = 起;
  let 到站 = false;
  let 到头 = false;
  for (let i = 0; i < 数; i += 1) {
    const 下 = 走一步(现, 方);
    if (!是路(网, 下)) { 到头 = true; break; }
    现 = 下;
    经过.push(现);
    if (目的地 && 现.行 === 目的地.行 && 现.列 === 目的地.列) { 到站 = true; break; }
  }
  return { 经过, 终点: 现, 走了: 经过.length, 到站, 到头 };
}
const 键 = ({ 行, 列 }) => `${行},${列}`;

/**
 * 规划从 起 到 终 的分段路线。
 *
 * @returns {[string, number][] | null} 形如 [['北',2],['东',3]]；起就是终 → []；到不了 → null
 *   （连通的小镇里到不了不会发生，null 只是留个诚实的出口）。
 */
export function 规划路线(网, 起, 终) {
  const 起键 = 键(起);
  const 终键 = 键(终);
  if (起键 === 终键) return [];

  // 键 → {前键, 段:[方, 格数]}；起点记 null（没有来路）
  const 来自 = new Map([[起键, null]]);
  const 队 = [起];
  while (队.length) {
    const 格 = 队.shift();
    for (const 方 of 四向) {
      const { 终点, 经过 } = 开车(网, 格, 方, [终]);
      if (经过.length === 0) continue; // 这个方向头一步就不是路：原地不动，不是一条边
      const 到键 = 键(终点);
      if (来自.has(到键)) continue; // 更短的路已经先到过它
      来自.set(到键, { 前键: 键(格), 段: [方, 经过.length] });
      if (到键 === 终键) return 回溯(来自, 起键, 终键);
      队.push(终点);
    }
  }
  return null;
}

/** 顺着 来自 从终点倒着串回起点，再翻正 */
function 回溯(来自, 起键, 终键) {
  const 逆 = [];
  let 当 = 终键;
  while (当 !== 起键) {
    const 记 = 来自.get(当);
    逆.push(记.段);
    当 = 记.前键;
  }
  return 逆.reverse();
}
