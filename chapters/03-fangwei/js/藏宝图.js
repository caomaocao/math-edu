// 藏宝图 —— 挖宝藏（第12关）那张海岛图的随机生成器。纯逻辑：无 DOM、无网络，node 直接测。
//
// 每次进关都摊开一张新图：三个地标随机落在 5×5 沙滩上，三关分别 1/2/3 段线索，
// 起点地标、每段方向与步数、埋的宝物全随机。生成器只有一件事：**吐出一张一定
// 解得开的图**，孩子照着念出来的线索走格子就能挖到。渲染、语音、脚印演示都在
// 环节/宝藏.js，这里一律不碰 DOM（所以能 node --test，见 test/藏宝图生成.test.js）。
//
// 一张合法图必须处处成立（每一条都由测试钉住）：
//   · 三个地标在界内、两两不同；
//   · 每一关一步一步走，任何一步都不出 [0,边)（脚印演示走的就是这条路）；
//   · 目标格不压在任何地标上，也不是起点那一格；
//   · 段数关1=1、关2=2、关3=3，每段 1–3 格；
//   · 相邻两段一律直角拐弯 —— 既不回头（北紧跟南），也不原地重复方向；
//   · 三样宝物金币/钻石/皇冠 是一个排列，各出现一次。

import { 走一步, 走多步 } from '/shared/js/罗盘.js';

/** 三个地标的规范名（位置随机，名字与元数据在 环节/宝藏.js） */
export const 地标名们 = ['海盗船', '棕榈树', '大石头'];
/** 三样宝物的规范名（挖到那一格画什么、怎么念都按这套键，见 宝藏.js / 台词表.js） */
export const 宝物名们 = ['金币', '钻石', '皇冠'];
/** 关卡数：段数逐关 +1，一共三关 */
export const 段数们 = [1, 2, 3];
export const 关数 = 段数们.length;

// 挖宝藏只用四个正方向（斜的不参与）。
const 四方 = ['北', '南', '东', '西'];
// 与某方向垂直的两个方向 —— 拐弯只拐直角，既排掉回头（反向），也排掉原地重复（同向）。
const 垂直 = {
  北: ['东', '西'], 南: ['东', '西'],
  东: ['北', '南'], 西: ['北', '南'],
};
const 每段最多 = 3;

// —— 抽签小工具：全部只经手递进来的那个 rng（[0,1)），一个 Math.random 都不藏 ——
const 取整 = (rng, n) => Math.floor(rng() * n);
const 抽 = (rng, 们) => 们[取整(rng, 们.length)];
function 洗(rng, 数组) {
  const 出 = [...数组];
  for (let i = 出.length - 1; i > 0; i--) {
    const j = 取整(rng, i + 1);
    [出[i], 出[j]] = [出[j], 出[i]];
  }
  return 出;
}

const 在界 = (格, 边) => 格.行 >= 0 && 格.行 < 边 && 格.列 >= 0 && 格.列 < 边;

/** 从某格朝某方向、每一步都不出界最多能走几步（封顶 每段最多） */
function 可走步数(格, 方, 边) {
  let 步 = 0;
  let 现 = 格;
  while (步 < 每段最多) {
    现 = 走一步(现, 方);
    if (!在界(现, 边)) break;
    步 += 1;
  }
  return 步; // 0..每段最多
}

/**
 * 从 起格 生成 段数 段的线索。方向按界内可走面 + 直角拐弯挑，步数在可走范围里抽，
 * 所以走出来的每一步天然在界内。
 * @returns {{步们:[方,数][], 目标}|null} 走进死角（没有能走的直角方向）就返回 null，外面重试。
 */
function 生成步们(rng, 起格, 段数, 边) {
  const 步们 = [];
  let 现 = 起格;
  let 上一方 = null;
  for (let s = 0; s < 段数; s++) {
    const 候选方 = 上一方 === null ? 四方 : 垂直[上一方];
    // 洗一下再挑，且这一格朝那儿至少走得动一格
    const 能走 = 洗(rng, 候选方).filter((方) => 可走步数(现, 方, 边) >= 1);
    if (能走.length === 0) return null; // 走进死角，这次作废
    const 方 = 能走[0];
    const 上限 = 可走步数(现, 方, 边); // 1..每段最多
    const 数 = 1 + 取整(rng, 上限); // 1..上限
    步们.push([方, 数]);
    现 = 走多步(现, 方, 数);
    上一方 = 方;
  }
  return { 步们, 目标: 现 };
}

/** 试摊一整张图；哪一步不合意就返回 null，让外层换一手再试 */
function 一次尝试(rng, 边) {
  // 三个地标：从 边×边 个格里随机取三个不同的
  const 全格 = [];
  for (let 行 = 0; 行 < 边; 行++) {
    for (let 列 = 0; 列 < 边; 列++) 全格.push({ 行, 列 });
  }
  const 取三 = 洗(rng, 全格).slice(0, 地标名们.length);
  const 地标位置们 = {};
  地标名们.forEach((名, i) => { 地标位置们[名] = 取三[i]; });
  const 地标键集 = new Set(取三.map((g) => `${g.行},${g.列}`));

  const 宝顺 = 洗(rng, 宝物名们); // 三样宝物的一个随机排列，一关一样

  const 关卡们 = [];
  for (let 关 = 0; 关 < 段数们.length; 关++) {
    const 起 = 抽(rng, 地标名们); // 每关随机挑一个地标当起点（可重复）
    const 起格 = 地标位置们[起];
    const 出 = 生成步们(rng, 起格, 段数们[关], 边);
    if (!出) return null;
    const { 步们, 目标 } = 出;
    const 目标键 = `${目标.行},${目标.列}`;
    // 目标压在任何地标上就作废（起点本身是地标，这条也就顺带管住了「目标≠起点」）
    if (地标键集.has(目标键)) return null;
    if (目标.行 === 起格.行 && 目标.列 === 起格.列) return null; // 冗余一道保险
    关卡们.push({ 起, 步们, 宝: 宝顺[关], 目标 });
  }
  return { 地标位置们, 关卡们 };
}

/** 走完一串 步们 落在哪一格（兜底图算终点用） */
function 算终点(起格, 步们) {
  let 现 = 起格;
  for (const [方, 数] of 步们) 现 = 走多步(现, 方, 数);
  return 现;
}

/**
 * 恒定合法的一张兜底图（边≥4 都装得下）：三角上摆地标，1/2/3 段各拐直角。
 * 上面的随机尝试单次成功率极高，正常永远走不到这儿 —— 它只是把「怎么抽都退不出图」
 * 这条尾巴接住，让 生成藏宝图 是个全函数：不抛错、不死循环、返回的一定合法。
 */
function 兜底藏宝图(边) {
  const 地标位置们 = {
    海盗船: { 行: 0, 列: 0 },
    棕榈树: { 行: 0, 列: 边 - 1 },
    大石头: { 行: 边 - 1, 列: 0 },
  };
  const 关卡们 = [
    { 起: '海盗船', 步们: [['南', 1]] },
    { 起: '棕榈树', 步们: [['南', 1], ['西', 1]] },
    { 起: '大石头', 步们: [['北', 1], ['东', 1], ['北', 1]] },
  ].map((关, i) => ({
    ...关,
    宝: 宝物名们[i],
    目标: 算终点(地标位置们[关.起], 关.步们),
  }));
  return { 地标位置们, 关卡们 };
}

/**
 * 摊一张随机藏宝图。
 * @param {object} [选项]
 * @param {number} [选项.边=5] 沙滩边长（这一讲固定 5，别改）
 * @param {() => number} [选项.rng=Math.random] 抽签的手：浏览器用 Math.random，测试注入确定 rng
 * @returns {{地标位置们:Record<string,{行,列}>, 关卡们:{起,步们,宝,目标}[]}}
 */
export function 生成藏宝图({ 边 = 5, rng = Math.random } = {}) {
  const 上限 = 2000; // 单次成功率高，几手内必成；这个上限纯是「绝不死循环」的封顶
  for (let 试 = 0; 试 < 上限; 试++) {
    const 图 = 一次尝试(rng, 边);
    if (图) return 图;
  }
  return 兜底藏宝图(边); // 理论到不了，但保证有一张合法图退出去
}
