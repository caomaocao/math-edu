// 这一关屏幕上出现的实体（规范名）。九宫格动物阵 + 六道题各自的布景道具；小龙是走过桥板的主角。
// 实体图覆盖测试拿它对账，见 test/实体图覆盖.test.js。
export const 实体们 = [
  '小猫', '小狗', '小兔', '狐狸', '小熊', '熊猫',
  '青蛙', '小鸡', '奶牛', '小龙', '木桥板', '礼物盒',
  '小鸟', '城堡', '冰淇淋', '大山', '气球',
];

const 话 = 台词.Boss;
const 模 = 模板.Boss;

const 四位 = ['上面', '下面', '左边', '右边'];

// 题五那个 3×3 动物阵。放在模块顶上而不是出题函数里，是为了让词表能被 node --test 看见
// —— 漏一个英文说法，孩子在英文课上答对了却判错，那是最难在浏览器里逮到的一种毛病。
const 动物阵 = [
  ['🐱', '小猫', 'cat'], ['🐶', '小狗', 'dog'], ['🐰', '小兔', 'rabbit'],
  ['🦊', '狐狸', 'fox'], ['🐻', '小熊', 'bear'], ['🐼', '熊猫', 'panda'],
  ['🐸', '青蛙', 'frog'], ['🐤', '小鸡', 'chick'], ['🐮', '奶牛', 'cow'],
];
const 阵英名 = Object.fromEntries(动物阵.map(([, 名, 英]) => [名, 英]));
export const 动物阵词表 = 建词表(动物阵.map(([, 名, 英]) => ({ 答: 名, 别名: [], 英 })));

/** 中心格那只 —— 题五永远从它出发，所以它既不是答案，也不该混进干扰项 */
const 出发点 = '小熊';

/**
 * 小龙的两种状态，和各自画成什么样。
 *
 * 「守着桥」还是「认输飞走了」是一件**状态**，从前它就存在 `龙.textContent` 里
 * ——「等于 🐲 就是还没通关」。屏幕上画什么归渲染层管，通关与否不该跟着一张图走。
 *
 * 守桥画的是小龙那张贴纸图；飞走画的是一团烟——它不是一个实体，是「它已经不在了」
 * 这件事的效果字形，跟彩带、星星同类，所以**不出素材**，`名` 留空就走文本节点。
 */
const 龙样 = Object.freeze({
  守桥: { 名: '小龙', 兜底: '🐲' },
  飞走: { 名: null, 兜底: '💨' },
});

/**
 * 题五的四颗备选钮：三只干扰 + 正确答案，**正确答案恰好出现一次**。
 *
 * 干扰池要排掉两只：出发点（孩子刚从它这儿走出来，摆出来只会绕人），
 * 以及**正确答案本身**。漏掉后面这条就是原来那个 bug —— 池子里还留着答案，
 * 从 8 只里抽 3 只，3/8 的概率把它抽成第二颗一模一样的按钮，
 * 孩子点哪颗都判对，但看着像网站出错了。
 *
 * 抽签的那只手从外面递进来，测试才好把它钉死。
 */
export function 凑题五备选(答, 洗 = 洗牌) {
  const 干扰池 = 动物阵.filter(([, 名]) => 名 !== 出发点 && 名 !== 答);
  const 那一格 = 动物阵.find(([, 名]) => 名 === 答);
  return 洗(干扰池)
    .slice(0, 3)
    .map(([图, 名]) => ({ 图, 答: 名 }))
    .concat([{ 图: 那一格[0], 答 }]);
}

export function 创建(面板, 工具) {
  面板.innerHTML = `
    <div class="舞台布">
      <div class="大画框">
        <div class="Boss台" id="Boss台">
          <div class="Boss演区" id="Boss演区"></div>
          <div class="过河桥" id="过河桥"></div>
          <div class="小龙" id="小龙"></div>
        </div>
      </div>
      <div class="进度点挂" id="Boss进度"></div>
    </div>`;
  const 演区 = 面板.querySelector('#Boss演区');
  const 桥 = 面板.querySelector('#过河桥');
  const 龙 = 面板.querySelector('#小龙');
  const 点 = 做进度点(面板.querySelector('#Boss进度'), 6);

  /** 小龙现在是哪种状态；退到第几块桥板由 退 说了算 */
  function 画龙(状态, 退 = 0) {
    const { 名, 兜底 } = 龙样[状态];
    龙.replaceChildren(名
      ? 画实体(名, 兜底, { 类名: '龙图' })
      : document.createTextNode(兜底));
    龙.style.transform = `translateX(${退 * 18}px)`;
  }
  画龙('守桥');

  // 六块桥板：暗的时候是 .桥板 那条 grayscale 滤镜压出来的，亮起来滤镜一撤就上色，
  // 换成贴纸图之后这套明暗照旧管用（滤镜作用在整个元素上，不挑文字还是图片）。
  const 桥板们 = [];
  for (let i = 0; i < 6; i++) {
    const 板 = 元('span', '桥板');
    板.appendChild(画实体('木桥板', '🟫', { 类名: '板图' }));
    桥.appendChild(板);
    桥板们.push(板);
  }

  // 填格 可以还回一个字（⭐ 是 UI 图形，永远保持 emoji），也可以还回一个现成的元素
  // （动物阵、城堡冰淇淋的贴纸图）—— 一格里放什么归出题的那道题说了算，摆格网只管摆。
  function 摆格网(类名, 填格) {
    const 网 = 元('div', `Boss网 ${类名}`);
    for (let 行 = 0; 行 < 3; 行++) {
      for (let 列 = 0; 列 < 3; 列++) {
        const 格 = 元('div', 'Boss格');
        const 填 = 填格(行, 列);
        if (typeof 填 === 'string' || 填 == null) 格.textContent = 填 || '';
        else 格.appendChild(填);
        网.appendChild(格);
      }
    }
    演区.innerHTML = '';
    演区.appendChild(网);
    return 网;
  }

  // 演区上摆一件东西：一大一小配一道方位题（盒子和小鸟、大山和气球）。
  // 类名决定字号盒（.Boss大件 120px / .Boss小件 54px），贴纸图跟着那个盒子一样大。
  function 摆件(类名, 名, 兜底, x, y) {
    const 件 = 元('span', 类名);
    件.appendChild(画实体(名, 兜底, { 类名: `${类名}图` }));
    件.style.left = `${x}%`;
    件.style.top = `${y}%`;
    return 件;
  }

  // ---- 六道题，每道返回一个「出题() → 问答参数」 ----
  //
  // 除了 问答() 认的那几个字段，每道题还多带一个 `答说`：**答案用当前这门课的说法**。
  // 教三次都不会时复述的就是它 —— 六道题的答案分别是方位、行列、动物名，
  // 形状各不相同，台词表那边只认「一个已经挑好语言的词」。

  function 题一方位() {
    const 位 = 洗牌(四位)[0];
    const 摆 = { 上面: [50, 8], 下面: [50, 90], 左边: [12, 50], 右边: [88, 50] };
    演区.innerHTML = '';
    演区.append(
      摆件('Boss大件', '礼物盒', '🎁', 50, 50),
      摆件('Boss小件', '小鸟', '🐦', 摆[位][0], 摆[位][1]),
    );
    return {
      问: 话.题一问,
      接受们: [位],
      答说: 说法(位),
      判: (文) => 判对(文, [位], { 竞争: 四位 }),
      上下文: 热词(四位),
      备选: 四位.map((方) => ({ 图: 牌字(方), 答: 方 })),
    };
  }

  function 题二行列() {
    const 行 = 1 + Math.floor(Math.random() * 3);
    const 列 = 1 + Math.floor(Math.random() * 3);
    摆格网('星星网', (r, c) => (r === 行 - 1 && c === 列 - 1 ? '⭐' : ''));
    return {
      问: 话.题二问,
      接受们: [行列答(行, 列)],
      答说: 选({ cn: `第${行}行第${列}列`, en: `row ${行}, column ${列}` }),
      判: (文) => 判行列(文, 行, 列),
      上下文: 行列上下文,
      提示: async () => 说(话.题二提示),
      备选: [[行, 列], [列, 行], [(行 % 3) + 1, 列]]
        .filter((对, i, 全) => 全.findIndex((x) => x[0] === 对[0] && x[1] === 对[1]) === i)
        .map(([r, c]) => ({ 图: 行列牌(r, c), 答: 行列答(r, c) })),
    };
  }

  function 题三罗盘() {
    const 方 = 洗牌([...八方位])[0];
    演区.innerHTML = `
      <div class="Boss罗盘">
        <span class="小北">${牌字('北')}</span><span class="小南">${牌字('南')}</span>
        <span class="小西">${牌字('西')}</span><span class="小东">${牌字('东')}</span>
        <span class="Boss针" style="transform: translate(-50%,-88%) rotate(${角度[方]}deg)"></span>
      </div>`;
    return {
      问: 话.题三问,
      接受们: [方],
      答说: 说法(方),
      判: (文) => 判对(文, [方], { 竞争: [...八方位] }),
      上下文: 热词([...八方位]),
      提示: async () => 说(话.题三提示),
      备选: 八方位.map((名) => ({ 图: 牌字(名), 答: 名 })),
    };
  }

  function 题四地图() {
    const 角落 = [[0, 0], [0, 1], [0, 2], [1, 0], [1, 2], [2, 0], [2, 1], [2, 2]];
    const [行, 列] = 洗牌(角落)[0];
    const 方 = 相对方位({ 行: 1, 列: 1 }, { 行, 列 });
    // 城堡在正中、冰淇淋在某个角落，孩子说的是「冰淇淋在城堡的哪个方向」——
    // 两样都是布景实体，跟星星网里那颗 ⭐（UI 图形）不同，得画成贴纸图。
    摆格网('城堡网', (r, c) => {
      if (r === 1 && c === 1) return 画实体('城堡', '🏰', { 类名: '堡图' });
      if (r === 行 && c === 列) return 画实体('冰淇淋', '🍦', { 类名: '堡图' });
      return '';
    });
    return {
      问: 话.题四问,
      接受们: [方],
      答说: 说法(方),
      判: (文) => 判对(文, [方], { 竞争: [...八方位] }),
      上下文: 热词([...八方位]),
      提示: async () => 说(话.题四提示),
      备选: 八方位.map((名) => ({ 图: 牌字(名), 答: 名 })),
    };
  }

  function 题五走格子() {
    const 起 = { 行: 1, 列: 1 }; // 从中间的小熊出发，四个方向都有邻居
    const 方 = 洗牌(['北', '南', '西', '东'])[0];
    const 到 = 走一步(起, 方);
    const 答 = 动物阵[到.行 * 3 + 到.列][1];
    摆格网('动物阵', (r, c) => {
      const [图, 名] = 动物阵[r * 3 + c];
      return 画实体(名, 图, { 类名: '阵图' });
    });
    return {
      问: 模.题五问(方),
      接受们: [答],
      答说: 选({ cn: 答, en: 阵英名[答] }),
      判: (文) => 判对(文, [答], { 词表: 动物阵词表 }),
      上下文: 热词(动物阵.map(([, 名]) => 名), 动物阵词表),
      提示: async () => 说(模.题五提示(方)),
      备选: 凑题五备选(答),
    };
  }

  async function 题六记忆() {
    const 位 = 洗牌(四位)[0];
    const 摆 = { 上面: [50, 8], 下面: [50, 90], 左边: [12, 50], 右边: [88, 50] };
    演区.innerHTML = '';
    const 山 = 摆件('Boss大件', '大山', '⛰️', 50, 50);
    const 球 = 摆件('Boss小件', '气球', '🎈', 摆[位][0], 摆[位][1]);
    演区.append(山, 球);
    await 说(话.题六开场);
    await 歇(3000);
    球.remove();
    return {
      问: 话.题六问,
      接受们: [位],
      答说: 说法(位),
      判: (文) => 判对(文, [位], { 竞争: 四位 }),
      上下文: 热词(四位),
      备选: 四位.map((方) => ({ 图: 牌字(方), 答: 方 })),
    };
  }

  let 局 = 0;

  async function 进入() {
    const 本局 = ++局;
    const 还在 = () => 局 === 本局 && 面板.classList.contains('在前');
    点.清零();
    收起麦克风();
    画龙('守桥');
    桥板们.forEach((板) => 板.classList.remove('亮板'));

    await 说(话.开场);
    if (!还在()) return;

    const 出题们 = [题一方位, 题二行列, 题三罗盘, 题四地图, 题五走格子, 题六记忆];
    for (let i = 0; i < 出题们.length; i++) {
      if (!还在()) return;
      // `答说` 原样递进去，不解构掉：答对时 问答() 拿它复述正确的那个词
      // （六道题的答案形状各不相同——方位、行列、动物名——只有这儿知道怎么念）
      const 题 = await 出题们[i]();
      await 问答({
        教: async () => 说(模.教(题.答说)),
        ...题,
      });
      if (!还在()) return;
      桥板们[i].classList.add('亮板');
      音效.星星();
      画龙('守桥', i + 1);
      点.点亮(i);
      if (i < 出题们.length - 1) await 说(模.亮桥板(i + 1));
    }

    // 通关
    画龙('飞走', 出题们.length);
    音效.大烟花();
    await 说(话.通关);
    if (!还在()) return;
    await 工具.完成('Boss');
    if (!还在()) return;
    收起麦克风();
    await 说(话.收尾);
  }

  return { 进入 };
}
