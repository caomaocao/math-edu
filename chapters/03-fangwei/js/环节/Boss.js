// Boss —— 空间大冒险（自创压轴关）。
// 六道混合题搭一座过河桥：方位、行列、罗盘、地图、走格子、记忆各来一道。
// 每答对一块桥板亮起来，小龙往后退一步；全亮了小龙认输飞走，放大烟花！

import { 说 } from '/shared/js/说话.js';
import { 问答, 收起麦克风 } from '/shared/js/问答.js';
import { 判对, 判行列, 建词表, 热词 } from '/shared/js/判对.js';
import { 相对方位, 走一步, 角度, 八方位 } from '/shared/js/罗盘.js';
import { 音效 } from '/shared/js/音效.js';
import { 元, 洗牌, 做进度点, 歇 } from '/shared/js/搭台.js';
