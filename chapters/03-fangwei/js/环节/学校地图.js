// 学校地图 —— 学校旁边有什么（书第 30 页 练一练 的活版）。
// 地图中间是学校，八个方向各有一个地方。上北下南、左西右东的字标在四条边上。
// 自由探索：划到哪念到哪。问答：「学校的东边是什么？」「医院在学校的哪个方向？」

import { 说 } from '/shared/js/说话.js';
import { 问答, 收起麦克风 } from '/shared/js/问答.js';
import { 判对, 建词表, 热词 } from '/shared/js/判对.js';
import { 相对方位, 八方位 } from '/shared/js/罗盘.js';
import { 元, 洗牌, 做进度点 } from '/shared/js/搭台.js';
import { 画实体 } from '/shared/js/实体图.js';
import { 台词, 模板 } from '../台词表.js';
import { 牌字, 名说 } from '../方位词.js';

// 这一关屏幕上出现的实体（规范名）。八个地点是教学实体，学校是地图正中的布景。
// 实体图覆盖测试拿它对账，见 test/实体图覆盖.test.js。
export const 实体们 = [
  '火车站', '加油站', '摩天轮', '马戏团', '公园', '医院',
  '面包店', '消防局', '学校',
];

const 话 = 台词.学校地图;
const 模 = 模板.学校地图;

// 3×3 摆位：行列 → 地点（中间是学校）
const 街坊 = [
  { 名: '火车站', 图: '🚉', 行: 0, 列: 1, 别名: ['车站'], 英: 'train station', 英别名: ['station'] },
  { 名: '加油站', 图: '⛽', 行: 0, 列: 2, 别名: [], 英: 'gas station', 英别名: ['petrol station'] },
  { 名: '摩天轮', 图: '🎡', 行: 1, 列: 2, 别名: ['大转轮', '游乐场'], 英: 'ferris wheel', 英别名: ['big wheel', 'fun fair'] },
  { 名: '马戏团', 图: '🎪', 行: 2, 列: 2, 别名: ['大帐篷'], 英: 'circus', 英别名: ['big tent'] },
  { 名: '公园', 图: '🌳', 行: 2, 列: 1, 别名: ['大树'], 英: 'park', 英别名: ['big tree'] },
  { 名: '医院', 图: '🏥', 行: 2, 列: 0, 别名: [], 英: 'hospital', 英别名: [] },
  { 名: '面包店', 图: '🍞', 行: 1, 列: 0, 别名: ['面包房'], 英: 'bakery', 英别名: ['bread shop'] },
  { 名: '消防局', 图: '🚒', 行: 0, 列: 0, 别名: ['消防车', '消防站'], 英: 'fire station', 英别名: ['fire house'] },
];
const 学校 = { 名: '学校', 图: '🏫', 英: 'school' };
const 学校格 = { 行: 1, 列: 1 };
export const 地点词表 = 建词表(街坊.map(({ 名, 别名, 英, 英别名 }) => ({ 答: 名, 别名, 英: [英, ...英别名] })));

export function 创建(面板, 工具) {
  面板.innerHTML = `
    <div class="舞台布">
      <div class="大画框">
        <div class="街区台" id="街区台">
          <span class="边字 北字" data-方="北"></span>
          <span class="边字 南字" data-方="南"></span>
          <span class="边字 西字" data-方="西"></span>
          <span class="边字 东字" data-方="东"></span>
          <div class="街区网" id="街区网"></div>
        </div>
      </div>
      <div class="进度点挂" id="街区进度"></div>
    </div>`;
  const 网 = 面板.querySelector('#街区网');
  const 点 = 做进度点(面板.querySelector('#街区进度'), 6);

  // 四条边上的教学字（中文课「北」，英文课 NORTH）。空着渲染，字由 换语言() 填 ——
  // 只有这一处出处，开场和切换走的是同一行代码。
  const 边字们 = [...面板.querySelectorAll('.边字')];
  function 换语言() {
    for (const 字 of 边字们) 字.textContent = 牌字(字.dataset.方);
  }
  换语言();

  const 楼们 = {};
  for (let 行 = 0; 行 < 3; 行++) {
    for (let 列 = 0; 列 < 3; 列++) {
      const 格 = 元('div', '街区格');
      const 主 = 行 === 1 && 列 === 1 ? 学校 : 街坊.find((f) => f.行 === 行 && f.列 === 列);
      // 贴纸图和 emoji 同占 60px 的字号盒，格子里的位置一点不动（缺图时回落成 emoji 文本）
      const 楼 = 元('span', '楼图');
      楼.appendChild(画实体(主.名, 主.图, { 类名: '楼实体图' }));
      格.appendChild(楼);
      格.dataset.名 = 主.名;
      网.appendChild(格);
      楼们[主.名] = 格;
      const 方 = 相对方位(学校格, { 行, 列 });
      /*
        pointerenter 而不是 mouseenter：鼠标划过来照旧念，手指按上去也念（触屏上
        pointerenter 就在手指落下那一刻发）。自由探索这一段本来只认鼠标，孩子在手机上
        戳半天一声不响 —— 而这一段不是装饰，是他认清「谁在学校哪一边」的唯一途径。

        这儿能这么改，是因为**格子在探索期没有任何点击动作**：念完就完了，没有下一句来
        打断它。地图上那些关卡节点就不行（主.js 里那句 mouseenter 是**故意**留着的）——
        点一下会进关，进关的第一句话开口就 闭嘴()，孩子只听得到半个词然后被掐掉，
        比不念更糟。有没有「点了之后还会发生别的事」，是这两处的分界线。

        考试时 免打扰 挡住它：手指点楼跟鼠标划过楼一样，都不许把答案念出来。
      */
      格.addEventListener('pointerenter', () => {
        if (格.dataset.免打扰 === '1') return;
        说(方 ? 模.摸到(名说(主), 方) : 话.这是学校);
      });
    }
  }

  function 免打扰(开) {
    for (const 格 of Object.values(楼们)) 格.dataset.免打扰 = 开 ? '1' : '0';
  }

  let 局 = 0;

  async function 进入() {
    const 本局 = ++局;
    const 还在 = () => 局 === 本局 && 面板.classList.contains('在前');
    点.清零();
    /*
      开场白念完之前先按住不响。开场白正是那句「上边是北，下边是南……先一个一个摸一摸」——
      孩子不认字，这是他这一关唯一的说明书，而 说() 是「新话开口、旧话闭嘴」：中途摸到一栋楼，
      说明书就在半句上被掐掉，再也不会重念。
      鼠标时代这个口子理论上也在（手一晃划过一格就断），只是没人会在听指令时把鼠标搁在地图上；
      换成手指之后它变得很容易撞上 —— 孩子的手本来就悬在屏幕上方。
    */
    免打扰(true);

    await 说(话.开场);
    if (!还在()) return;
    免打扰(false); // 说明书念完了，随便摸
    await new Promise((好) => setTimeout(好, 6000)); // 给孩子一小会儿自由探索
    if (!还在()) return;
    免打扰(true); // 考试的时候别把答案念出来

    const 考题 = 洗牌([...街坊]).slice(0, 6);
    for (let i = 0; i < 考题.length; i++) {
      if (!还在()) return;
      const 家 = 考题[i];
      const 方 = 相对方位(学校格, { 行: 家.行, 列: 家.列 });
      const 问地点 = i % 2 === 0;
      if (问地点) {
        await 问答({
          问: 模.问地点(方),
          接受们: [家.名],
          判: (文) => 判对(文, [家.名], { 词表: 地点词表 }),
          上下文: 热词(街坊.map((f) => f.名), 地点词表),
          提示: async () => {
            楼们[家.名].classList.add('提示中');
            await 说(方.length === 1 ? 模.提示单字(方) : 模.提示两字(方));
            setTimeout(() => 楼们[家.名].classList.remove('提示中'), 2600);
          },
          教: async () => 说(模.教地点(方, 名说(家))),
          备选: 洗牌([家, ...洗牌(街坊.filter((f) => f !== 家)).slice(0, 3)]).map((f) => ({ 图: f.图, 答: f.名 })),
        });
      } else {
        楼们[家.名].classList.add('提示中');
        setTimeout(() => 楼们[家.名].classList.remove('提示中'), 2600);
        await 问答({
          问: 模.问方向(名说(家)),
          接受们: [方],
          判: (文) => 判对(文, [方], { 竞争: [...八方位] }),
          上下文: 热词([...八方位]),
          提示: async () => 说(话.提示方向),
          教: async () => 说(模.教方向(名说(家), 方)),
          备选: 八方位.map((名) => ({ 图: 牌字(名), 答: 名 })),
        });
      }
      if (!还在()) return;
      点.点亮(i);
    }

    if (!还在()) return;
    await 工具.完成('学校地图');
    if (!还在()) return;
    收起麦克风();
    await 说(话.收尾);
    /*
      这道闸别省 —— 它护着的正是上面开场那段静音。收尾念到一半孩子走了（或家长切了语言），
      新的一局会先 免打扰(true) 再念开场白；而新话一开口，旧局这个 await 就解开了 ——
      没有这道闸，**旧局**接着跑下面那句 免打扰(false)，等于把新局开场白期的静音当场拆掉，
      刚堵上的「说明书被戳断」原样复发。旧局早退时静音悬在 1 上没关系：进入() 开头会复位。
    */
    if (!还在()) return;
    // 先让它说完，再把地图还给孩子随便摸（同开场那段注释的道理）
    免打扰(false);
  }

  return { 进入, 换语言 };
}
