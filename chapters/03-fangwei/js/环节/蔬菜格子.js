export function 创建(面板, 工具) {
  面板.innerHTML = `
    <div class="舞台布">
      <div class="大画框">
        <div class="冰箱台" id="冰箱台">
          <div class="冰箱" id="冰箱"></div>
        </div>
      </div>
      <div class="进度点挂" id="蔬菜进度"></div>
    </div>`;
  const 台 = 面板.querySelector('#冰箱台');
  const 冰箱 = 面板.querySelector('#冰箱');
  const 点 = 做进度点(面板.querySelector('#蔬菜进度'), 题A.length + 链B.length);

  // 4 行 × 2 列的格子
  const 格们 = {};
  for (let 行 = 1; 行 <= 4; 行++) {
    for (let 列 = 1; 列 <= 2; 列++) {
      const 格 = 元('div', '冰箱格 落点');
      冰箱.appendChild(格);
      格们[`${行},${列}`] = 格;
    }
  }

  // 贴纸只有 56 舞台px（24pt），够不着 44pt 那条线 → 热区不动位 补一圈隐形的可点
  // 范围（外扩量在 styles.css 的 .货员 那儿调到 12px，约 48pt），视觉一个像素不动。
  // 这一关的托盘挤：七样东西中心只隔 43px，本来就互相压着一角。但压的方向是固定的
  // —— 链B 从左往右一件一件放，该拖的那件永远是最左边那件，它的左半边（含中心）
  // 从来没被压住。外扩之后它多得到左边 10px，右边那 10px 本来也不是它的。
  const 员们 = {};
  for (const { 名, 图 } of 货) {
    const 员 = 元('span', '货员 热区不动位');
    员.appendChild(画实体(名, 图, { 类名: '菜图' }));
    员.title = 名;
    台.appendChild(员);
    员们[名] = 员;
  }

  function 各就各位(只留) {
    for (const { 名, 行, 列 } of 货) {
      const 员 = 员们[名];
      员.dataset.锁 = '1';
      员.style.zIndex = 3;
      if (!只留 || 只留.includes(名)) 吸到(员, 格们[`${行},${列}`], 台);
    }
  }

  function 亮一亮(名们) {
    for (const 名 of 名们) {
      员们[名].classList.add('提示中');
      setTimeout(() => 员们[名].classList.remove('提示中'), 2800);
    }
  }

  let 局 = 0;

  async function 进入() {
    const 本局 = ++局;
    const 还在 = () => 局 === 本局 && 面板.classList.contains('在前');
    点.清零();
    await 歇(60); // 等面板摆到前面再量格子的位置
    各就各位();

    await 说(话.开场);
    if (!还在()) return;
    let 做到 = 0;

    // ---------------- 玩法A 问答
    for (const 题 of 题A) {
      if (!还在()) return;
      亮一亮(题.主角);
      const 是方位题 = 题.类 === '方位';
      const 接受们 = 是方位题 ? [题.答] : [题.答名];
      // 答对/答错要复述的那个词，用当前这门课的说法
      const 答说 = 是方位题 ? 说法(接受们[0]) : 名说(找货(接受们[0]));
      await 问答({
        问: 话.题面[题.面],
        接受们,
        判: (文) => (是方位题
          ? 判对(文, 接受们, { 竞争: 四方 })
          : 判对(文, 接受们, { 词表: 食物词表 })),
        上下文: 是方位题 ? 热词(四方) : 热词(货.map((g) => g.名), 食物词表),
        提示: async () => { 亮一亮(题.主角); await 说(是方位题 ? 话.提示方位 : 话.提示食物); },
        教: async () => 说(模.教(答说)),
        备选: 是方位题
          ? 四方.map((方) => ({ 图: 牌字(方), 答: 方 }))
          : 货.filter((g) => [接受们[0], 题.主角[0], '茄子', '白菜'].includes(g.名)).slice(0, 4).map((g) => ({ 图: g.图, 答: g.名 })),
      });
      if (!还在()) return;
      点.点亮(做到++);
    }

    await 说(话.换玩法);
    if (!还在()) return;

    // ---------------- 玩法B 装冰箱：只留鸡蛋，其它排到托盘
    链B.map(({ 名 }) => 名).forEach((名, i) => {
      const 员 = 员们[名];
      员.style.left = `${6 + i * 13.4}%`;
      员.style.top = '103%';
      员.style.zIndex = 9;
    });
    各就各位(['鸡蛋']);
    await 说(话.鸡蛋先放好);

    for (const { 名, 参照, 方 } of 链B) {
      if (!还在()) return;
      const 员 = 员们[名];
      const 参照货 = 货.find((g) => g.名 === 参照);
      const 目标 = 货.find((g) => g.名 === 名);
      const 目标格 = 格们[`${目标.行},${目标.列}`];
      员.dataset.锁 = '0';
      目标格.classList.add('候着');
      await new Promise((好) => {
        装拖(员, 台, (中x, 中y) => {
          const 系数 = 舞台系数();
          for (const [号, 格] of Object.entries(格们)) {
            const 框 = 格.getBoundingClientRect();
            // 中x / 中y 和 框 同是**视觉**坐标，这一比不用换算（搭台.js 的约定）
            if (中x > 框.left && 中x < 框.right && 中y > 框.top && 中y < 框.bottom) {
              if (格 === 目标格) { 好(); return true; }
              // 「这一格已经有人了吗」：谁的左上角离这一格的左上角不到半格，就算在这一格里。
              // 两个 rect 都是视觉坐标，相减出来的距离跟着缩放一起缩，所以要折回舞台单位
              // 再跟格子比 —— 容差取自格子自己的 offsetWidth/Height（那是布局像素，
              // 本来就是舞台单位，不能再除）。原来这儿是个写死的 60：手机上两格中心
              // 只剩 83 视觉px，60 就成了「半格多」，隔壁那格也会被算成占着。
              const 占着 = Object.values(员们).some((别人) => 别人 !== 员 && 别人.dataset.锁 === '1'
                && 落到舞台的长度(Math.abs(别人.getBoundingClientRect().left - 框.left), 系数) < 格.offsetWidth / 2
                && 落到舞台的长度(Math.abs(别人.getBoundingClientRect().top - 框.top), 系数) < 格.offsetHeight / 2);
              音效.答错();
              说(占着 ? 话.格子占着了 : 模.再听一遍(名说(参照货), 方));
              亮一亮([参照]);
              return false;
            }
          }
          return false;
        });
        亮一亮([参照]);
        说(模.指令(名说(目标), 名说(参照货), 方));
      });
      if (!还在()) return;
      吸到(员, 目标格, 台);
      员.dataset.锁 = '1';
      目标格.classList.remove('候着');
      音效.答对();
      员.classList.add('对了');
      setTimeout(() => 员.classList.remove('对了'), 600);
      await 说(话.放对了);
      点.点亮(做到++);
    }

    if (!还在()) return;
    await 工具.完成('蔬菜格子');
    if (!还在()) return;
    收起麦克风();
    await 说(话.收尾);
  }

  return { 进入 };
}
