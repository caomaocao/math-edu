// 方位词 —— 这一讲的教学字符，两语各一份。
//
// 家规里「屏幕上一个句子都没有，只有要学的那几个字」的那几个字，就是这儿的东西。
// 英文课不是「汉字旁边配个英文注释」，而是**同一堂课换一套要认的词**：
// 中文课孩子认的是「北」，英文课认的就是 NORTH —— 屏幕上只出现当前这门课的那一个。
//
// 三件事分开放，别混：
//   · 规范名（这张表的键）永远是中文。判对.js 的词条键、罗盘.js 的 生活对地图、
//     模板函数收到的参数，全都是这套中文规范名。**英文只活在显示层和语音层。**
//     （所以别拿这儿的东西去改罗盘的数学 —— 那边一个字都不用动。）
//   · `方位牌` = 印在屏幕上的样子。英文用大写：这是要认的单词本身，像识字卡。
//   · `方位说` = 念出来的样子。英文用小写自然说法（NORTH 念作 north，「右上」念作
//     upper right）—— TTS 的磁盘缓存键就是这串文本，大小写不统一会白合成两份。

