/**
 * 一条题库数据念给孩子听时用哪个名字。
 *
 * 各环节的题库（班底、货、街坊、住户、站点、客串……）一律是
 * `{ 名: '小松鼠', 英: 'squirrel', … }`：**中文名仍是那条数据的规范名**
 * —— 它同时是 `员们[名]` 的键、`建词表()` 的键、判对的答案，动了到处都要跟着动。
 * 英文只是又一个字段，只在「念出来」和「判对时多认一种说法」这两处露面。
 *
 * 英文一律写光杆名词（squirrel / bakery / palm tree）：冠词由台词表的英文句子加，
 * 塞进数据里的话「the ${名}」就会变成 the the。
 */
export function 名说(条) {
  return 选({ cn: 条.名, en: 条.英 }) ?? 条.名;
}

// ---------------------------------------------------------------------------
// 行与列
// ---------------------------------------------------------------------------

/**
 * 备选钮上那一小块「第几行第几列」。
 *
 * 钮只有指甲盖大，中文两个数字四个字塞得下，英文 "Row 2, Column 3" 塞不下 ——
 * 缩成 R2C3。孩子本来就不认字，这个钮是「听不清两次」之后的救急；
 * 真正要学的 row / column 是嘴里念的，不是钮上印的。
 */
export function 行列牌(行, 列) {
  return 选({ cn: `${行}行${列}列`, en: `R${行}C${列}` });
}

/** 货架旁边那一排行标 / 列标（也是教学字：row 和 column 这两个词） */
export function 行标字(行) {
  return 选({ cn: `第${行}行`, en: `Row ${行}` });
}
export function 列标字(列) {
  return 选({ cn: `第${列}列`, en: `Col ${列}` });
}

/** 备选钮按下去交给判对的那串。**永远是中文规范写法** —— 判行列() 认的就是它 */
export function 行列答(行, 列) {
  return `第${行}行第${列}列`;
}

