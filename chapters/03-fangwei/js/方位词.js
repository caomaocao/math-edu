/** 屏幕上该印哪个字（按当前语言） */
export function 牌字(规范名) {
  return 选(方位牌[规范名]) ?? 规范名;
}

/** 这个方位在某一门课里怎么念（不给语言就按当前语言） */
export function 说法(规范名, 语) {
  const 条 = 方位说[规范名];
  if (!条) return 规范名;
  return 语 ? (条[语] ?? 条.cn) : 选(条);
}

