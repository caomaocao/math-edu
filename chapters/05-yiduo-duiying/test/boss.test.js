import test from 'node:test';
import assert from 'node:assert/strict';

import { 连闯题单, 一排腿数, 满屏排数列, 实体们 } from '../js/站/Boss.js';
import { 站点表 } from '../js/站点表.js';
import { 两语模板 } from '../js/台词表.js';
import { 几个几 } from '../js/站/果盘数数.js';
import { 图清单 } from '/shared/js/实体图.js';

/*
  篝火晚会 Boss（票 08）的纯逻辑：连闯五关的题目生成（换实体不换题型，值从各站题池推得），
  与青蛙彩蛋 40→400 的两串数列。DOM / 动画 / 引擎联动手验，这里只咬「数对不对、族齐不齐、
  彩蛋的每个数都念得出来」——数改歪一处（站点表台账、几个几算术、念大摊）立刻红。
*/

const 账 = 站点表.find((条) => 条.号 === 'Boss').台账;
const 汉字 = /[　-〿一-鿿＀-￯]/;
const 报数顶 = 20; // 本讲报数射程（报数.js 的 射程顶）；连闯与彩蛋里进判对的数都得 ≤ 它

// ── 连闯五关：族齐、顺序对、题面自洽 ─────────────────────────────────────────

test('连闯题单：五关，族与顺序 = 台账 族们（配对/喂食/发饭/几个几/腿数）', () => {
  const 单 = 连闯题单();
  assert.equal(单.length, 5);
  assert.deepEqual(单.map((关) => 关.族), 账.族们);
});

test('连闯·配对：3 对，两侧颜色各不重复且成套，归宿素材名 = 色+帐篷', () => {
  const 关 = 连闯题单()[0];
  assert.equal(关.动物们.length, 3);
  assert.equal(关.归宿们.length, 3);
  const 动色 = 关.动物们.map((a) => a.色);
  const 宿色 = 关.归宿们.map((h) => h.色);
  assert.equal(new Set(动色).size, 3, '同侧颜色不许重复（色就是配对答案）');
  assert.equal(new Set(宿色).size, 3);
  assert.deepEqual([...动色].sort(), [...宿色].sort(), '两侧颜色要成套，才配得成');
  for (const h of 关.归宿们) assert.equal(h.名, `${h.色}帐篷`);
});

test('连闯·喂食：一格 2 条鱼、3 格，头一格是示范——总数换皮不换型', () => {
  const 关 = 连闯题单()[1];
  assert.equal(关.实体, '小鱼');
  assert.equal(关.每, 2);
  assert.equal(关.格数, 3);
  assert.equal(关.每 * 关.格数, 6);
});

test('连闯·发饭：共能被每人整除、发到锅空正好 = 答，排队的比吃上的多', () => {
  const 关 = 连闯题单()[2];
  assert.equal(关.共 % 关.每人, 0, '发到锅空要正好分完');
  assert.equal(关.共 / 关.每人, 关.答);
  assert.ok(关.答 > 0);
});

test('连闯·几个几：答从 果盘数数.几个几() 现算（横着数一排几个），不硬编码第二份', () => {
  const 关 = 连闯题单()[3];
  assert.equal(关.答, 几个几(关.排数, 关.每排, '横').每份);
  assert.equal(关.答, 关.每排); // 横着数一排 = 每排
});

test('连闯·腿数：答 = 腿 × 只数', () => {
  const 关 = 连闯题单()[4];
  assert.equal(关.答, 关.腿 * 关.只数);
});

test('连闯：所有走判对的数（报数关的答 + 彩蛋的青蛙腿）都在报数射程内（≤20）', () => {
  const 单 = 连闯题单();
  assert.ok(单[3].答 <= 报数顶, '几个几关的答超出报数射程');
  assert.ok(单[4].答 <= 报数顶, '腿数关的答超出报数射程');
  assert.ok(账.彩蛋.腿 <= 报数顶, '彩蛋 Phase A 的青蛙腿数超出报数射程');
});

// ── 青蛙彩蛋：40→400 的两串数列 ───────────────────────────────────────────────

test('一排腿数：10 只青蛙带数到 40（4、8、…、40）', () => {
  const { 腿, 一排 } = 账.彩蛋;
  const 串 = 一排腿数(腿, 一排);
  assert.equal(串.length, 一排);
  assert.deepEqual(串, [4, 8, 12, 16, 20, 24, 28, 32, 36, 40]);
  assert.equal(串.at(-1), 腿 * 一排);
});

test('满屏排数列：十排一排一声 40、80、…、400，末位 = 台账 顶', () => {
  const { 腿, 一排, 排数, 顶 } = 账.彩蛋;
  const 串 = 满屏排数列(腿, 一排, 排数);
  assert.equal(串.length, 排数);
  assert.deepEqual(串, [40, 80, 120, 160, 200, 240, 280, 320, 360, 400]);
  assert.equal(串.at(-1), 顶);
  assert.equal(顶, 腿 * 一排 * 排数);
  串.forEach((v, r) => assert.equal(v, 腿 * 一排 * (r + 1)));
});

test('模板.Boss.念大：满屏排数列每个数在两门课都念得出（>99 也不落空，英文无汉字）', () => {
  const { 腿, 一排, 排数 } = 账.彩蛋;
  for (const n of 满屏排数列(腿, 一排, 排数)) {
    const 中 = 两语模板.cn.Boss.念大(n);
    const 英 = 两语模板.en.Boss.念大(n);
    assert.ok(中 && 中.trim() && 中 !== String(n), `中文没给 ${n} 的念法（落到了裸数字兜底）`);
    assert.ok(英 && 英.trim() && 英 !== String(n), `英文没给 ${n} 的念法`);
    assert.equal(汉字.test(英), false, `英文课 ${n} 的念法夹汉字：${英}`);
  }
});

