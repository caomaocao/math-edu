import test from 'node:test';
import assert from 'node:assert/strict';

import { 几个几, 实体们 as 果实体们 } from '../js/站/果盘数数.js';
import { 逐只腿数, 实体们 as 腿实体们 } from '../js/站/腿腿站.js';
import { 站点表 } from '../js/站点表.js';
import { 两语台词, 两语模板 } from '../js/台词表.js';

/*
  票 07 的两站：果盘数数（几个几，横竖两问）+ 腿腿站（腿数报数）。
  这里咬三件事：
    1. 几个几 / 逐只腿数 的纯算术 —— 两问的答案、说破的口径、按只带数那串数；
    2. 站数据与台账一致 —— 实体们、盘开场每盘一句、每种动物都有自己的模板；
    3. 两语话术的口径 —— 英文「几个几」钉死 "N groups of M"，中文量词位的 2 念「两」。
  台词两表键同构、英文表无汉字由 台词表.test.js 统管，这儿只管票 07 自己的口径。
*/

const 汉字 = /[　-〿一-鿿＀-￯]/;
const 果账 = 站点表.find((条) => 条.号 === '果盘数数').台账;
const 腿账 = 站点表.find((条) => 条.号 === '腿腿站').台账;

// ── 几个几：行列换算纯逻辑 ────────────────────────────────────────────────────

test('几个几：台账三盘的横竖两问各自对得上，两个方向总数相等', () => {
  for (const { 排数, 每排 } of 果账.盘们) {
    const 横 = 几个几(排数, 每排, '横');
    const 竖 = 几个几(排数, 每排, '竖');
    assert.equal(横.每份, 每排, '横着数，一排有几个 = 每排');
    assert.equal(横.份数, 排数, '有几排 = 排数');
    assert.equal(竖.每份, 排数, '竖着数，一列有几个 = 排数');
    assert.equal(竖.份数, 每排, '有几列 = 每排');
    assert.equal(横.总, 排数 * 每排);
    assert.equal(横.总, 竖.总, '横着数竖着数一样多——这一站教的就是这件事');
  }
});

test('几个几：樱桃 3×6 手算钉死——横着数 3 个 6，竖着数 6 个 3', () => {
  assert.deepEqual(几个几(3, 6, '横'), { 每份: 6, 份数: 3, 总: 18 });
  assert.deepEqual(几个几(3, 6, '竖'), { 每份: 3, 份数: 6, 总: 18 });
});

// ── 逐只腿数：按只带数那串 ────────────────────────────────────────────────────

test('逐只腿数：小鸡 2、4、6、8、10；小猪 4、8、12、16——末位就是台账的答', () => {
  assert.deepEqual(逐只腿数(2, 5), [2, 4, 6, 8, 10]);
  assert.deepEqual(逐只腿数(4, 4), [4, 8, 12, 16]);
  for (const 题 of 腿账.题们) {
    const 数列 = 逐只腿数(题.腿, 题.只数);
    assert.equal(数列.length, 题.只数, `「${题.物}」一只念一声，声数 = 只数`);
    assert.equal(数列.at(-1), 题.答, `「${题.物}」数到最后一只就是答案`);
  }
});

// ── 站数据与台账一致 ─────────────────────────────────────────────────────────

test('实体们：两站各自导出台账里的实体，顺序也一致', () => {
  assert.deepEqual(果实体们, ['苹果', '橘子', '樱桃']);
  assert.deepEqual(腿实体们, ['小鸡', '小猪']);
  assert.deepEqual(果实体们, 果账.盘们.map((盘) => 盘.果));
  assert.deepEqual(腿实体们, 腿账.题们.map((题) => 题.物));
});

test('果盘数数：盘开场每盘一句，两语都齐', () => {
  for (const 语 of ['cn', 'en']) {
    assert.equal(两语台词[语].果盘数数.盘开场们.length, 果账.盘们.length,
      `${语} 课的盘开场要一盘一句`);
  }
});

test('腿腿站：台账里的每种动物都有自己的开场与问的模板', () => {
  for (const 语 of ['cn', 'en']) {
    for (const 题 of 腿账.题们) {
      assert.equal(typeof 两语模板[语].腿腿站[`${题.物}开场`], 'function',
        `${语} 课缺「${题.物}开场」模板`);
      assert.equal(typeof 两语模板[语].腿腿站[`${题.物}问`], 'function',
        `${语} 课缺「${题.物}问」模板`);
    }
  }
});

// ── 两语话术口径 ─────────────────────────────────────────────────────────────

test('英文「几个几」口径钉死为 groups of', () => {
  assert.match(两语模板.en.果盘数数.横破(3, 6), /three groups of six/);
  assert.match(两语模板.en.果盘数数.竖破(6, 3), /six groups of three/);
});

test('模板成句：英文无汉字（台账里会出现的实参逐个过）', () => {
  const 英果 = 两语模板.en.果盘数数;
  const 英腿 = 两语模板.en.腿腿站;
  const 样句们 = [];
  for (const { 排数, 每排 } of 果账.盘们) {
    样句们.push(英果.排里破(每排), 英果.几排破(排数),
      英果.横破(排数, 每排), 英果.竖破(每排, 排数));
  }
  for (const 题 of 腿账.题们) {
    样句们.push(英腿[`${题.物}开场`](题.腿), 英腿[`${题.物}问`](题.只数));
  }
  for (const 句 of 样句们) {
    assert.equal(typeof 句, 'string');
    assert.ok(句.trim());
    assert.equal(汉字.test(句), false, `英文课这一句夹着中文：${句}`);
  }
});

test('中文说破：量词位的 2 念「两」，纯数位照用数词（三个六 / 两个三）', () => {
  const 中果 = 两语模板.cn.果盘数数;
  assert.ok(中果.横破(3, 6).includes('三个六'), 中果.横破(3, 6));
  assert.ok(中果.竖破(6, 3).includes('六个三'), 中果.竖破(6, 3));
  assert.ok(中果.横破(2, 3).includes('两个三'), '苹果盘横着数是「两个三」，不是「二个三」');
  assert.ok(中果.几排破(2).includes('两排'), '「两排」不是「二排」');
  assert.ok(两语模板.cn.腿腿站.小鸡开场(2).includes('两条腿'), '「两条腿」不是「二条腿」');
});
