import test from 'node:test';
import assert from 'node:assert/strict';

import { 开局, 点动物, 点归宿, 空归宿们, 剩余对, 全配好 } from '../js/配对.js';
import { 实体们, 配对阵 } from '../js/站/帐篷站.js';
import { 图清单 } from '/shared/js/实体图.js';

/*
  配对引擎（票 04）的纯逻辑：状态机 + 剩余项推演。DOM 与动画手验，这里只咬判定——
  判定纯本地（颜色相等），三次机会梯子的级数，以及演示走的那份推演单。
  末尾还替帐篷站咬两笔账：实体们 全员有图（覆盖接缝），四动物四色对得上 03 票的定案。
*/

const 四动物 = [
  { 名: '青蛙', 色: '绿' },
  { 名: '瓢虫', 色: '红' },
  { 名: '小鸟', 色: '蓝' },
  { 名: '小熊', 色: '棕' },
];
const 四帐篷 = [
  { 名: '绿帐篷', 色: '绿' },
  { 名: '红帐篷', 色: '红' },
  { 名: '蓝帐篷', 色: '蓝' },
  { 名: '棕帐篷', 色: '棕' },
];
const 开一局 = () => 开局({ 动物们: 四动物, 归宿们: 四帐篷 });

// ── 开局 ────────────────────────────────────────────────────────────────────

test('开局：干净的局——没选中、没配好、没错过', () => {
  const 局 = 开一局();
  assert.equal(局.选中, null);
  assert.deepEqual(局.配好, {});
  assert.equal(局.错次, 0);
});

test('开局：配错阵就地炸（数量不齐 / 同侧重色 / 两侧颜色对不上）', () => {
  assert.throws(() => 开局({ 动物们: 四动物, 归宿们: 四帐篷.slice(0, 3) }));
  assert.throws(() => 开局({ 动物们: [], 归宿们: [] }));
  assert.throws(() => 开局({
    动物们: [{ 名: '甲', 色: '绿' }, { 名: '乙', 色: '绿' }],
    归宿们: [{ 名: '丙', 色: '绿' }, { 名: '丁', 色: '红' }],
  }));
  assert.throws(() => 开局({
    动物们: [{ 名: '甲', 色: '绿' }, { 名: '乙', 色: '红' }],
    归宿们: [{ 名: '丙', 色: '绿' }, { 名: '丁', 色: '蓝' }],
  }));
});

// ── 点动物 ──────────────────────────────────────────────────────────────────

test('点动物：选中它；换点另一只就换选', () => {
  let { 局, 动作 } = 点动物(开一局(), '青蛙');
  assert.equal(动作, '选中');
  assert.equal(局.选中, '青蛙');
  ({ 局, 动作 } = 点动物(局, '小熊'));
  assert.equal(动作, '选中');
  assert.equal(局.选中, '小熊');
});

test('点动物：不认识的、已安家的一律没理', () => {
  const 局 = 开一局();
  assert.equal(点动物(局, '恐龙').动作, '没理');
  const 安了家 = 点归宿(点动物(局, '青蛙').局, '绿帐篷').局;
  const 果 = 点动物(安了家, '青蛙');
  assert.equal(果.动作, '没理');
  assert.equal(果.局.选中, null);
});

// ── 点归宿：判定就是颜色相等 ─────────────────────────────────────────────────

test('点归宿：没选中实体时点归宿不算答题，也不计错', () => {
  const 果 = 点归宿(开一局(), '绿帐篷');
  assert.equal(果.动作, '没理');
  assert.equal(果.局.错次, 0);
});

test('点归宿：颜色相等 → 安家，配好记上、选中清空、错次不动', () => {
  const 果 = 点归宿(点动物(开一局(), '青蛙').局, '绿帐篷');
  assert.equal(果.动作, '安家');
  assert.equal(果.动物, '青蛙');
  assert.equal(果.归宿, '绿帐篷');
  assert.equal(果.局.配好.青蛙, '绿帐篷');
  assert.equal(果.局.选中, null);
  assert.equal(果.局.错次, 0);
});

test('点归宿：颜色不等 → 摇头，错次 +1，选中保留让孩子接着试', () => {
  const 果 = 点归宿(点动物(开一局(), '青蛙').局, '红帐篷');
  assert.equal(果.动作, '摇头');
  assert.equal(果.局.错次, 1);
  assert.equal(果.局.选中, '青蛙');
  assert.deepEqual(果.局.配好, {});
});

test('点归宿：有主的归宿再点是没理，不计错', () => {
  const 安了 = 点归宿(点动物(开一局(), '青蛙').局, '绿帐篷').局;
  const 果 = 点归宿(点动物(安了, '瓢虫').局, '绿帐篷');
  assert.equal(果.动作, '没理');
  assert.equal(果.局.错次, 0);
});

// ── 三次机会梯子 ────────────────────────────────────────────────────────────

test('梯子：连错三次的梯级是 1（鼓励）→ 2（提示）→ 3（演示），封顶 3', () => {
  let 局 = 点动物(开一局(), '青蛙').局;
  const 级们 = [];
  for (let i = 0; i < 4; i += 1) {
    const 果 = 点归宿(局, '红帐篷');
    局 = 果.局;
    级们.push(果.梯级);
  }
  assert.deepEqual(级们, [1, 2, 3, 3]);
  assert.equal(局.错次, 4);
});

test('梯子：错次跨实体累计——换一只接着错，梯子接着爬', () => {
  let 局 = 点归宿(点动物(开一局(), '青蛙').局, '红帐篷').局; // 错 1
  const 果 = 点归宿(点动物(局, '小鸟').局, '棕帐篷'); // 换只再错
  assert.equal(果.梯级, 2);
});

// ── 剩余项推演（演示照它走）与收官 ───────────────────────────────────────────

test('剩余对：开局四对色色对应；配掉两对剩两对；占了的归宿不再进单', () => {
  let 局 = 开一局();
  assert.deepEqual(剩余对(局), [
    { 动物: '青蛙', 归宿: '绿帐篷' },
    { 动物: '瓢虫', 归宿: '红帐篷' },
    { 动物: '小鸟', 归宿: '蓝帐篷' },
    { 动物: '小熊', 归宿: '棕帐篷' },
  ]);
  局 = 点归宿(点动物(局, '青蛙').局, '绿帐篷').局;
  局 = 点归宿(点动物(局, '小熊').局, '棕帐篷').局;
  assert.deepEqual(剩余对(局), [
    { 动物: '瓢虫', 归宿: '红帐篷' },
    { 动物: '小鸟', 归宿: '蓝帐篷' },
  ]);
  assert.deepEqual(空归宿们(局).map((h) => h.名), ['红帐篷', '蓝帐篷']);
});

test('全配好：亲手配完四对为真；照剩余对推演走（演示的路）每步都是安家，走完也为真', () => {
  let 局 = 开一局();
  assert.equal(全配好(局), false);
  // 先错三次进演示（梯子第三级），再照推演单走
  局 = 点动物(局, '青蛙').局;
  for (let i = 0; i < 3; i += 1) 局 = 点归宿(局, '红帐篷').局;
  for (const { 动物, 归宿 } of 剩余对(局)) {
    const 果 = 点归宿(点动物(局, 动物).局, 归宿);
    assert.equal(果.动作, '安家', `演示走到 ${动物}→${归宿} 该是安家`);
    局 = 果.局;
  }
  assert.equal(全配好(局), true);
  assert.deepEqual(剩余对(局), []);
});

test('reducer 不改旧局：点过之后旧局原样', () => {
  const 局 = 开一局();
  const 照 = JSON.stringify(局);
  点动物(局, '青蛙');
  点归宿(点动物(局, '青蛙').局, '红帐篷');
  assert.equal(JSON.stringify(局), 照);
});

// ── 替帐篷站咬的两笔账 ───────────────────────────────────────────────────────

test('帐篷站.配对阵：四动物四色与 03 票定案一字不差', () => {
  assert.deepEqual(
    配对阵.map(({ 名, 色 }) => `${名}-${色}`),
    ['青蛙-绿', '瓢虫-红', '小鸟-蓝', '小熊-棕'],
  );
});

test('帐篷站.实体们：四动物 + 四色帐篷 + 四色雨伞共 12 个，个个有图（覆盖接缝）', () => {
  assert.equal(new Set(实体们).size, 12);
  for (const 色 of ['绿', '红', '蓝', '棕']) {
    assert.ok(实体们.includes(`${色}帐篷`), `实体们里缺 ${色}帐篷`);
    assert.ok(实体们.includes(`${色}雨伞`), `实体们里缺 ${色}雨伞`);
  }
  // 图清单 会丢掉没图的实体——一个都不许丢（03 票的图全部已入库）
  assert.equal(图清单(实体们).length, 12, '实体们里有素材还没入库的名字');
});
