// 熊猫竹林 —— 书第 53 页 例2 的活版（一多对应 1:2）。
// 三只熊猫每只吃两根竹子：第一只已经拿到两根（书上的示范，也是错2提示「一组一组数过去」
// 的那组「已给」——全空的话梯子第二档就没东西可数），孩子给另外两只喂（共享摆放引擎，
// 容器=熊猫），摇开饭铃交卷 → 转报数「一共吃了几根」→ 6 → 答对后**换位演示**（只演不考）：
// 每只熊猫左手的竹子逐根亮 1-2-3、右手再亮 1-2-3，语音说破「3+3 也是 6」。
//
// 题面数值一律从 站点表.js 的台账读（摆放题() 现场推导），不许在这儿硬编码第二份 ——
// test/一多三站.test.js 拿台账逐项咬。
// 换位步子 / 带数序列 / 带数着亮 是一多对应三站共用的小逻辑，家在头一站，
// 兔子草地 / 喂食站 从这儿 import，别抄第二份（共享件「两份必漂移」的家规）。

import { 说 } from '/shared/js/说话.js';
import { 收起麦克风 } from '/shared/js/问答.js';
import { 玩一轮 } from '/shared/js/摆放.js';
import { 画实体 } from '/shared/js/实体图.js';
import { 选 } from '/shared/js/语言.js';
import { 中文数, 英文数 } from '/shared/js/数词.js';
import { 元, 歇 } from '/shared/js/搭台.js';
import { 报一个数 } from '../报数.js';
import { 台词, 模板 } from '../台词表.js';
import { 摆放配 } from '../组件.js';
import { 站点表 } from '../站点表.js';

export const 实体们 = ['熊猫', '竹子'];

const 账 = 站点表.find((条) => 条.号 === '熊猫竹林').台账;
const 话 = 台词.熊猫竹林;

// ---------------------------------------------------------------- 纯逻辑（node --test 咬这几口）

/** 这个数在当前这门课里怎么念（六 / six）。三站的带数、换位报数都用它。 */
export const 念数 = (n) => 选({ cn: 中文数(n), en: 英文数(n) });

/**
 * 摆放题() —— 递给共享摆放引擎的题（形状见 /shared/js/摆放.js 头注）。
 * 从台账现场推导：每只熊猫 每只 根，共 只数 格；第 0 格是书上的示范（已给），
 * 其余空着等孩子摆。
 */
export function 摆放题() {
  return {
    实体: '竹子',
    兜底: '🎋',
    排布: '横',
    值们: Array(账.只数).fill(账.每只),
    空: Array.from({ length: 账.只数 - 1 }, (_, i) => i + 1),
  };
}

/**
 * 换位步子([甲, 乙]) —— 换位演示的亮灯序列：先把「左手」那一撮逐个点亮（数 1..甲），
 * 再把「右手」那一撮逐个点亮（数 1..乙）。纯数据，怎么亮、亮哪个元素由各站自己接。
 */
export function 换位步子([甲, 乙]) {
  const 出 = [];
  for (let k = 1; k <= 甲; k += 1) 出.push({ 侧: 0, 第几: k });
  for (let k = 1; k <= 乙; k += 1) 出.push({ 侧: 1, 第几: k });
  return 出;
}

/** 带数序列(每只, 只数) —— 按只带着数的那串数：2、4、6……（报数错2提示的词）。 */
export function 带数序列(每只, 只数) {
  return Array.from({ length: 只数 }, (_, i) => 每只 * (i + 1));
}

/** 报数错2的提示动作：把一组组容器挨个高亮、带着数过去（2、4、6……）。三站共用。 */
export async function 带数着亮(格们, 数们, 还在 = () => true) {
  for (const [i, 格] of 格们.entries()) {
    if (!还在()) return;
    格.classList.add('提示中');
    await 说(念数(数们[i]));
    格.classList.remove('提示中');
  }
}

// ---------------------------------------------------------------- 站

export function 创建(面板, 工具) {
  面板.innerHTML = `
    <div class="舞台布">
      <div class="大画框"><div class="摆放挂点 竹林台"></div></div>
    </div>`;
  const 挂 = 面板.querySelector('.摆放挂点');
  let 局 = 0;

  async function 进入() {
    const 本局 = ++局;
    const 还在 = () => 局 === 本局 && 面板.classList.contains('在前');

    // 先把台子摆出来再开口（摆放站的先例：空框像卡住了），但念完话之前闸是关的——
    // 孩子抢在开场白里连摇三下铃，三次机会梯子会在题目念完前自动演完（04 评审抓过的雷）。
    let 闸开 = false;
    const 一轮 = 玩一轮({ 挂点: 挂, 题: 摆放题(), 配: 摆放配, 走查: () => 闸开 && 还在() });

    // 装扮引擎搭好的台：每个摆格头上站一只熊猫（容器=熊猫——点熊猫这一格就是喂它），
    // 交卷键接上通用营地部件的开饭铃皮（引擎的钩子叫 .提交钮，长相账在 styles.css 通用段）。
    const 格们 = [...挂.querySelectorAll('.摆格')];
    for (const 格 of 格们) {
      const 头 = 元('div', '熊猫头位');
      头.append(画实体('熊猫', '🐼', { 类名: '熊猫图' }));
      格.prepend(头);
    }
    const 铃 = 挂.querySelector('.提交钮');
    铃.classList.add('开饭铃');

    await 说(话.开场);
    if (!还在()) return;
    await 说(话.动手);
    if (!还在()) return;
    闸开 = true;
    await 一轮;
    if (!还在()) return;
    铃.disabled = true; // 交完卷的铃不再响应，别让孩子按一个没反应的大按钮（防呆）

    // 转报数：一共吃了几根 → 答（错2提示 = 把三只熊猫的竹子两根两根带着数）
    await 报一个数(账.答, {
      问: 话.问几根,
      提示: async () => {
        await 说(话.带数头);
        await 带数着亮(格们, 带数序列(账.每只, 账.只数), 还在);
      },
    });
    if (!还在()) return;
    收起麦克风();

    // 换位演示（只演不考，本站的灵魂）：每只熊猫手里两根竹子，先把每只的第一根
    // （左手）逐根亮 1-2-3，再把第二根（右手）亮 1-2-3，最后说破 3+3 也是 6。
    await 说(话.换位头);
    if (!还在()) return;
    const 亮过 = [];
    for (const { 侧, 第几 } of 换位步子(账.换位)) {
      if (!还在()) return;
      const 件 = 格们[第几 - 1]?.querySelectorAll('.摆件图, .摆件形')[侧];
      if (件) {
        件.classList.add(侧 === 0 ? '换位亮甲' : '换位亮乙');
        亮过.push(件);
      }
      工具.音效.点一下();
      await 说(念数(第几));
    }
    await 说(模板.熊猫竹林.换位说破(账.换位[0], 账.换位[1], 账.答));
    if (!还在()) return;
    await 歇(600);
    for (const 件 of 亮过) 件.classList.remove('换位亮甲', '换位亮乙');

    await 工具.完成('熊猫竹林');
    if (!还在()) return;
    await 说(话.收尾);
  }

  return { 进入 };
}
