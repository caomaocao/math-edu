// 喂食站 —— 书第 56 页 闯关一 的活版，两轮：
// ⑴ 狗骨头 1:1——三群 2/3/4 只小狗各配一个食盘，孩子往盘里摆对应根数的骨头
//    （第一群已给两根当示范，兼作错2提示「一组一组数过去」的那组「已给」）；
// ⑵ 企鹅鱼 1:2——四只企鹅各喂两条小鱼（第一只已给示范）→ 摇开饭铃 →
//    转报数「一共几条」→ 8。
// 轮次进度走 工具.记/取（落「柜」，跟星星一起存、同步、被重来清）：轮⑴做完记 1，
// 中途离开再进直接从企鹅轮续；整站完成记回 0，下次重玩从头。
//
// 题面数值从 站点表.js 的台账读（狗骨头题 / 企鹅题 现场推导），不许硬编码第二份；
// 带数序列 / 带数着亮 / 念数 从 熊猫竹林.js import（三站共用，家在头一站）。

import { 说 } from '/shared/js/说话.js';
import { 收起麦克风 } from '/shared/js/问答.js';
import { 玩一轮 } from '/shared/js/摆放.js';
import { 画实体 } from '/shared/js/实体图.js';
import { 元, 做进度点 } from '/shared/js/搭台.js';
import { 报一个数 } from '../报数.js';
import { 台词 } from '../台词表.js';
import { 摆放配 } from '../组件.js';
import { 站点表 } from '../站点表.js';
import { 带数序列, 带数着亮 } from './熊猫竹林.js';

export const 实体们 = ['小狗', '骨头', '企鹅', '小鱼'];

const 账 = 站点表.find((条) => 条.号 === '喂食站').台账;
const 话 = 台词.喂食站;
const 轮格 = '喂食站轮'; // 柜里的格名：0 = 从头，1 = 狗骨头轮已过、从企鹅轮续

// ---------------------------------------------------------------- 纯逻辑（node --test 咬这几口）

/** 轮⑴的摆放题：1:1——每群的骨头数 = 狗数 × 每只(1)。第 0 群是示范（已给）。 */
export function 狗骨头题() {
  const { 每只, 狗数们 } = 账.狗骨头;
  return {
    实体: '骨头',
    兜底: '🦴',
    排布: '横',
    值们: 狗数们.map((狗) => 狗 * 每只),
    空: Array.from({ length: 狗数们.length - 1 }, (_, i) => i + 1),
  };
}

/** 轮⑵的摆放题：1:2——每只企鹅 每只 条鱼，共 只数 格。第 0 只是示范（已给）。 */
export function 企鹅题() {
  const { 每只, 只数 } = 账.企鹅鱼;
  return {
    实体: '小鱼',
    兜底: '🐟',
    排布: '横',
    值们: Array(只数).fill(每只),
    空: Array.from({ length: 只数 - 1 }, (_, i) => i + 1),
  };
}

// ---------------------------------------------------------------- 站

export function 创建(面板, 工具) {
  面板.innerHTML = `
    <div class="舞台布">
      <div class="大画框"><div class="摆放挂点 喂食台"></div></div>
      <div class="进度点挂"></div>
    </div>`;
  const 挂 = 面板.querySelector('.摆放挂点');
  const 点 = 做进度点(面板.querySelector('.进度点挂'), 2);
  let 局 = 0;

  /**
   * 开一轮摆放：搭台（闸关着）→ 给每个摆格装上「谁在等饭」的头（狗群/企鹅）→
   * 铃接开饭铃皮 → 念开场词们 → 开闸放手。resolve 时把 {格们, 铃} 交回去
   * （企鹅轮的报数提示还要拿格们接着亮）。
   */
  async function 开一轮({ 题, 装头, 词们, 还在 }) {
    let 闸开 = false;
    const 一轮 = 玩一轮({ 挂点: 挂, 题, 配: 摆放配, 走查: () => 闸开 && 还在() });
    const 格们 = [...挂.querySelectorAll('.摆格')];
    格们.forEach(装头);
    const 铃 = 挂.querySelector('.提交钮');
    铃.classList.add('开饭铃');
    for (const 词 of 词们) {
      await 说(词);
      if (!还在()) return null;
    }
    闸开 = true;
    await 一轮;
    if (!还在()) return null;
    return { 格们, 铃 };
  }

  async function 进入() {
    const 本局 = ++局;
    const 还在 = () => 局 === 本局 && 面板.classList.contains('在前');
    const 从企鹅续 = 工具.取(轮格) === 1;
    点.清零();
    if (从企鹅续) 点.点亮(0);

    if (!从企鹅续) {
      // 轮⑴ 狗骨头 1:1：每格头上蹲一群小狗（2/3/4 只），盘里摆对应根数
      const 过了 = await 开一轮({
        题: 狗骨头题(),
        装头: (格, i) => {
          const 头 = 元('div', '狗群位');
          for (let k = 0; k < 账.狗骨头.狗数们[i]; k += 1) {
            头.append(画实体('小狗', '🐶', { 类名: '狗图' }));
          }
          格.prepend(头);
        },
        词们: [话.开场, 话.狗动手],
        还在,
      });
      if (!过了) return;
      点.点亮(0);
      工具.记(轮格, 1);
    }

    // 轮⑵ 企鹅鱼 1:2：每格头上站一只企鹅，各喂两条
    const 企鹅轮 = await 开一轮({
      题: 企鹅题(),
      装头: (格) => {
        const 头 = 元('div', '企鹅位');
        头.append(画实体('企鹅', '🐧', { 类名: '企鹅图' }));
        格.prepend(头);
      },
      词们: [话.企鹅开场],
      还在,
    });
    if (!企鹅轮) return;
    企鹅轮.铃.disabled = true; // 交完卷的铃不再响应（防呆，同熊猫竹林）
    点.点亮(1);

    // 转报数：一共几条小鱼 → 答（错2提示 = 两条两条带着数企鹅的鱼）
    await 报一个数(账.企鹅鱼.答, {
      问: 话.问几条,
      提示: async () => {
        await 说(话.带数头);
        await 带数着亮(企鹅轮.格们, 带数序列(账.企鹅鱼.每只, 账.企鹅鱼.只数), 还在);
      },
    });
    if (!还在()) return;
    收起麦克风();

    工具.记(轮格, 0); // 整站走完，下次重玩从头
    await 工具.完成('喂食站');
    if (!还在()) return;
    await 说(话.收尾);
  }

  return { 进入 };
}
