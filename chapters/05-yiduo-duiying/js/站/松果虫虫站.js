// 松果虫虫站 —— 正反混练三轮（书 p57 闯关二；数值已由票 06 对裁图逐格核准，台账在
// 站点表，这儿不背数）：⑴ 松鼠 1:3 松果，正向摆松果；⑵ 反向 4 骨头配 1 狗，摆小狗；
// ⑶ 3 毛毛虫配 1 鸡，摆公鸡（素材名 公鸡）。
// 摆放走共享引擎（配 = 组件.js 的 摆放配，开饭铃提交）；每格头顶那块「题眼牌」
// （几只松鼠 / 几根骨头）是本站自己贴的 —— 引擎只认一种摆件，谁提示谁是站点层的事。
// 每轮第 0 格是样例格（书上的示范：1 鼠 3 果 / 4 骨 1 狗 / 3 虫 1 鸡），引擎错 2 的
// 「一组一组数过去」正好落在它头上；反向轮另配提示（票面）：把食物按每只的份圈亮
// 分堆 —— 题眼牌里的骨头/毛毛虫本来就按每只的份扎成小堆，提示那一刻挨堆点亮。

import { 说 } from '/shared/js/说话.js';
import { 做进度点, 歇 } from '/shared/js/搭台.js';
import { 玩一轮 } from '/shared/js/摆放.js';
import { 台词 } from '../台词表.js';
import { 摆放配 } from '../组件.js';
import { 站点表 } from '../站点表.js';
import { 造贴 } from '../发饭.js';

export const 实体们 = ['松鼠', '松果', '骨头', '小狗', '毛毛虫', '公鸡'];

const 账面 = 站点表.find((条) => 条.号 === '松果虫虫站').台账;

/**
 * 排轮们(小题们) —— 台账三小题 → 三轮 玩一轮 的题面 + 题眼牌（纯函数，测试咬台账一致）。
 * 每轮四格：第 0 格样例（已给），后三格空着要孩子摆。
 *   标 = 题眼牌（格头顶的提示实体）：数们 是每格几个；每堆 > 0 就按每只的份扎堆（反向轮）。
 *   题 = 交给共享摆放引擎的格子（实体 = 孩子要摆的那样东西）。
 */
export function 排轮们(小题们) {
  const [松鼠, 骨头, 毛毛虫] = 小题们;
  return [
    {
      话键: '松鼠轮', 反向: false,
      标: { 实体: '松鼠', 兜底: '🐿️', 数们: [1, ...松鼠.只数们], 每堆: 0 },
      题: { 实体: '松果', 兜底: '🌰', 值们: [松鼠.每只, ...松鼠.答们], 空: [1, 2, 3] },
    },
    {
      话键: '骨头轮', 反向: true,
      标: { 实体: '骨头', 兜底: '🦴', 数们: [骨头.每只, ...骨头.根数们], 每堆: 骨头.每只 },
      题: { 实体: '小狗', 兜底: '🐶', 值们: [1, ...骨头.答们], 空: [1, 2, 3] },
    },
    {
      话键: '毛毛虫轮', 反向: true,
      标: { 实体: '毛毛虫', 兜底: '🐛', 数们: [毛毛虫.每只, ...毛毛虫.条数们], 每堆: 毛毛虫.每只 },
      题: { 实体: '公鸡', 兜底: '🐓', 值们: [1, ...毛毛虫.答们], 空: [1, 2, 3] },
    },
  ];
}

/** 玩一轮把格子摆好后（executor 同步建 DOM），给每格贴题眼牌、标出样例格，
 * 再让开饭铃穿上通用段的衣裳（引擎只给 .提交钮 这个钩子）。 */
function 上标牌(挂, 标) {
  挂.querySelectorAll('.摆格').forEach((格, i) => {
    if (i === 0) 格.classList.add('样例格');
    const 牌 = document.createElement('div');
    牌.className = '题眼牌';
    const n = 标.数们[i];
    if (标.每堆 > 0) {
      for (let 起 = 0; 起 < n; 起 += 标.每堆) {
        const 堆 = document.createElement('span');
        堆.className = '题眼堆';
        for (let k = 起; k < Math.min(起 + 标.每堆, n); k += 1) {
          堆.appendChild(造贴(标.实体, 标.兜底, '题眼图'));
        }
        牌.appendChild(堆);
      }
    } else {
      for (let k = 0; k < n; k += 1) 牌.appendChild(造贴(标.实体, 标.兜底, '题眼图'));
    }
    格.prepend(牌);
  });
  挂.querySelector('.提交钮')?.classList.add('开饭铃');
}

/** 反向轮错 2：提示头被引擎叫到的那一刻起跑，把空格题眼牌里的食物堆挨个圈亮。
 * 不 await —— 句子照说，点亮是给眼睛的伴奏（提示头得同步还句子给引擎）。 */
function 圈亮分堆(挂, 还在) {
  (async () => {
    for (const 堆 of 挂.querySelectorAll('.摆格.可摆 .题眼堆')) {
      if (!还在()) return;
      堆.classList.add('提示中');
      await 歇(650);
      堆.classList.remove('提示中');
    }
  })();
}

export function 创建(面板, 工具) {
  面板.innerHTML = `
    <div class="舞台布">
      <div class="大画框 虫站框"><div class="虫站挂点"></div></div>
      <div class="进度点挂"></div>
    </div>`;
  const 挂 = 面板.querySelector('.虫站挂点');
  const 轮们 = 排轮们(账面.小题们);
  const 点 = 做进度点(面板.querySelector('.进度点挂'), 轮们.length);
  let 局 = 0;

  async function 进入() {
    const 本局 = ++局;
    const 还在 = () => 局 === 本局 && 面板.classList.contains('在前');
    const 话 = 台词.松果虫虫站;
    点.清零();

    // 轮次进度落柜（同分饭站）：玩到第几轮记第几轮，整站玩完归零当复习。
    let 起 = 工具.取('松果虫虫站轮');
    if (!Number.isInteger(起) || 起 < 0 || 起 >= 轮们.length) 起 = 0;
    for (let i = 0; i < 起; i += 1) 点.点亮(i);

    for (let i = 起; i < 轮们.length; i += 1) {
      if (!还在()) return;
      const 轮 = 轮们[i];
      let 闸开 = false;
      // 反向轮换掉提示头：句子换成「分堆」的话，捎带把题眼牌挨堆点亮（引擎没有
      // 提示的注入口，提示头这个函数被叫到的那一刻就是错 2 的时机 —— 借它一用）。
      const 配 = 轮.反向
        ? { ...摆放配, 话术: { ...摆放配.话术, 提示头: () => { 圈亮分堆(挂, 还在); return 台词.松果虫虫站.分堆提示; } } }
        : 摆放配;
      // 先摆台子再开口、念完才开闸（04 摆放站的先例：防抢跑把梯子烧光）。
      const 局内 = 玩一轮({ 挂点: 挂, 题: { ...轮.题, 排布: '横' }, 配, 走查: () => 闸开 && 还在() });
      上标牌(挂, 轮.标);
      if (i === 起) { await 说(话.开场); if (!还在()) return; }
      await 说(话[轮.话键]);
      if (!还在()) return;
      闸开 = true;
      await 局内;
      if (!还在()) return;
      点.点亮(i);
      工具.记('松果虫虫站轮', (i + 1) % 轮们.length);
    }

    if (!还在()) return;
    await 工具.完成('松果虫虫站');
    if (!还在()) return;
    await 说(话.收尾);
  }

  return { 进入 };
}
