def 生成(key: str, 提示词: str, size: str = "2048*2048", 负面: str = 默认负面) -> bytes:
    body = {
        "model": 模型,
        "input": {"messages": [{"role": "user", "content": [{"text": 提示词}]}]},
        "parameters": {
            "size": size,
            "n": 1,
            "watermark": False,
            # 关掉智能改写：统一风格靠我们自己的提示词模板，改写器只会带来漂移
            "prompt_extend": False,
            "seed": 42,
            "negative_prompt": 负面,
        },
    }
    resp = httpx.post(
        端点,
        headers={"Authorization": f"Bearer {key}", "Content-Type": "application/json"},
        json=body,
        timeout=300,
    )
    resp.raise_for_status()
    data = resp.json()
    图url = data["output"]["choices"][0]["message"]["content"][0]["image"]
    图 = httpx.get(图url, timeout=120)
    图.raise_for_status()
    return 图.content


def 跑一批(key: str, 出目录: Path, 任务, 收尾提示: str = "") -> None:
    """任务 = 可迭代的 (文件名, 提示词, size, 负面)。已有文件跳过；单张失败不拦整批、收尾统一报。
    实体批和全景批共用这一个循环——只差文件名/提示词/负面词/目录。"""
    出目录.mkdir(parents=True, exist_ok=True)
    失败 = []
    for 文件名, 提示词, size, 负面 in 任务:
        文件 = 出目录 / 文件名
        if 文件.exists():
            print(f"跳过（已有）: {文件.name}")
            continue
        print(f"生成中: {文件.name} …", flush=True)
        try:
            文件.write_bytes(生成(key, 提示词, size, 负面))
            print(f"  完成 ({文件.stat().st_size // 1024} KB)")
        except Exception as e:  # noqa: BLE001 —— 单张失败不拦整批
            失败.append((文件.name, str(e)))
            print(f"  失败: {e}")
        time.sleep(间隔秒)
    if 收尾提示:
        print(f"\n{收尾提示}")
    if 失败:
        print("\n以下没成，重跑脚本会只补这些（已有的会跳过）：")
        for 名字, 错 in 失败:
            print(f"  {名字}: {错}")
        sys.exit(1)
    print(f"\n全部完成 → {出目录}")


