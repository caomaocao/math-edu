# -*- coding: utf-8 -*-
"""把生成的「篮子」白底图裁成第4讲蘑菇站要的那种**带篮口的敞口托篮**，落进 assets/实体图/。

为什么篮子不走 tools/抠白底.py 那条标准线（正方 256、整只抠出来）：
  · 文生图**总给篮子画一根高高的提手**（提示词求了「不要提手」也拦不住这个先验），
    整只抠出来是个近正方、带拱形提手的篮子。蘑菇站要把「已摘的小蘑菇」排成**一行**
    卧进篮口（数列 1 2 4 7 → 11 16 得从左往右读得出差递增），提手纯是干扰。
  · 所以从**绳箍那一圈往下**取（篮口 + 内壁 + 前壁），只去掉提手和提手上方的空档。
    留住整个**敞口**是关键：小蘑菇坐进篮口的空腔里、伞盖冒出前沿绳箍，才读得出「在篮子里」；
    早先只取前壁那一薄条（上切 1185）没有篮口，蘑菇只能贴在一堵深壁的外面，
    看着像挂在墙上、被大篮身**遮住**（用户桌面反馈「篮子把蘑菇遮挡了」）——现在从 620 起裁。

这一张的落盘尺寸**非正方**（约 1024×620，宽高比 ~1.65），是本仓库里唯一一张宽扁素材；
渲染在 styles.css 的 .蘑菇篮框/.篮图 里按这个宽高比给尺寸，不要用 画实体 的方形 尺寸。
出宽给到 1024 而非早先的 680：蘑菇站在 16″ MBP 上篮子显示约 430 舞台px，430×系数×dpr 顶到近
千设备像素，680 会糊。

用法（仓库根，先 `生成实体图.py 第4讲美化` 出好 篮子.png）：
    uv run python tools/裁篮子.py
"""

from pathlib import Path

from PIL import Image

from 抠白底 import 洪泛白底

仓库根 = Path(__file__).resolve().parent.parent
源 = 仓库根 / ".scratch" / "entity-art" / "第4讲美化" / "篮子.png"
目标 = 仓库根 / "web" / "shared" / "assets" / "实体图" / "篮子.webp"

上切 = 620    # 2048 高的原图里，从这一行往下是「绳箍篮口 + 内壁 + 前壁」的敞口托篮；
              # 以上只剩提手和空档，全不要。左右和底不用切：洪泛把白底抠透明后 getbbox 自会贴住内容。
出宽 = 1024


def main() -> None:
    if not 源.exists():
        raise SystemExit(f"没找到 {源}——先跑 uv run python tools/生成实体图.py 第4讲美化")
    图 = Image.open(源).convert("RGBA")
    图 = 图.crop((0, 上切, 图.width, 图.height))
    洪泛白底(图)
    图 = 图.crop(图.getbbox())
    宽, 高 = 图.size
    图 = 图.resize((出宽, round(高 * 出宽 / 宽)), Image.LANCZOS)
    图.save(目标, "WEBP", quality=90)
    print(f"{源.name} → {目标.relative_to(仓库根)} {图.size} ({目标.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
